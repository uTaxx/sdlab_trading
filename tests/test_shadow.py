def _비교들(차이들: list[float]):
    줄들 = []
    for i, ㄷ in enumerate(차이들):
        날 = 오늘 - timedelta(days=i)
        줄들.append(_잰줄(날, "3개월", "지금것", 0.0, 지금것=True, 자리=9))
        줄들.append(_잰줄(날, "3개월", "후보", ㄷ, 제안것=True, 자리=1))
    return 비교하기(줄들)


def test_나은_회차와_못한_회차를_따로_센다():
    ㅇ = 모아보기(_비교들([3.0, -1.0, -2.0, 0.0]))
    assert (ㅇ.표본수, ㅇ.나은수, ㅇ.못한수, ㅇ.같은수) == (4, 1, 2, 1)
    assert ㅇ.중앙값차이 == pytest.approx(-0.5)


def test_표본이_모자라면_판단하지_않는다고_적는다():
    글 = 학습글(모아보기(_비교들([1.0, 2.0])))
    assert "판단하지" in 글
