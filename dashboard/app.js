  /* 마지막 변경일로부터 며칠 지났나. 못 세면 null이다.

     **연결이 때에서 해를 버리고 보낸다**("09-03 08:20"). 좁은 칸에 넣으려고
     그렇게 해 둔 것이라 여기서 해를 도로 붙여야 한다. 그냥 파싱하면 값이
     NaN이 되고, 그러면 30일 안내가 조용히 안 뜬다.

     붙인 해가 미래로 나오면 지난해 것이다. 연말연시에 그렇게 된다. */
  function 지난날수(날짜글) {
    const 글 = String(날짜글 || "").trim();
    if (!글) return null;
    const 짧은것 = /^(\d{2})-(\d{2})/.exec(글);
    const 긴것 = /^(\d{4})-(\d{2})-(\d{2})/.exec(글);
    let ㄱ;
    if (긴것) {
      ㄱ = new Date(Number(긴것[1]), Number(긴것[2]) - 1, Number(긴것[3]));
    } else if (짧은것) {
      const 올해 = new Date().getFullYear();
      ㄱ = new Date(올해, Number(짧은것[1]) - 1, Number(짧은것[2]));
      if (ㄱ - new Date() > 0) ㄱ.setFullYear(올해 - 1);
    } else {
      return null;
    }
    if (Number.isNaN(ㄱ.getTime())) return null;
    return Math.floor((new Date() - ㄱ) / (1000 * 60 * 60 * 24));
  }

