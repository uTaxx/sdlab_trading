def _읽는칸번호(창구: str, 무엇: str) -> dict[str, int]:
    """`if (무엇 === "전략추적") { ... }` 안의 `이름: 값(ㅈ, 3)`을 모은다."""
    시작 = 창구.index(f'무엇 === "{무엇}"')
    끝 = 창구.index("\n}", 시작)
    안 = 창구[시작:끝]
    나온것 = {}
    # `이름: 값(ㅈ,3)`, `이름: 수(값(ㅈ,3))`, `이름: 때(값(ㅈ,3))` 셋 다 잡는다.
    for 이름, 번호 in re.findall(r"([가-힣]+):\s*(?:[가-힣]+\()?값\(ㅈ,\s*(\d+)\)", 안):
        나온것[이름] = int(번호)
    return 나온것


def _스크립트머리(경로: str, 이름: str) -> list[str]:
    import importlib.util
    import sys

    길 = 뿌리 / "scripts" / 경로
    스펙 = importlib.util.spec_from_file_location(f"{경로}_for_fields", 길)
    모듈 = importlib.util.module_from_spec(스펙)
    sys.modules[f"{경로}_for_fields"] = 모듈
    스펙.loader.exec_module(모듈)
    return list(getattr(모듈, 이름))


def test_전략추적_칸번호가_파이썬_머리와_맞는다():
    """**한 칸만 밀려도 표의 모든 줄이 어긋난다.** 그런데 화면은 멀쩡히
    그려진다. 수익률 칸에 거래 수가 들어가 있어도 숫자라서 안 보인다."""
    머리 = _스크립트머리("run_strategy_review.py", "추적머리")
    쓰는이름 = {
        "제안일": "제안일", "잰날": "잰날", "지난날수": "지난날수",
        "구간": "구간", "전략": "전략", "자리": "자리",
        "제안시수익률": "제안시수익률%", "뒤수익률": "뒤수익률%",
        "뒤거래수": "뒤거래수", "상태": "상태",
    }
    번호표 = _읽는칸번호(_창구(), "전략추적")
    for 창구이름, 시트이름 in 쓰는이름.items():
        assert 창구이름 in 번호표, f"창구가 {창구이름}을 안 읽습니다"
        assert 번호표[창구이름] == 머리.index(시트이름), (
            f"{창구이름}이 {번호표[창구이름]}번인데 시트에서는 "
            f"{머리.index(시트이름)}번입니다"
        )


