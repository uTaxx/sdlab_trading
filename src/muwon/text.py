"""앞말의 받침을 보고 조사를 고른다.

## 왜 한 곳에 두나

전략 이름이 설정에서 오므로 무엇이 올지 모른다. 그래서 조사를 글자로 박으면
"변동성 돌파이 앞섭니다", "변동성 돌파으로 확정" 같은 문장이 나온다. 둘 다
실제로 나왔던 것이다.

같은 함수를 분석 쪽과 알림 쪽이 따로 두면 한쪽만 고치게 된다. 두 곳 어디에도
안 딸린 자리에 두고 양쪽이 가져다 쓴다.

한글이 아니면(영문 키가 그대로 나오는 경우) 받침 없는 쪽으로 둔다. 둘 중
하나는 골라야 하고, "volume_surge_3d가"가 "volume_surge_3d이"보다 낫다.
"""

from __future__ import annotations

#: 받침이 ㄹ이면 "으로"가 아니라 "로"를 쓴다. "서울으로"는 안 읽힌다.
_리을 = 8

#: 숫자로 끝나는 이름이 실제로 있다("골든크로스 20/60"). 읽는 소리를 보고
#: 받침을 정한다. 0으로 끝나면 십·백·천·만으로 읽혀 받침이 있다.
_숫자받침 = {
    "0": 1, "1": _리을, "2": 0, "3": 1, "4": 0,
    "5": 0, "6": 1, "7": _리을, "8": _리을, "9": 0,
}


def _받침(말: str) -> int | None:
    """마지막 글자의 받침 번호. 0이면 받침 없음, 한글도 숫자도 아니면 None."""
    끝 = (말 or "").strip()[-1:]
    if not 끝:
        return None
    if 끝 in _숫자받침:
        return _숫자받침[끝]
    if not ("가" <= 끝 <= "힣"):
        return None
    return (ord(끝) - 0xAC00) % 28


def 조사(말: str, 받침있을때: str, 받침없을때: str) -> str:
    ㅂ = _받침(말)
    if ㅂ is None:
        return 받침없을때
    return 받침있을때 if ㅂ else 받침없을때


def 이가(말: str) -> str:
    return 조사(말, "이", "가")


def 은는(말: str) -> str:
    return 조사(말, "은", "는")


def 을를(말: str) -> str:
    return 조사(말, "을", "를")


def 으로로(말: str) -> str:
    """받침이 없거나 ㄹ이면 "로", 나머지는 "으로"다."""
    ㅂ = _받침(말)
    if ㅂ is None or ㅂ == 0 or ㅂ == _리을:
        return "로"
    return "으로"
