"""장 마감 뒤 체결 재조회의 판단을 고정한다.

여기가 틀리면 **기록이 조용히 어긋난다.** 화면에는 아무 일도 없어 보이고,
손절이 엉뚱한 자리에 걸린 것은 값이 빠진 뒤에야 드러난다.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date

from muwon.execution.fill_settle import 보유맞추기, 주문고침, 주문맞추기

오늘 = date(2026, 8, 25)


@dataclass
class _체결:
    ordered_quantity: int
    filled_quantity: int
    avg_fill_price: float


@dataclass
class _보유:
    symbol: str
    quantity: int
    entry_price: float
    entry_date: date


@dataclass
class _계좌:
    symbol: str
    quantity: int


def _주문(order_id="A1", symbol="066970", 수량=4, 체결가=118300.0, 판단가=121600.0):
    return (order_id, symbol, 수량, 체결가, 판단가)


# ── 주문 맞추기 ────────────────────────────────────────────────


def test_최종_체결로_수량과_값을_바로잡는다():
    """오늘 실제로 난 일: 12주가 다 체결됐는데 기록엔 4주였다."""
    고침 = 주문맞추기([_주문()], lambda _: _체결(12, 12, 118500.0))

    assert len(고침) == 1
    assert (고침[0].옛수량, 고침[0].새수량) == (4, 12)
    assert 고침[0].새체결가 == 118500.0
    assert 고침[0].바뀌나


def test_조회에서_안_나오면_건드리지_않는다():
    """**모르는 것을 0으로 덮으면 안 된다.** 체결된 주문이 조회에서 잠깐
    빠졌다고 수량을 0으로 만들면 보유가 통째로 사라진다."""
    assert 주문맞추기([_주문()], lambda _: None) == []


def test_체결수량이_0이면_건드리지_않는다():
    """미체결로 취소된 주문이다. 기록을 0으로 덮는 것은 지우는 판단이라
    여기서 할 일이 아니다."""
    assert 주문맞추기([_주문()], lambda _: _체결(12, 0, 0.0)) == []


def test_바뀐_게_없으면_바뀌나가_거짓이다():
    """평소에는 다 채워져서 고칠 것이 없다. 그때 '고쳤다'고 하면 안 된다."""
    고침 = 주문맞추기([_주문(수량=12)], lambda _: _체결(12, 12, 118300.0))

    assert not 고침[0].바뀌나


def test_평균가를_못_받으면_옛값을_지킨다():
    """0으로 덮으면 슬리피지 통계에 0원 체결이라는 헛값이 들어간다."""
    고침 = 주문맞추기([_주문()], lambda _: _체결(12, 12, 0.0))

    assert 고침[0].새체결가 == 118300.0


def test_슬리피지는_판단가_대비다():
    """이 저장소의 실측 표본이 여기서 나온다."""
    ㅈ = 주문고침("A", "066970", 4, 12, 118300.0, 118500.0, 판단가=121600.0)

    assert ㅈ.슬리피지 == (118500.0 - 121600.0) / 121600.0


def test_판단가를_모르면_슬리피지는_0이다():
    """나눗셈이 터지면 그날 마감 처리가 통째로 멈춘다."""
    assert 주문고침("A", "X", 1, 1, 100.0, 100.0, 판단가=0.0).슬리피지 == 0.0


# ── 보유 맞추기 ────────────────────────────────────────────────


def test_수량은_언제나_계좌가_이긴다():
    고칠것, _ = 보유맞추기(
        {"066970": _보유("066970", 4, 118300.0, 오늘)},
        [_계좌("066970", 12)],
        [],
        오늘,
    )

    assert (고칠것[0].옛수량, 고칠것[0].새수량) == (4, 12)


def test_오늘_산_것의_진입가를_최종_평균가로_옮긴다():
    """첫 조각 값이 진입가로 남으면 **손절선이 엉뚱한 자리에 걸린다.**"""
    고침 = 주문맞추기([_주문()], lambda _: _체결(12, 12, 118500.0))
    고칠것, _ = 보유맞추기(
        {"066970": _보유("066970", 4, 118300.0, 오늘)}, [_계좌("066970", 12)], 고침, 오늘
    )

    assert 고칠것[0].새진입가 == 118500.0


def test_어제_산_것의_진입가는_안_건드린다():
    고침 = 주문맞추기([_주문()], lambda _: _체결(12, 12, 118500.0))
    고칠것, _ = 보유맞추기(
        {"066970": _보유("066970", 12, 100000.0, date(2026, 8, 20))},
        [_계좌("066970", 12)], 고침, 오늘,
    )

    assert 고칠것[0].새진입가 == 100000.0


def test_한_종목을_여러_번_샀으면_진입가를_안_건드린다():
    """평균을 어떻게 잡을지가 따로 판단이다. 모르면 안 건드리는 쪽이 맞다."""
    고침 = 주문맞추기(
        [_주문("A1"), _주문("A2")],
        lambda oid: _체결(6, 6, 118000.0 if oid == "A1" else 119000.0),
    )
    고칠것, _ = 보유맞추기(
        {"066970": _보유("066970", 6, 118300.0, 오늘)}, [_계좌("066970", 12)], 고침, 오늘
    )

    assert 고칠것[0].새진입가 == 118300.0
    assert 고칠것[0].새수량 == 12  # 수량은 그래도 계좌를 따른다


def test_계좌에_없는_종목은_안_지운다():
    """이미 팔렸을 수도 있지만 조회가 늦은 것일 수도 있다. 매일 자동으로
    도는 자리에 지우는 권한까지 주면 위험하다."""
    고칠것, 모르는것 = 보유맞추기(
        {"066970": _보유("066970", 12, 118300.0, 오늘)}, [], [], 오늘
    )

    assert 고칠것 == []
    assert 모르는것 == []


def test_계좌에만_있는_종목은_알리되_안_들인다():
    """들이는 판단은 adopt_holdings의 것이다. 진입일을 사람이 줘야 한다."""
    고칠것, 모르는것 = 보유맞추기({}, [_계좌("000660", 5)], [], 오늘)

    assert 고칠것 == []
    assert 모르는것 == ["000660"]
