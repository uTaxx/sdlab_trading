  function 중앙값(값들) {
    if (!값들.length) return null;
    const ㄱ = [...값들].sort((a, b) => a - b);
    const 가운데 = Math.floor(ㄱ.length / 2);
    return ㄱ.length % 2 ? ㄱ[가운데] : (ㄱ[가운데 - 1] + ㄱ[가운데]) / 2;
  }

