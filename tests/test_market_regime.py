"""날짜마다 상승·조정·하락을 가르는 자리를 본다.

## 여기서 꼭 잡아야 하는 것

**미래를 보면 안 된다.** 뒤를 보고 "여기가 바닥이었다"고 이름 붙이면
백테스트가 실제보다 좋게 나오고, 그 사실이 화면에 아무 표시도 안 남는다.

**경계에서 하루 단위로 뒤집히면 안 된다.** 실제 코스피에서 겪었다.
2021년 가을에 상승과 조정이 열 번 넘게 갈렸고 1거래일짜리 구간이 여럿
나왔다. 그렇게 나뉜 구간으로 성적을 모으면 표본이 뜻 없이 잘게 쪼개진다.

**모르는 것을 상승으로 채우면 안 된다.** 자료가 모자라 판정 못 한 것과
실제로 오르는 장은 다르다.
"""

from __future__ import annotations

from datetime import date

import pandas as pd
import pytest

from muwon.analysis import market_regime as ㄱ


def _시세(값들: list[float], 시작="2021-01-04") -> pd.DataFrame:
    날들 = pd.bdate_range(시작, periods=len(값들))
    return pd.DataFrame({"trade_date": [ㅈ.date() for ㅈ in 날들], "close": 값들})


def _쭉(값: float, 몇: int) -> list[float]:
    return [값] * 몇


