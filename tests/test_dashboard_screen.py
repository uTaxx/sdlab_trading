def test_일정표가_n8n_시계와_같은_수다():
    """화면에 6개만 있고 실제로 8개가 돌던 적이 있다(2026-09-01에 고침).
    n8n에 트리거를 더하면 여기도 더해야 한다.

    시각은 화면에 그대로 적히므로 여기서 값을 고정한다. n8n을 고치면
    이 시험이 먼저 빨개진다."""
    import re

    평일 = set(re.findall(r'\["(\d\d:\d\d(?:~\d\d:\d\d)?)", "', 글))
    주말 = set(re.findall(r'\["(토 \d\d:\d\d)", "', 글))
    assert 평일 == {
        "08:20", "08:30", "09:00~15:20", "09:05",
        "15:40", "17:30", "17:40", "17:50", "20:00",
    }, sorted(평일)
    assert 주말 == {"토 09:00"}, sorted(주말)


