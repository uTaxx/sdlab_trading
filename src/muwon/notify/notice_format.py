"""텔레그램으로 나가는 글의 모양을 한 곳에서 정한다.

부르는 쪽에서는 `모양`이라는 이름으로 쓴다.

## 왜 한 곳인가

체결 알림이 세 자리에서 만들어진다. 하루 한 번 도는 엔진, 장중에 도는
엔진, 그리고 저녁에 실제 체결로 맞추는 정산 스크립트다. 각자 문장을 쓰면
같은 일을 세 가지 말투로 알리게 되고, 하나를 고칠 때 나머지를 빠뜨린다.
실제로 장중 알림만 `종목:`으로 적고 나머지는 문장으로 적고 있었다.

## 모양

**라벨과 값을 콜론으로 가른다.** 문장으로 풀어 쓰면 읽는 사람이 매번
문장을 해석해서 숫자를 찾아야 한다. 알림은 훑어보는 글이라, 찾는 값이
언제나 같은 자리에 있어야 한다.

    🟢 매수체결
    한국전력(015760)

    수량 : 43주
    단가 : 33,581원/주
    매수총액 : 1,443,983원

**텔레그램에는 표가 없다.** 자리를 맞추려고 공백을 넣어도 폰의 글꼴이
글자마다 폭이 달라서 안 맞는다. 그래서 라벨 길이를 맞추지 않는다.

**굵게·기울임 표시를 쓰지 않는다.** 이 저장소는 텔레그램 글에
`parse_mode`를 HTML로만 켜 두었고, 그건 링크 하나를 걸기 위한 것이다.
`**굵게**`를 적으면 별표가 그대로 도착한다.
"""

from __future__ import annotations


def 돈(값: float) -> str:
    return f"{값:,.0f}원"


def 주(수: int) -> str:
    return f"{수:,}주"


def 단가(값: float) -> str:
    """1주 값. 총액과 헷갈리지 않게 단위를 붙인다.

    예전 글에는 `가격: 118,300원`만 있었다. 1주 값인지 전부 합친 값인지
    알 수 없었다."""
    return f"{돈(값)}/주"


def 칸(라벨: str, 값: str) -> str:
    return f"{라벨} : {값}"


def 여러값(라벨: str, 값들: list[str]) -> list[str]:
    """값이 여럿인 칸.

    하나면 한 줄로 둔다. 여럿이면 라벨만 남기고 아래에 점으로 나열한다.
    한 줄에 쉼표로 이으면 조건 셋이 '그리고'인지 '또는'인지 알 수 없다."""
    값들 = [ㄱ for ㄱ in 값들 if ㄱ]
    if not 값들:
        return []
    if len(값들) == 1:
        return [칸(라벨, 값들[0])]
    return [라벨, *[f"  · {ㄱ}" for ㄱ in 값들]]


def 머리(아이콘: str, 무슨일: str, 이름: str, 종목코드: str) -> list[str]:
    """알림 맨 위 두 줄과 빈 줄.

    종목명을 반드시 같이 적는다. 종목코드만으로는 무슨 주식인지 알 수
    없다는 말을 받은 적이 있다."""
    return [f"{아이콘} {무슨일}", f"{이름}({종목코드})", ""]


def 글(줄들: list[str]) -> str:
    """빈 줄이 이어지거나 맨 끝에 남는 것을 정리해서 잇는다.

    조건에 따라 빠지는 줄이 있어서, 그냥 이으면 빈 줄이 둘씩 생긴다."""
    나온것: list[str] = []
    for 줄 in 줄들:
        if 줄 == "" and (not 나온것 or 나온것[-1] == ""):
            continue
        나온것.append(줄)
    while 나온것 and 나온것[-1] == "":
        나온것.pop()
    return "\n".join(나온것)


def 수량칸(order) -> str:
    """수량 한 줄. 부분 체결이면 주문·체결·잔여를 같이 적는다.

    부분 체결은 사고가 아니라 흔한 일이다. 그래서 경보를 걸지 않고 사실만
    적는다. 잔여는 대개 그날 안에 마저 채워지거나 장 마감에 취소된다."""
    남은것 = getattr(order, "잔여", 0)
    if not 남은것:
        return 칸("수량", 주(order.quantity))
    return 칸(
        "수량",
        f"{주(order.quantity)} "
        f"(주문 {주(order.ordered_quantity)} 중 체결, 잔여 {주(남은것)})",
    )


