def test_텔레그램에_안_먹는_기호를_안_쓴다():
    """send_message에 parse_mode를 안 준다. `**굵게**`가 그대로 도착한다."""
    assert "**" not in 매수알림("A", "1", _주문(), "이유", 손절비율=-0.05)
    assert "**" not in 매도알림("A", "1", _주문(OrderSide.SELL), "손절", 진입가=100.0)


def test_종목명과_코드를_같이_적는다():
    """코드만 있으면 무슨 주식인지 모르고, 이름만 있으면 확인할 수가 없다."""
    assert "엘앤에프(066970)" in 매수알림("엘앤에프", "066970", _주문(), "이유")
    assert "엘앤에프(066970)" in 매도알림("엘앤에프", "066970", _주문(OrderSide.SELL), "손절")


# ── 전략 이름과 매도 조건 ────────────────────────────────────────────────


def test_적용전략에_한글_이름이_들어간다():
    """`volume_surge_5d_ma20`이 그대로 오면 무슨 전략인지 알 수 없다."""
    from muwon.strategy.registry import build_strategy

    글 = 매수알림("엘앤에프", "066970", _주문(), "거래량 2배 급증 + 6.4% 상승",
                전략=build_strategy("volume_surge_5d_ma20"))

    assert "적용전략 : 거래량 급증 + 20일선 (거래량 2배 급증 + 6.4% 상승)" in 글
    assert "volume_surge" not in 글


def test_매수와_매도를_따로_걸면_사는_쪽_이름이_뜬다():
    """사는 알림에 파는 쪽 이름이 뜨면 왜 샀는지 설명이 안 된다."""
    from muwon.strategy.registry import build_strategies

    묶음 = build_strategies(("ma_rsi_v1",), "OR", ("volume_surge_5d_ma20",))
    글 = 매수알림("엘앤에프", "066970", _주문(), "RSI 반등", 전략=묶음)

    assert "적용전략 : 이평+RSI 20/60" in 글


def test_파는_길을_전부_적는다():
    """손절만 적으면 '매도 전략은 손절밖에 없냐'가 된다. 실제로 받은 질문이다."""
    from muwon.settings.schema import RiskPolicy
    from muwon.strategy.registry import build_strategy

    글 = 매수알림("엘앤에프", "066970", _주문(), "거래량 급증",
                전략=build_strategy("volume_surge_5d_ma20"), 정책=RiskPolicy())

    assert "-5% 손절" in 글
    assert "5거래일이 지나면" in 글
    assert "20일 평균선" in 글


def test_굵게_표시가_그대로_도착하지_않는다():
    """텔레그램에 parse_mode가 없어서 별표가 글자로 보인다."""
    from muwon.settings.schema import RiskPolicy
    from muwon.strategy.registry import build_strategy

    글 = 매수알림("엘앤에프", "066970", _주문(), "거래량 급증",
                전략=build_strategy("volume_surge_5d_ma20"), 정책=RiskPolicy())

    assert "**" not in 글


def test_파는_길이_하나면_한_줄로_둔다():
    """점 하나짜리 목록은 목록이 아니다."""
    글 = 매수알림("엘앤에프", "066970", _주문(), "거래량 급증", 손절비율=-0.05)

    assert "매도전략 : " in 글
    assert "  · " not in 글
