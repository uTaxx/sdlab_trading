"""**체결 알림이 처음 쓰는 사람에게 읽히는가.**

예전 글은 이랬다.

    🟢 매수 체결
    종목: 엘앤에프(066970)
    수량: 12주 중 4주 체결 · 잔여 8주
    가격: 118,300원
    사유: 거래량 2배 급증 + 3.4% 상승

`가격: 118,300원`이 1주 값인지 전부 합친 값인지 없고, 그래서 얼마를 쓴
것인지 없고, 앞으로 언제 팔리는지 없다.

매도 쪽은 더 나빴다. **손익이 아예 없었다.** 팔았다는 사실만 있고 벌었는지
잃었는지가 없으면, 받아 보는 사람이 제일 먼저 묻는 것에 답을 못 한다.
"""

from __future__ import annotations

from datetime import date

from muwon.domain.types import OrderResult, OrderSide
from muwon.execution.engine import 매도알림, 매수알림


def _주문(방향=OrderSide.BUY, 수량=12, 값=118300.0, 주문수량=0) -> OrderResult:
    return OrderResult(
        symbol="066970", side=방향, quantity=수량, price=값, order_id="1",
        is_paper=True, reference_price=121600.0, fill_confirmed=True,
        ordered_quantity=주문수량,
    )


# ── 매수 ─────────────────────────────────────────────────────────────────


def test_1주값인지_총액인지_구분해_적는다():
    글 = 매수알림("엘앤에프", "066970", _주문(), "거래량 급증")

    assert "1주당 118,300원" in 글
    assert "모두 1,419,600원" in 글


def test_언제_자동으로_팔리는지_실제_가격으로_알려준다():
    """'손절 -5%'는 규칙이지 가격이 아니다. 사람은 가격을 봐야 안다."""
    글 = 매수알림("엘앤에프", "066970", _주문(), "거래량 급증", 손절비율=-0.05)

    assert "112,385원까지 떨어지면 자동으로 팝니다" in 글
    assert "5% 손해" in 글


def test_ATR_손절이면_고정_가격을_말하지_않는다():
    """켜져 있는데 고정 %로 적으면 화면이 거짓말을 한다."""
    글 = 매수알림("엘앤에프", "066970", _주문(), "거래량 급증",
                손절비율=-0.05, atr손절=True)

    assert "112,385원" not in 글
    assert "ATR" in 글


def test_부분_체결이면_무엇을_해야_하는지까지_적는다():
    """'잔여 8주'만 보면 뭘 해야 하나 하고 멈춘다."""
    글 = 매수알림("엘앤에프", "066970", _주문(수량=4, 주문수량=12), "거래량 급증")

    assert "주문한 12주 중 4주를 샀습니다" in 글
    assert "손댈 것 없습니다" in 글
    assert "모두 473,200원" in 글, "총액은 산 만큼으로 세야 한다"


# ── 매도 ─────────────────────────────────────────────────────────────────


def test_판_뒤에는_벌었는지_잃었는지_말한다():
    """이 파일에서 제일 중요한 시험이다. 예전 글에는 이게 통째로 없었다."""
    글 = 매도알림(
        "엘앤에프", "066970", _주문(OrderSide.SELL, 12, 112300.0), "손절",
        진입가=118241.0, 진입일=date(2026, 8, 25), 판날=date(2026, 9, 2),
    )

    assert "산 값 118,241원 → 판 값 112,300원" in 글
    assert "-71,292원 (-5.0%) 잃었습니다" in 글
    assert "8일 들고 있었습니다" in 글


def test_이익이_나면_벌었다고_한다():
    글 = 매도알림(
        "ACE KRX금현물", "411060", _주문(OrderSide.SELL, 51, 31500.0), "익절 (+7.7%)",
        진입가=29260.0,
    )

    assert "+114,240원 (+7.7%) 벌었습니다" in 글


def test_수수료를_뺀_값이_아니라고_밝힌다():
    """이 숫자를 그대로 세금 신고에 쓰면 안 된다."""
    글 = 매도알림("엘앤에프", "066970", _주문(OrderSide.SELL), "손절", 진입가=118241.0)

    assert "수수료·세금은 빼기 전 값입니다" in 글


def test_산_값을_모르면_손익을_지어내지_않는다():
    글 = 매도알림("엘앤에프", "066970", _주문(OrderSide.SELL), "손절")

    assert "이 거래의 결과" not in 글


def test_왜_저절로_팔렸는지_풀어_준다():
    """처음 쓰는 사람에게 제일 큰 질문은 '왜 내 주식이 저절로 팔렸나'다.
    '손절' 두 글자로는 답이 안 된다."""
    손절 = 매도알림("A", "1", _주문(OrderSide.SELL), "손절")
    익절 = 매도알림("A", "1", _주문(OrderSide.SELL), "익절 (+7.7%)")
    기간 = 매도알림("A", "1", _주문(OrderSide.SELL), "보유기간 만료")
    atr = 매도알림("A", "1", _주문(OrderSide.SELL), "ATR 손절 (2ATR, -6.1%)")

    assert "미리 정해 둔 한계보다 더 떨어져서" in 손절
    assert "목표한 만큼 올라서" in 익절
    assert "전략이 정한 보유 기간이 끝나" in 기간
    assert "하루에 보통 움직이는 폭보다" in atr


def test_모르는_사유는_그대로_두고_안_터진다():
    글 = 매도알림("A", "1", _주문(OrderSide.SELL), "무슨무슨 사유")

    assert "무슨무슨 사유" in 글


# ── 둘 다 ────────────────────────────────────────────────────────────────


def test_텔레그램에_안_먹는_기호를_안_쓴다():
    """send_message에 parse_mode를 안 준다 — `**굵게**`가 그대로 도착한다."""
    assert "**" not in 매수알림("A", "1", _주문(), "이유", 손절비율=-0.05)
    assert "**" not in 매도알림("A", "1", _주문(OrderSide.SELL), "손절", 진입가=100.0)


def test_종목명과_코드를_같이_적는다():
    """코드만 있으면 무슨 주식인지 모르고, 이름만 있으면 확인할 수가 없다."""
    assert "엘앤에프(066970)" in 매수알림("엘앤에프", "066970", _주문(), "이유")
    assert "엘앤에프(066970)" in 매도알림("엘앤에프", "066970", _주문(OrderSide.SELL), "손절")
