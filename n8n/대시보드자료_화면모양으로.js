const 요청 = $('무엇을 물었나').first().json;
const 무엇 = 요청.무엇;
// 요청마다 탭 하나만 읽으므로 답은 항상 valueRanges[0]이다.
const 줄들 = ((($input.first().json.valueRanges || [])[0]) || {}).values || [];

const 값 = (줄, i) => String(줄 && 줄[i] != null ? 줄[i] : "").trim();
const 수 = (글) => {
  const n = Number(String(글).replace(/[^0-9.eE+-]/g, ""));
  return Number.isFinite(n) ? n : 0;
};
// 시트는 "2026-08-25 09:05"로 적는다. 화면은 좁은 칸에 넣으므로 해를 버린다.
const 때 = (글) => String(글 || "").replace(/^\d{4}-/, "");
// 최근 것이 위로. 시트는 덧붙이기만 해서 오래된 것이 앞에 있다.
const 최근 = (줌, 몇 = 50) => 줌.slice(-몇).reverse();
// 시트의 날짜는 한국 날짜다. 서버가 UTC라 new Date()를 그냥 쓰면
// 오전 9시 이전에는 어제 날짜가 나와 오늘 후보가 통째로 안 보인다.
const 오늘 = new Date().toLocaleDateString("sv-SE", { timeZone: "Asia/Seoul" });
const 몸줄 = 줄들.slice(1).filter((ㅈ) => 값(ㅈ, 0));

// 전략 키는 시트에 코드 이름으로 적힌다(volume_surge_5d_ma20). 한글로
// 옮기는 것은 화면이 한다 — 전략 목록의 원본이 파이썬이라, 창구가 이름까지
// 나르면 원본이 둘이 되고 언젠가 어긋난다. 여기서는 키만 실어 보낸다.
//
// 다만 평가·총평·신호 문장은 파이썬이 만들어 시트에 쌓아 둔 것을 그대로
// 나른다. 화면에서 따로 문장을 만들면 시트에 남은 기록과 화면이 다른 말을
// 하게 된다.
if (무엇 === "승인목록") {
  const 후보 = 줄들.slice(1)
    .filter((ㅈ) => 값(ㅈ, 1) === 오늘 && 값(ㅈ, 2))
    .map((ㅈ) => ({
      종목코드: 값(ㅈ, 2),
      종목명: 값(ㅈ, 3),
      섹터: 값(ㅈ, 4),
      전략: 값(ㅈ, 5),
      수량: 수(값(ㅈ, 6)),
      예상가: 수(값(ㅈ, 7)),
      승인: 값(ㅈ, 8).toUpperCase(),
    }));
  return [{ json: { 날짜: 오늘, 후보 } }];
}

if (무엇 === "기준") {
  const 설정 = {};
  줄들.slice(1).forEach((ㅈ) => { const 이름 = 값(ㅈ, 0); if (이름) 설정[이름] = 값(ㅈ, 1); });
  const 참 = (글, 기본) => {
    const g = String(글 || "").trim().toLowerCase();
    if (!g) return 기본;
    return ["true", "y", "yes", "1", "o", "ok", "on", "켜짐", "켬", "예"].indexOf(g) >= 0;
  };
  const 전략 = 설정.strategy || "";
  // 파는 쪽을 따로 걸어 뒀으면 그것도 보낸다. 이 칸이 없으면 화면에는
  // 사는 쪽만 뜨고, 실제로는 다른 규칙으로 팔고 있어도 안 보인다.
  const 매도전략 = 설정.sell_strategy || "";
  return [{ json: {
    // ── 매수 기초 ──
    매매켜짐: 참(설정.trading_enabled, false),
    비중: 수(설정.max_position_weight || "15"),
    동시보유: 수(설정.max_concurrent_positions || "8"),
    섹터당: 수(설정.max_per_sector || "2"),
    거래대금문턱: 수(설정.min_turnover_eok || "50"),
    // 화면은 양수로 보여 준다. 시트는 음수로 적혀 있다.
    하루손실한도: Math.abs(수(설정.daily_loss_limit_pct || "-3")),
    승인필요: 참(설정.require_approval, true),
    // ── 매도 기초 ──
    매도켜짐: 참(설정.sell_enabled, true),
    손절: Math.abs(수(설정.stop_loss_pct || "-5")),
    // 익절과 보유기간은 0이 뜻을 가진 값이다. 익절 0은 '끔', 보유기간
    // 0은 '전략에게 맡김'이다. 안 보내면 화면이 지금 상태를 모른다.
    익절: 수(설정.take_profit_pct || "0"),
    보유기간: 수(설정.max_holding_days || "0"),
    // ── 세부전략 ──
    전략,
    매도전략,
    // 전략은 보여 줄 수는 있지만 여기서 바꿀 수는 없다. 바꾸는 것은
    // 돈이 나가는 결정이라 화면에서 조용히 되게 두지 않는다.
    읽기만하는칸: ["전략", "매도전략"],
    아직없는칸: 전략 ? [] : ["전략"],
  } }];
}

if (무엇 === "기록") {
  const 거래 = 몸줄.map((ㅈ) => ({
    종목: 값(ㅈ, 2),
    전략: 값(ㅈ, 3),
    손익: 수(값(ㅈ, 7)),
    수익률: 수(값(ㅈ, 8)),
    수량: 수(값(ㅈ, 4)),
    산값: 수(값(ㅈ, 5)),
    판값: 값(ㅈ, 6) ? 수(값(ㅈ, 6)) : 0,
    기간: "",
  }));
  const 이긴 = 거래.filter((ㄱ) => ㄱ.손익 > 0);
  const 진 = 거래.filter((ㄱ) => ㄱ.손익 < 0);
  const 번돈 = 이긴.reduce((합, ㄱ) => 합 + ㄱ.손익, 0);
  const 잃은돈 = Math.abs(진.reduce((합, ㄱ) => 합 + ㄱ.손익, 0));

  // 이 최대낙폭은 백테스트의 것과 다르다. 백테스트는 평가금액으로 재고
  // 이것은 청산이 끝난 매매의 누적 손익으로 잰다. 지금 들고 있는 종목이
  // 빠진 것은 안 잡힌다.
  let 누적 = 0;
  let 꼭지 = 0;
  let 낙폭 = 0;
  거래.forEach((ㄱ) => {
    누적 += ㄱ.손익;
    if (누적 > 꼭지) 꼭지 = 누적;
    if (꼭지 > 0) 낙폭 = Math.min(낙폭, ((누적 - 꼭지) / 꼭지) * 100);
  });

  return [{ json: {
    승률: 거래.length ? (이긴.length / 거래.length) * 100 : 0,
    손익비: 잃은돈 > 0 ? 번돈 / 잃은돈 : 0,
    최대낙폭: 낙폭,
    거래: 최근(거래),
    낙폭기준: "청산이 끝난 매매의 누적 손익으로 잰 값입니다. 지금 들고 있는 종목이 빠진 것은 안 잡힙니다.",
  } }];
}

// 기간별 검증. 잰때는 해를 안 버린다 — 이 표는 언제 잰 숫자인지가
// 숫자만큼 중요하다. 지난달에 잰 것을 오늘 것으로 읽으면 안 된다.
// 한 회차에 다섯 줄씩 쌓이므로 지난 회차까지 넉넉하게 본다.
if (무엇 === "기간검증") {
  return [{ json: { 검증: 최근(몸줄, 300).map((ㅈ) => ({
    잰때: 값(ㅈ, 1),
    기간: 값(ㅈ, 2),
    시작일: 값(ㅈ, 3),
    끝일: 값(ㅈ, 4),
    매수전략: 값(ㅈ, 5),
    매도전략: 값(ㅈ, 6),
    수익률: 수(값(ㅈ, 7)),
    최대낙폭: 수(값(ㅈ, 8)),
    최악토막: 값(ㅈ, 9),
    최악토막수익률: 수(값(ㅈ, 10)),
    승률: 수(값(ㅈ, 11)),
    손익비: 수(값(ㅈ, 12)),
    거래수: 수(값(ㅈ, 13)),
    표본충분: 값(ㅈ, 14) === "예",
    기준: 값(ㅈ, 15),
    상태: 값(ㅈ, 16) || "됨",
    까닭: 값(ㅈ, 17),
    평가: 값(ㅈ, 18),
    신호등급: 값(ㅈ, 19),
    신호: 값(ㅈ, 20),
  })) } }];
}

// 골라서 돌려 본 것. 한 번에 27개 × 5구간 = 135줄이 올라온다.
// 화면에서 지난 회차를 골라 볼 수 있게 하려면 그것들이 먼저 와야 한다.
// 200줄이면 지난 회차 하나도 온전히 안 온다.
if (무엇 === "기간비교") {
  return [{ json: { 비교: 최근(몸줄, 1500).map((ㅈ) => ({
    잰때: 값(ㅈ, 1),
    기간: 값(ㅈ, 2),
    시작일: 값(ㅈ, 3),
    끝일: 값(ㅈ, 4),
    매수전략: 값(ㅈ, 5),
    수익률: 수(값(ㅈ, 7)),
    최대낙폭: 수(값(ㅈ, 8)),
    최악토막: 값(ㅈ, 9),
    최악토막수익률: 수(값(ㅈ, 10)),
    승률: 수(값(ㅈ, 11)),
    손익비: 수(값(ㅈ, 12)),
    거래수: 수(값(ㅈ, 13)),
    노출: 수(값(ㅈ, 14)),
    기준: 값(ㅈ, 15),
    매도전략: 값(ㅈ, 16),
    총평: 값(ㅈ, 18),
  })) } }];
}

if (무엇 === "최근주문") {
  // 칸 이름은 화면이 읽는 이름과 한 글자도 달라지면 안 된다.
  // 사고팔로 적어 내보내다 매수/매도 칸이 빈 점으로 보였다.
  return [{ json: { 주문: 최근(몸줄).map((ㅈ) => ({
    때: 때(값(ㅈ, 1)),
    종목: 값(ㅈ, 2),
    사고팜: 값(ㅈ, 3),
    수량: 수(값(ㅈ, 4)),
    값: 수(값(ㅈ, 5)),
    상태: 값(ㅈ, 6),
  })) } }];
}

if (무엇 === "실행기록") {
  return [{ json: { 회차: 최근(몸줄).map((ㅈ) => ({
    때: 때(값(ㅈ, 1)),
    전략: 값(ㅈ, 2),
    살펴본종목: 수(값(ㅈ, 4)),
    매수신호: 수(값(ㅈ, 5)),
    매도신호: 수(값(ㅈ, 6)),
    주문수: 수(값(ㅈ, 7)),
    막힌이유: 값(ㅈ, 8),
  })) } }];
}

if (무엇 === "알림") {
  return [{ json: { 알림: 최근(몸줄).map((ㅈ) => ({
    때: 때(값(ㅈ, 1)),
    종류: 값(ㅈ, 2),
    글: 값(ㅈ, 3),
  })) } }];
}

if (무엇 === "변경이력") {
  // 이미 시트에 쌓인 줄은 지우지 않는다(기록이므로). 대신 화면에
  // 낼 때 거른다. 안 바뀐 줄과 기계가 매번 다시 적는 값이 그것이다.
  // 실제로 106줄 중 100줄이었고, 그러면 진짜 변경 한 줄이 그 사이에 묻힌다.
  const 기계가쓰는키 = ["kis.access_token", "kis.token_expires_at", "telegram.update_offset"];
  const 쓸만한것 = 몸줄.filter((ㅈ) =>
    기계가쓰는키.indexOf(값(ㅈ, 2)) < 0 && 값(ㅈ, 3) !== 값(ㅈ, 4));
  return [{ json: { 이력: 최근(쓸만한것).map((ㅈ) => ({
    때: 때(값(ㅈ, 1)),
    무엇: 값(ㅈ, 2),
    이전: 값(ㅈ, 3) || "(비어 있음)",
    이후: 값(ㅈ, 4),
  })) } }];
}

return [{ json: {
  아직없음: true,
  무엇,
  까닭: "무엇을 물었는지 모르겠습니다. 화면과 창구의 판이 서로 다른 것 같습니다.",
} }];
