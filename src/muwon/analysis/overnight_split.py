"""번 돈이 **밤사이**에 났나, **낮 동안**에 났나.

왜 이걸 먼저 재는가. 실시간(장중) 매매 구조를 만들지 말지를 가르는
가장 값싼 실험이기 때문이다(단타전략조사 §3.2, 설계안 §25).

Lou·Polk·Skouras(JFE)는 미국 주식이 장기적으로 버는 수익의 **거의 전부가
오버나이트**(전날 종가 → 다음 날 시가, 장이 닫혀 있는 동안)에서 나왔고
**장중**(시가 → 종가) 수익은 0에 가까웠다고 보고했다. 더 나아가 팩터마다
시간대가 갈렸는데, **모멘텀은 오버나이트에서만** 벌었다.

지금 활성 전략(`volume_surge_5d`, 거래량 급증 + 상승)은 모멘텀 계열이다.
그러니 이런 예측이 선다. **우리 수익도 밤사이에서 나왔을 것이다.**
만약 맞다면, 장중에 사고파는 구조를 정교하게 만들 이유가 크게 줄어든다.
낮에는 애초에 벌 게 없기 때문이다.

## 어떻게 쪼개나

산 날 종가에서 판 날 종가까지의 가격 변화는 **정확히** 두 조각의 곱이다.

    전체 = ∏(시가ₜ / 종가ₜ₋₁) × ∏(종가ₜ / 시가ₜ)
              └── 오버나이트 ──┘   └──── 장중 ────┘

근사가 아니라 항등식이다. 그래서 "밤에만 들고 있었다면"과 "낮에만 들고
있었다면"을 각각 따로 말할 수 있다.

## 반드시 같이 읽어야 할 것: 이건 전략이 아니라 진단이다

1. **"밤에만 들고 있기"는 실제로 하면 매일 사고팔아야 한다.** 보유
   10일이면 왕복 10번이다. 여기 나오는 숫자에는 그 비용이 **하나도 안 들어
   있다.** 우리는 슬리피지 실측이 0건이라 얼마를 빼야 하는지도 모른다.
   즉 이 표는 "그러니 밤에만 사자"가 아니라 **"수익이 어디서 났나"**를
   가리키는 도구다.
2. 산 날의 장중은 뺀다. 종가에 샀으므로 그날 낮은 우리 것이 아니다.
3. 시가는 동시호가로 정해진다. 그 값에 실제로 살 수 있었는지는 별개 문제다.
"""

from __future__ import annotations

import statistics
from dataclasses import dataclass

import pandas as pd


@dataclass(frozen=True)
class Split:
    """매매 하나의 수익을 시간대별로 나눈 것. 단위는 %."""

    symbol: str
    보유일: int
    오버나이트: float  # 밤사이만 들고 있었다면
    장중: float  # 낮에만 들고 있었다면
    전체: float  # 둘의 곱 (= 비용 전 가격 수익률)

    @property
    def 밤이_더컸나(self) -> bool:
        return self.오버나이트 > self.장중


def split_overnight(trades, histories: dict[str, pd.DataFrame]) -> list[Split]:
    """완결된 매매마다 수익을 오버나이트와 장중으로 나눈다."""
    결과: list[Split] = []
    for trade in trades:
        df = histories.get(trade.symbol)
        if df is None or len(df) == 0:
            continue
        구간 = df[
            (df["trade_date"] >= trade.entry_date) & (df["trade_date"] <= trade.exit_date)
        ].sort_values("trade_date")
        # 산 날 종가가 출발점이므로 최소 두 봉이 있어야 나눌 것이 생긴다.
        if len(구간) < 2:
            continue

        밤, 낮 = 1.0, 1.0
        전날종가 = float(구간.iloc[0]["close"])
        성립 = True
        for _, 봉 in list(구간.iterrows())[1:]:
            시가, 종가 = float(봉["open"]), float(봉["close"])
            # 0이나 결측이 섞이면 곱이 통째로 망가진다. 조용히 0을 곱하느니
            # 그 매매를 통째로 뺀다. 반쯤 계산된 숫자가 가장 위험하다.
            if 전날종가 <= 0 or 시가 <= 0 or 종가 <= 0:
                성립 = False
                break
            밤 *= 시가 / 전날종가
            낮 *= 종가 / 시가
            전날종가 = 종가
        if not 성립:
            continue

        결과.append(
            Split(
                symbol=trade.symbol,
                보유일=len(구간) - 1,
                오버나이트=(밤 - 1) * 100,
                장중=(낮 - 1) * 100,
                전체=(밤 * 낮 - 1) * 100,
            )
        )
    return 결과


def _양수비율(값들: list[float]) -> float:
    return sum(1 for v in 값들 if v > 0) / len(값들) * 100


def _줄(이름: str, 밤: str, 낮: str, 전체: str) -> str:
    return f"{이름:<14}{밤:>16}{낮:>14}{전체:>12}"


def format_split(결과: list[Split], label: str = "") -> str:
    머리 = f"■ 번 돈은 밤사이에 났나, 낮에 났나{f' ({label})' if label else ''}"
    if not 결과:
        return f"{머리}\n\n나눌 수 있는 매매가 없습니다."

    밤들 = [s.오버나이트 for s in 결과]
    낮들 = [s.장중 for s in 결과]
    전체들 = [s.전체 for s in 결과]

    lines = [
        머리,
        "  오버나이트 = 전날 종가 → 다음 날 시가 (장이 닫혀 있는 동안)",
        "  장중       = 시가 → 종가 (장이 열려 있는 동안)",
        "  둘을 곱하면 정확히 전체가 됩니다. 근사가 아니라 항등식입니다.",
        "",
        "  ⚠ 이 표는 전략이 아니라 진단입니다. '밤에만 들고 있기'를 실제로 하면",
        "  매일 사고팔아야 하는데, 그 비용이 여기 하나도 안 들어 있습니다.",
        "",
        f"나눈 매매 {len(결과)}건 · 평균 보유 {statistics.fmean([s.보유일 for s in 결과]):.1f}거래일",
        "",
        "  '모두 더하기'는 매매별 수익률을 그냥 **더한** 것입니다. 계좌 수익률이",
        "  아닙니다. 포트폴리오는 여러 종목을 동시에 들고 있어서 매매들이 겹치므로,",
        "  이걸 곱해서 이어 붙이면 실제와 무관한 숫자가 나옵니다. 밤과 낮의 몫을",
        "  같은 잣대로 비교하려고 두는 값입니다.",
        "",
        _줄("", "오버나이트(밤)", "장중(낮)", "전체"),
        _줄(
            "매매당 평균",
            f"{statistics.fmean(밤들):+.2f}%",
            f"{statistics.fmean(낮들):+.2f}%",
            f"{statistics.fmean(전체들):+.2f}%",
        ),
        _줄(
            "매매당 중앙",
            f"{statistics.median(밤들):+.2f}%",
            f"{statistics.median(낮들):+.2f}%",
            f"{statistics.median(전체들):+.2f}%",
        ),
        _줄(
            "플러스 비율",
            f"{_양수비율(밤들):.1f}%",
            f"{_양수비율(낮들):.1f}%",
            f"{_양수비율(전체들):.1f}%",
        ),
        _줄(
            "모두 더하기",
            f"{sum(밤들):+.0f}%p",
            f"{sum(낮들):+.0f}%p",
            f"{sum(전체들):+.0f}%p",
        ),
    ]

    밤이더큰것 = sum(1 for s in 결과 if s.밤이_더컸나)
    밤합, 낮합 = sum(밤들), sum(낮들)
    lines += [
        "",
        (
            f"매매별로 밤이 더 컸던 경우 {밤이더큰것}건 "
            f"({밤이더큰것 / len(결과) * 100:.1f}%)"
        ),
    ]

    # 부호가 갈리면 '몇 %가 밤에서 나왔나'라는 말 자체가 성립하지 않는다.
    # 100%를 넘거나 음수인 비율을 태연히 찍는 것이 이런 표의 흔한 거짓말이다.
    if 밤합 > 0 and 낮합 > 0:
        lines.append(
            f"합계 기준 기여도: 밤 {밤합 / (밤합 + 낮합) * 100:.0f}% · "
            f"낮 {낮합 / (밤합 + 낮합) * 100:.0f}%"
        )
    elif 밤합 > 0 >= 낮합:
        꼬리 = "낮은 오히려 갉아먹었습니다" if 낮합 < 0 else "낮은 본전이었습니다"
        lines.append(f"합계 기준: **번 것은 전부 밤사이**, {꼬리}.")
    elif 낮합 > 0 >= 밤합:
        꼬리 = "밤사이는 오히려 갉아먹었습니다" if 밤합 < 0 else "밤사이는 본전이었습니다"
        lines.append(f"합계 기준: **번 것은 전부 낮**, {꼬리}.")
    else:
        lines.append("합계 기준: 밤도 낮도 마이너스입니다. 기여도를 나눌 것이 없습니다.")

    lines += [
        "",
        "읽는 법:",
        "  · 밤이 압도적이면 → **장중에 사고파는 구조를 만들 이유가 약합니다.**",
        "    낮에는 애초에 벌 게 없기 때문입니다. 실시간 매매보다 '언제 종가에",
        "    사서 언제 시가에 팔까'를 다듬는 편이 낫습니다.",
        "  · 낮이 크면 → 장중 움직임에 먹을 것이 있다는 뜻이므로, 실시간 판단이",
        "    성과를 바꿀 여지가 있습니다. 다만 그때부터는 비용 실측이 필수입니다.",
        "  · 둘이 비슷하면 → 이 실험으로는 결론이 안 납니다. 다른 근거가 필요합니다.",
    ]
    return "\n".join(lines)
