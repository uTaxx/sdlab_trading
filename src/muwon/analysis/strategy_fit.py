"""구간마다 어느 전략이 좋았나, 그리고 바꿀 만한가.

## 이 파일이 하는 일

구간(1주·1개월·3개월)마다 등록된 전략을 전부 같은 시세로 계산한 결과를
받아, 순위를 내고 **구간마다 변경 후보를 하나씩** 낸다. 구간이 셋이면
후보도 최대 셋이고, 셋이 다른 전략일 수 있다. 어느 것을 고를지는 사람이
정한다.

## 왜 구간마다 따로 내나

한 구간의 1위를 그대로 걸면 그 구간에 맞춘 것이 된다. 구간마다 따로 내면
**세 답이 갈리는지 모이는지가 보인다.** 세 구간이 같은 전략을 가리키면 그
근거는 한 구간짜리보다 강하고, 갈리면 갈린다는 사실 자체가 정보다.

2026-08-28 검증에서 3개월 1위가 12개월에서는 하위권이었다. 그때 3개월만
봤으면 그 사실을 못 봤다.

## 제안을 막는 자리

아래 중 하나라도 걸리면 후보를 내지 않고 **왜 안 냈는지를 적는다.**

- 거래가 문턱에 못 미친다 (구간이 짧으면 거의 항상 걸린다)
- 1위가 지금 설정된 전략이다
- 전략을 바꾼 지 최소 운용기간이 안 지났다
- 계산이 실패했거나 시세가 모자랐다

**막힌 이유를 적는 것이 후보를 내는 것만큼 중요하다.** 아무 말도 없으면
"오늘은 볼 것이 없다"와 "오늘은 계산이 안 됐다"가 구별되지 않는다.

## 등급

`period_check`와 같은 세 등급을 쓴다. 같은 말이 두 화면에서 다른 뜻이면
안 된다.

- 이상없음: 지금 설정된 전략을 바꿀 이유가 이 구간에서 안 나왔다
- 살펴볼것: 다른 전략이 앞서지만 표본이나 폭이 판단하기에 모자라다
- 확인필요: 다른 전략이 표본과 폭을 다 갖추고 앞선다

**어느 등급도 "바꿔라"라고 말하지 않는다.** 후보를 보여 주고 판단을 사람에게
넘긴다.
"""

