  // 들어 있어서, 못 읽으면 그 두 탭이 빈 채로 열린다.
  자동맞추기(false);
  자료읽기().then(() => {
    if (읽기()?.열쇠) {
      보이기("본문", true);
      탭보이기("손익");
      // 머리의 스위치와 전략 띠는 어느 탭에서든 보이는 것이라 기준 탭을
      // 안 열어도 맞아야 한다. 예전에는 열쇠를 처음 넣는 길에서만 읽어서,
      // 창을 닫았다 다시 열면 둘 다 빈 채로 남았다.
      기준불러오기();
      불러온적.add("기준");
    } else {
      첫화면();
    }
  });
