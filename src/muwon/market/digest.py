"""리포트 전문을 텔레그램에 보낼 짧은 요약으로 줄인다.

## 왜 줄이나

시장·섹터 리포트 전문은 200줄이 넘는다. 그걸 매일 텔레그램으로 보내면
**아무도 안 읽는다.** 안 읽는 알림은 없는 것과 같고, 오히려 진짜 중요한
알림이 묻힌다.

## 2026-08-25에 다시 쓴 이유

받아 보는 사람이 **한 줄도 이해할 수 없다**고 했다. 다시 읽어 보니 맞았다.
"그냥 찍었을 때", "우연폭", "전망 못 냄", "렌즈 확장". 전부 이 저장소
안에서만 통하는 말이었고, 밖에서 보면 무슨 소린지 알 수 없는 글이었다.

고치면서 지킨 것 넷.

1. **처음 쓰는 말은 그 자리에서 푼다.** 뜻만이 아니라 "그래서 그걸 보고
   뭘 판단하나"까지 적는다.
2. **숫자마다 단위와 조건을 붙인다.** `-2.8`이 퍼센트인지 z점수인지
   안 적으면 읽는 사람이 퍼센트로 읽는다. 실제로 그랬다.
3. **별표(★)나 `**굵게**` 같은 기호로 뜻을 대신하지 않는다.** 텔레그램에
   마크다운을 안 읽어서 `**기각**`이 그대로 별 네 개로 도착한다.
   기호가 필요하면 말로 쓴다.
4. **제일 중요한 말을 맨 위에 둔다.** 이 전망은 검증에서 떨어진 실험
   기록이다. 그 말이 맨 아래 있으면 위쪽 숫자를 먼저 믿게 된다.
"""

from __future__ import annotations

import math

#: 텔레그램 한 통의 안전한 길이.
MAX_LEN = 3500

_요일 = ("월", "화", "수", "목", "금", "토", "일")

#: 앞으로 며칠을 보는가. analog.HORIZON과 같아야 한다.
_지평_거래일 = 20


def _날짜글(기준일) -> str:
    try:
        return f"{기준일.month}월 {기준일.day}일({_요일[기준일.weekday()]})"
    except AttributeError:
        return str(기준일)


def _얼마나드문가(z: float) -> str:
    """지금 값이 평소에 비교해 얼마나 드문 자리인가를 **한 문장으로**.

    예전에는 `"아주 드물게 " + "깊이 빠져 있습니다"`처럼 부사를 앞에 붙였다.
    그런데 **'아주 드물게'는 빈도를 뜻하는 말**이라, "아주 드물게 깊이 빠져
    있습니다"가 "가끔씩만 깊이 빠진다"로 읽힌다. 지금 상태가 아니라 습관을
    말하는 문장이 된다.

    그래서 상태와 드문 정도를 **문장 두 개로 나눈다.** 앞에서 지금이 어떤지를
    말하고, 여기서 그게 흔한 일인지 아닌지를 따로 말한다."""
    셈 = abs(z)
    if 셈 >= 2:
        return "이런 자리는 몇 해에 한 번 볼까 말까 합니다"
    if 셈 >= 1:
        return "평소보다 뚜렷하게 벗어나 있습니다"
    # 1표준편차 안은 '조금 벗어났다'가 아니라 평소다. '조금 벗어나 있습니다'는
    # 읽고 나서 무엇을 판단해야 할지 알 수 없는 말이라 줄만 차지한다.
    return "평소와 비슷한 수준입니다"


def _센말(z: float, 위: str, 아래: str, 보통: str) -> str:
    """숫자가 없을 때 쓰는 말. 방향과 드문 정도를 한 줄에 담는다."""
    if abs(z) < 0.3:
        return 보통
    return f"{위 if z > 0 else 아래} {_얼마나드문가(z)}"


def state_line(state, 원시=None, 지수=None) -> str:
    """오늘 장 상태를 여러 줄로 풀어 쓴다.

    ## 숫자를 두 번 고쳤다

    처음에는 `단기추세 ▲+0.8 | 고점대비 -2.8`처럼 **z점수를 그대로** 찍었다.
    z점수는 "평소에 비교해 얼마나 벗어났나"이지 퍼센트가 아닌데 단위를 안 적어,
    받아 보는 사람이 -2.8을 "고점에서 2.8% 빠졌다"로 읽었다.

    그래서 숫자를 지우고 말만 남겼더니 이번에는 **"얼마나 깊이?"에 답을 못
    했다.** 고점대비는 원래 퍼센트로 말할 수 있는 값인데(지수 ÷ 1년 최고 − 1)
    같이 지워 버린 것이다.

    지금은 둘을 나눈다.
      - **원시값**은 그대로 쓴다. "최고점보다 12.3% 아래입니다"
      - **z점수**는 "그게 흔한 일인가"를 판단하는 데만 쓰고 숫자로는 안 낸다

    `원시`를 못 받으면 말만으로 적는다(숫자를 지어내지 않는다).

    `지수`(코스피 종가)를 주면 맨 위에 지수 값을 적는다. "20일 평균보다
    1.8% 위"만으로는 무엇과 무엇을 비교한 것인지 알 수 없다는 지적을 받았다.
    기준이 되는 숫자가 있어야 나머지 줄이 읽힌다."""
    if len(state) == 0:
        return "  아직 잴 수 없습니다. 비교할 과거(3년)가 안 쌓였습니다."
    오늘 = state.iloc[-1]
    원시오늘 = None
    if 원시 is not None and len(원시):
        같은날 = 원시.loc[:state.index[-1]]
        if len(같은날):
            원시오늘 = 같은날.iloc[-1]

    def _z(이름: str):
        return float(오늘[이름]) if 이름 in 오늘.index else None

    def _raw(이름: str):
        if 원시오늘 is None or 이름 not in 원시오늘.index:
            return None
        값 = float(원시오늘[이름])
        return None if math.isnan(값) else 값  # 값이 비어 있으면 지어내지 않는다

    줄 = []
    지금값 = None
    if 지수 is not None and len(지수):
        쓸것 = 지수.loc[:state.index[-1]]
        if len(쓸것):
            지금값 = float(쓸것.iloc[-1])
            어제대비 = ""
            if len(쓸것) >= 2 and float(쓸것.iloc[-2]) > 0:
                오름 = 지금값 / float(쓸것.iloc[-2]) - 1
                어제대비 = f" (하루 전보다 {오름:+.1%})"
            줄.append(f"코스피 {지금값:,.0f}{어제대비}")

    if (추세 := _z("kospi_추세20")) is not None:
        몫 = _raw("kospi_추세20")
        if 몫 is not None:
            # 평균값도 같이 적는다. 비율만으로는 무엇과 견줬는지 안 보인다.
            평균 = 지금값 / (1 + 몫) if 지금값 and 몫 != -1 else None
            기준 = f"평균 {평균:,.0f}보다" if 평균 else "평균보다"
            높낮이 = "높은" if 몫 >= 0 else "낮은"
            줄.append(
                f"  · 최근 한 달 흐름: 최근 20거래일 {기준} {abs(몫):.1%} {높낮이} 자리입니다."
                f" {_얼마나드문가(추세)}"
            )
        else:
            줄.append(
                "  · 최근 한 달 흐름: "
                + _센말(
                    추세,
                    "최근 20거래일 평균보다 높은 자리입니다.",
                    "최근 20거래일 평균보다 낮은 자리입니다.",
                    "최근 20거래일 평균 근처입니다.",
                )
            )

    if (낙폭 := _z("kospi_고점대비")) is not None:
        몫 = _raw("kospi_고점대비")
        if 몫 is not None:
            줄.append(
                f"  · 1년 최고점보다 {abs(몫):.1%} 아래에 있습니다."
                f" {_얼마나드문가(낙폭)}"
            )
        else:
            줄.append(
                "  · 1년 최고점보다 "
                + _센말(낙폭, "고점에 가깝습니다.", "깊이 빠져 있습니다.", "평소만큼입니다.")
            )

    if (변동 := _z("kospi_변동성")) is not None:
        몫 = _raw("kospi_변동성")
        뒷말 = " 손절선에 잘 걸리는 장입니다." if 변동 >= 1 else ""  # 앞 문장이 마침표로 끝난다
        if 몫 is not None:
            줄.append(
                f"  · 하루 등락 폭: 요즘 하루에 평균 {몫:.1%}씩 움직입니다."
                f" {_얼마나드문가(변동)}.{뒷말}"
            )
        else:
            줄.append(
                "  · 하루 등락 폭: "
                + _센말(변동, "출렁입니다.", "조용합니다.", "평소만큼입니다.")
                + 뒷말
            )

    return "\n".join(줄) if 줄 else "  지표를 못 읽었습니다."


def _섹터줄(f) -> str:
    """섹터 한 줄. 숫자마다 무엇인지가 줄 안에 들어 있어야 한다."""
    이번 = f"{f.상승확률:.0f}%"
    if f.기준선 is None or f.더한것_상승확률 is None:
        return f"  · {f.대상} {이번}"

    벌어짐 = f.더한것_상승확률
    차이 = "차이 없음" if abs(벌어짐) < 0.5 else f"차이 {벌어짐:+.0f}%p"
    판정 = "우연보다 큼" if f.우연을_넘었나 else "우연 범위 안"
    # 구분자로 '—'를 안 쓴다. 섹터 이름에 이미 들어 있다(원자재 ETF: 금 선물).
    # 한 줄에 대시가 둘이면 어디까지가 이름인지 안 보인다.
    return f"  · {f.대상} {이번}  (평소 {f.기준선.상승확률:.0f}% / {차이} / {판정})"


def _돈(값) -> str:
    return f"{값:,.0f}원"


def 오늘한일(산것=None, 판것=None, 보유=None, 못읽음="") -> list[str]:
    """오늘 실제로 무슨 일이 있었나.

    **이게 이 알림을 여는 이유다.** 앞의 시장 지표는 배경이고, 사람이 밤에
    확인하고 싶은 것은 "오늘 내 계좌에 무슨 일이 있었나"다. 그게 없으면
    지표만 열 줄 읽고 닫게 된다.

    셋 다 비어 있어도 줄을 적는다. "산 것 없음"과 "이 알림이 매수 얘기를
    안 한다"는 다른 말이고, 뒤쪽으로 읽히면 안 산 날과 알림이 고장 난 날이
    구별되지 않는다."""
    if 못읽음:
        # 안 산 날과 DB를 못 읽은 날이 화면에서 같아 보이면, 매수가 통째로
        # 막힌 날을 평범한 날로 읽게 된다. 실제로 그런 날이 있었다.
        return [
            "오늘 한 일",
            "  기록을 읽지 못했습니다. 오늘 무엇을 샀고 팔았는지 여기서는 알 수 없습니다.",
            f"  ({못읽음})",
        ]

    산것 = list(산것 or [])
    판것 = list(판것 or [])
    보유 = list(보유 or [])

    줄 = ["오늘 한 일"]

    if 산것:
        줄.append(f"  산 것 {len(산것)}종목")
        # 한 주 값인지 다 합친 값인지 안 적으면 둘 중 하나로 읽고, 어느 쪽으로
        # 읽었는지는 본인도 모른다. 둘 다 적는다.
        줄 += [
            f"    {이름} {수량:,}주 · 1주 {_돈(값)} · 모두 {_돈(수량 * 값)}"
            for 이름, 수량, 값 in 산것
        ]
    else:
        줄.append("  산 것 없음")

    if 판것:
        줄.append(f"  판 것 {len(판것)}종목")
        for 이름, 수량, 손익, 손익률 in 판것:
            줄.append(f"    {이름} {수량:,}주 · {손익:+,.0f}원 ({손익률:+.1f}%)")
    else:
        줄.append("  판 것 없음")

    if 보유:
        이름들 = ", ".join(이름 for 이름, _, _ in 보유)
        줄.append(f"  들고 있는 것 {len(보유)}종목: {이름들}")
        줄.append("    지금 얼마인지는 대시보드의 '지금 손익'에서 봅니다")
    else:
        줄.append("  들고 있는 것 없음")

    return 줄


def summarize(state, forecasts, 기준일, 렌즈: str = "", 지평: int = _지평_거래일,
              원시=None, 지수=None, 한일=None) -> str:
    """텔레그램 한 통짜리 요약.

    ## 2026-08-26에 또 줄인 이유

    받아 보는 사람이 "자꾸 이따구 문장으로 만들래"라고 했다. 다시 읽어 보니
    문장이 아니라 **구조**가 문제였다.

    전체의 60%가 "이건 기각된 방식이니 쓰지 마세요"를 설명한 뒤, 바로 그
    쓰지 말라는 표를 열 줄 찍고 있었다. 게다가 그 열 줄 중 여덟 줄에는
    "우연 범위 안"이라고 적혀 있다. 스스로 "차이가 없다"고 적은 줄이
    메시지의 절반을 차지한 것이다.

    매일 밤 이런 글을 받으면 **메시지 전체를 흘려보게 된다.** 그러면 정작
    중요한 줄도 같이 놓친다. 설명을 더 잘 쓰는 것으로는 안 고쳐진다.

    그래서 섹터 표를 알림에서 뺐다. 표는 리포트 전문과 시트에 그대로 쌓이고,
    알림에는 몇 개가 우연을 넘었는지 한 줄만 남긴다. 설명이 길었던 이유가
    표가 거기 있었기 때문이므로, 표를 빼면 설명도 같이 짧아진다.

    대신 **오늘 무슨 일이 있었는지**를 넣었다. 그게 이 알림을 여는 이유다.
    """
    낸것 = [f for f in forecasts if f.낼수있나]
    넘은것 = [f for f in 낸것 if f.우연을_넘었나]

    줄 = [f"📊 {_날짜글(기준일)} 장 마감", ""]

    if 지수 is None and 원시 is None and len(state) == 0:
        줄.append("오늘 코스피")
    줄.append(state_line(state, 원시, 지수))
    줄.append("")

    줄 += 오늘한일(**(한일 or {}))

    줄 += [
        "",
        "─────────────",
        "섹터 전망 실험도 같이 돌았습니다.",
    ]
    if 낸것:
        줄.append(f"  {len(낸것)}개 중 {len(넘은것)}개가 우연을 넘었습니다.")
    else:
        줄.append("  이번에는 숫자를 낼 만큼 비슷했던 과거가 없었습니다.")
    줄 += [
        "",
        "  이 방식은 검증에서 떨어졌습니다. 과거로 되돌아가 실제로 맞히는지",
        "  세어 보니 51.8%였고, 아무 날에나 샀을 때가 56.3%였습니다.",
        "  그래서 매매에 쓰지 마세요. 표는 대시보드와 시트에 그대로 남습니다.",
    ]

    if 렌즈:
        줄 += ["", f"이 기록이 본 자료: {_렌즈설명(렌즈)}"]

    글 = "\n".join(줄)
    if len(글) > MAX_LEN:
        글 = 글[: MAX_LEN - 20] + "\n… (줄임)"
    return 글


def _렌즈설명(렌즈: str) -> str:
    """'렌즈 확장'만 적으면 무슨 말인지 알 수 없다. 무엇을 봤는지 적는다."""
    from muwon.market.series import LENSES, SERIES

    if 렌즈 not in LENSES:
        return 렌즈
    키들, 시작연도, _ = LENSES[렌즈]
    이름들 = ", ".join(SERIES[k].이름 for k in 키들 if k in SERIES)
    return f"{이름들} ({시작연도}년부터)"
