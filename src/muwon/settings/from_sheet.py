class SettingsError(ValueError):
    """설정 값이 매매에 쓸 수 없는 상태다."""


def _참인가(값: str) -> bool:
    return str(값).strip().upper() in 켜짐표시


def _숫자(이름: str, 값: str) -> float:
    try:
        return float(str(값).strip())
    except ValueError as e:
        raise SettingsError(f"{이름}: 숫자가 아닙니다 ({값!r})") from e


@dataclass(frozen=True)
class 시트설정:
    """시트에서 읽어 검증까지 끝난 값.

    `값`에는 **기준표에 있는 모든 항목**이 시트에 적힌 대로 들어간다(빈 칸은
    안 들어간다). `덮개`는 그중 RiskPolicy로 갈 것만 골라 단위까지 바꾼
    것이다. 둘을 나눠 두는 이유는, 정책이 아닌 값(섹터 상한 같은 것)도
    똑같이 시트에서 관리해야 하기 때문이다."""

    값: dict[str, object] = field(default_factory=dict)
    덮개: dict[str, object] = field(default_factory=dict)
    모르는이름: tuple[str, ...] = ()

    def 가져오기(self, 이름: str):
        """시트에 있으면 그 값, 없으면 기준표의 기본값."""
        if 이름 in self.값:
            return self.값[이름]
        return 기본값(기준표[이름])

    @property
    def 승인필요(self) -> bool:
        return bool(self.가져오기("require_approval"))

    @property
    def 최소거래대금_억(self) -> float:
        return float(self.가져오기("min_turnover_eok"))


def 기본값(b: 기준):
    return 해석값(b, b.기본)


def 해석값(b: 기준, 값: str):
    """한 칸의 글자 → 그 기준의 종류에 맞는 값. 범위도 여기서 본다."""
    if b.종류 == "참거짓":
        return _참인가(값)
    if b.종류 == "글자":
        # 숫자로 바꾸지 않는다. 범위 검사도 없다 — 이 종류는 화면에
        # 보여 주기만 하는 값이라 매매에 닿지 않는다.
        return str(값).strip()
    수 = _숫자(b.이름, 값)
    if b.종류 == "정수" and 수 != int(수):
        raise SettingsError(f"{b.이름}({b.표시}): {값!r} — 정수여야 합니다")
    if b.최소 is not None and 수 < b.최소:
        raise SettingsError(_범위말(b, 수))
    if b.최대 is not None and 수 > b.최대:
        raise SettingsError(_범위말(b, 수))
    # 0을 허용하지 않는 항목은 최소가 0으로 적혀 있어도 0이면 안 된다.
    if b.이름 == "max_position_weight" and 수 == 0:
        raise SettingsError(_범위말(b, 수))
    return int(수) if b.종류 == "정수" else 수


def _범위말(b: 기준, 수: float) -> str:
    단위 = "%" if b.종류 == "퍼센트" else ""
    아래 = "" if b.최소 is None else f"{b.최소:g}{단위} 이상"
    위 = "" if b.최대 is None else f"{b.최대:g}{단위} 이하"
    범위 = " ".join(x for x in (아래, 위) if x)
    끝말 = ""
    if b.이름 == "max_position_weight":
        끝말 = " — 절반 넘게 한 종목에 넣을 수 있으면 분산이 아닙니다"
    elif b.이름 in ("stop_loss_pct", "daily_loss_limit_pct"):
        끝말 = " — '이만큼 빠지면'이므로 -5처럼 음수로 적습니다"
    return f"{b.이름}({b.표시}): {수:g}{단위} — {범위}여야 합니다{끝말}"


def parse_settings(설정: dict[str, str]) -> 시트설정:
    """`설정` 탭의 이름·값 → 검증된 값.

    **네트워크 없이 시험할 수 있게 따로 뺐다.** 규칙이 이 함수의 전부이고,
    그걸 시험하려고 매번 구글에 붙을 수는 없다."""
    값: dict[str, object] = {}
    모르는것: list[str] = []

    for 이름, 원값 in 설정.items():
        키 = str(이름).strip()
        글자 = str(원값).strip()
        if not 키:
            continue
        b = 기준표.get(키)
        if b is None:
            모르는것.append(키)
            continue
        if 글자 == "":
            # 빈 칸은 "안 적었다"이지 "0으로 하라"가 아니다. 아래 단계가
            # DB나 기본값으로 채운다. 다만 킬스위치만은 빈 칸도 꺼짐이다.
            if 키 == "trading_enabled":
                값[키] = False
            continue
        값[키] = 해석값(b, 글자)

    덮개 = {}
    for 이름, 것 in 값.items():
        b = 기준표[이름]
        if not b.정책필드:
            continue
        # 시트에는 사람이 읽는 %로, 정책에는 소수로 들어간다.
        덮개[b.정책필드] = (것 / 100.0) if b.종류 == "퍼센트" else 것

    return 시트설정(값=값, 덮개=덮개, 모르는이름=tuple(모르는것))


def apply(기본: RiskPolicy, 시트: 시트설정 | None) -> tuple[RiskPolicy, dict[str, str]]:
    """DB에서 읽은 정책 위에 시트 값을 덮는다. (정책, 항목별 출처).

    **시트가 None이면 매매를 끈다.** 시트를 못 읽었다는 뜻인데, 그 상태로
    DB 값을 믿고 돌면 사람이 시트에서 끈 킬스위치가 안 먹는다.

    ## 킬스위치만 규칙이 다르다 — 덮는 게 아니라 **둘 다 켜져야 켜진다**

    다른 항목은 시트가 DB를 이긴다(시트가 원본이니까). 그런데
    `trading_enabled`을 그렇게 하면 **시트가 DB의 킬스위치를 무력화한다** —
    대시보드에서 껐는데 시트가 켜져 있으면 매매가 돈다.

    끄는 스위치는 **어느 쪽에서 꺼도 꺼져야** 한다. 켜는 것만 양쪽 동의를
    받는다. 그러면 두 곳 중 하나를 잊어도 사고가 안 나고, 틀리는 방향이
    언제나 "안 사는 쪽"이다.
    """
    if 시트 is None:
        # 매수는 끄고 **매도는 켠다.** 방향이 반대인 이유는 아래 참조.
        return replace(기본, trading_enabled=False, sell_enabled=True), {
            "trading_enabled": "시트를 못 읽어 끔",
            "sell_enabled": "시트를 못 읽어 켬(손절은 살려 둔다)",
        }

    덮개 = dict(시트.덮개)
    출처 = {필드: "DB" for 필드 in vars(기본)}
    for 필드 in 덮개:
        출처[필드] = "시트"

    시트킬 = 덮개.pop("trading_enabled", None)
    덮개["trading_enabled"] = 켤까 = 기본.trading_enabled and bool(시트킬)
    if 시트킬 is None:
        출처["trading_enabled"] = "시트에 없어 꺼짐"
    elif 켤까:
        출처["trading_enabled"] = "시트+DB 둘 다 켬"
    elif not 시트킬:
        출처["trading_enabled"] = "시트에서 끔"
    else:
        출처["trading_enabled"] = "DB에서 끔"

    # ── 매도는 규칙이 정반대다 ──────────────────────────────────
    #
    # 매수는 **둘 다 켜야 켜진다**(AND) — 어느 쪽에서 꺼도 꺼지므로, 틀리는
    # 방향이 언제나 "안 사는 쪽"이다.
    #
    # 매도는 **둘 다 꺼야 꺼진다**(OR) — 어느 쪽에서 켜도 켜지므로, 틀리는
    # 방향이 언제나 "파는 쪽"이다. 매수를 못 하면 기회를 놓칠 뿐이지만
    # **매도를 못 하면 손실이 그대로 자란다.** 안전한 쪽이 반대다.
    #
    # 그래서 시트에 항목이 없으면(예전 시트) 끄지 않고 켠 것으로 본다.
    시트매도 = 덮개.pop("sell_enabled", None)
    덮개["sell_enabled"] = 팔까 = 기본.sell_enabled or (시트매도 is None) or bool(시트매도)
    if 시트매도 is None:
        출처["sell_enabled"] = "시트에 없어 켜짐"
    elif 팔까 and 기본.sell_enabled and 시트매도:
        출처["sell_enabled"] = "시트+DB 둘 다 켬"
    elif 팔까:
        출처["sell_enabled"] = "한쪽만 켰지만 켬(손절 우선)"
    else:
        출처["sell_enabled"] = "**시트+DB 둘 다 꺼서 꺼짐**"

    return replace(기본, **덮개), 출처


def 지금값(정책: RiskPolicy, 시트: 시트설정 | None, b: 기준):
    """이 기준이 지금 실제로 얼마인가. 정책으로 간 것은 정책에서 읽는다 —
    거기가 킬스위치의 AND 규칙까지 반영된 최종값이기 때문이다."""
    if b.정책필드:
        것 = getattr(정책, b.정책필드)
        return 것 * 100 if b.종류 == "퍼센트" else 것
    return 시트.가져오기(b.이름) if 시트 is not None else 기본값(b)


def _폭(글: str) -> int:
    """한글은 자리를 두 칸 먹는다. 세지 않으면 표가 어긋난다."""
    from unicodedata import east_asian_width

    return sum(2 if east_asian_width(c) in "WF" else 1 for c in 글)


def _채움(글: str, 폭: int, 오른쪽=False) -> str:
    빈칸 = " " * max(0, 폭 - _폭(글))
    return 빈칸 + 글 if 오른쪽 else 글 + 빈칸


def 값글자(b: 기준, 것) -> str:
    if b.종류 == "참거짓":
        return "켜짐" if 것 else "꺼짐"
    if b.종류 == "글자":
        return str(것)
    if b.종류 == "퍼센트":
        return f"{float(것):+.1f}%" if float(것) < 0 else f"{float(것):.1f}%"
    if b.종류 == "정수":
        return f"{int(것)}"
    return f"{float(것):g}"


def describe(정책: RiskPolicy, 출처: dict[str, str], 시트: 시트설정 | None) -> str:
    """사람이 읽을 한 덩어리. 로그·텔레그램·화면이 같은 말을 쓰게 한 군데에 둔다."""
    켬 = "켜짐" if 정책.trading_enabled else "**꺼짐**"
    팜 = "켜짐" if 정책.sell_enabled else "**꺼짐**"
    줄 = [f"■ 지금 걸려 있는 기준 (매수 {켬} · 매도 {팜})", ""]
    for b in 기준들:
        어디 = 출처.get(b.정책필드 or b.이름)
        if 어디 is None:
            어디 = "시트" if (시트 is not None and b.이름 in 시트.값) else "기본값"
        줄.append(
            f"  {_채움(b.표시, 22)}{_채움(값글자(b, 지금값(정책, 시트, b)), 8, True)}   [{어디}]"
        )
    if not 정책.sell_enabled:
        줄 += [
            "",
            "  🛑 **매도가 꺼져 있습니다 — 손절·익절·청산이 전부 안 걸립니다.**",
            "     들고 있는 종목의 값이 얼마나 빠지든 아무 일도 일어나지 않습니다.",
        ]
    if 시트 is None:
        줄 += ["", "  ⚠️ **시트를 못 읽어 매수를 껐습니다(매도는 살려 뒀습니다).**"]
    elif 시트.모르는이름:
        줄 += [
            "",
            (f"  ⚠️ 시트에 **모르는 이름 {len(시트.모르는이름)}개**가 있습니다 — "
             "적어 두셨지만 **아무 효과가 없습니다**:"),
            f"     {', '.join(시트.모르는이름)}",
        ]
    return "\n".join(줄)

def build_policy_provider(service, sheet_id: str, reader=None):
    """매매 스크립트가 쓸 정책 제공자. **한 번만 읽고 그 값으로 그 회차를 돈다.**

    리스크 매니저는 종목마다 정책을 묻는다. 그때마다 구글에 붙으면 느리고,
    더 나쁘게는 **한 회차 도는 중간에 값이 바뀔 수 있다** — 앞 종목은 옛
    기준, 뒤 종목은 새 기준으로 걸러지면 나중에 로그를 봐도 왜 그랬는지
    알 수 없다. 그래서 시작할 때 한 번 읽어 고정한다.

    돌려주는 것: (정책을 돌려주는 함수, 사람이 읽을 설명, 시트설정 또는 None)
    """
    읽기 = reader
    if 읽기 is None:  # pragma: no cover — 실제 구글 호출은 시험하지 않는다
        from muwon.cloud.sector_sheet import read as 시트읽기

        def 읽기():
            return 시트읽기(sheet_id).설정

    try:
        시트 = parse_settings(읽기())
    except Exception as e:  # noqa: BLE001 — 어떤 이유든 못 읽었으면 멈춰야 한다
        시트 = None
        사유 = f"{type(e).__name__}: {e}"
    else:
        사유 = ""

    정책, 출처 = apply(service.get_risk_policy(), 시트)
    글 = describe(정책, 출처, 시트)
    if 사유:
        글 += f"\n     사유: {사유}"
    return (lambda: 정책), 글, 시트
