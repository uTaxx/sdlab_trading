등급들 = ("이상없음", "살펴볼것", "확인필요")


def 더센등급(ㄱ: str, ㄴ: str) -> str:
    return 등급들[max(등급들.index(ㄱ), 등급들.index(ㄴ))]


@dataclass(frozen=True)
class 전략줄:
    """한 구간에서 전략 하나의 성적."""

    키: str
    이름: str
    성적: 기간성적

    @property
    def 수익률(self) -> float:
        return self.성적.수익률

    @property
    def 거래수(self) -> int:
        return self.성적.metrics.num_trades


@dataclass(frozen=True)
class 구간순위:
    """한 구간의 전략 순위.

    **매수가 한 건도 없던 전략은 순위에서 뺀다.** 수익률 0%로 위에 올라오는데
    그건 손실을 막은 것이 아니라 거래가 없었던 것이다.

    순서는 `기준`이 정한다(2026-09-03에 바꿈). 전에는 수익률 하나로만
    줄을 세웠는데, 저장소가 적어 둔 1순위 판단 기준은 가장 나빴던 구간이었다.
    적힌 것과 도는 것이 달랐고 그 어긋남을 아무것도 빨갛게 만들지 않았다."""

    구간: str
    줄들: list[전략줄] = field(default_factory=list)
    지금키: str = ""
    기준: 판단기준 = 기본기준

    @property
    def 산것(self) -> list[전략줄]:
        return [ㄱ for ㄱ in self.줄들 if ㄱ.거래수 > 0]

    @property
    def 차례(self) -> list[전략줄]:
        return 줄세우기(self.산것, self.기준, lambda ㄱ: ㄱ.성적)

    @property
    def 최고(self) -> 전략줄 | None:
        차 = self.차례
        return 차[0] if 차 else None

    @property
    def 지금줄(self) -> 전략줄 | None:
        return next((ㄱ for ㄱ in self.줄들 if ㄱ.키 == self.지금키), None)

    @property
    def 지금자리(self) -> int | None:
        차 = self.차례
        return next((i for i, ㄱ in enumerate(차, 1) if ㄱ.키 == self.지금키), None)

    @property
    def 플러스수(self) -> int:
        return sum(1 for ㄱ in self.차례 if ㄱ.수익률 > 0)


@dataclass(frozen=True)
class 변경후보:
    """한 구간이 낸 답. 후보가 없으면 `키`가 비고 `막힌까닭`이 찬다."""

    구간: str
    등급: str
    지금키: str = ""
    키: str = ""
    이름: str = ""
    지금수익률: float | None = None
    후보수익률: float | None = None
    거래수: int = 0
    지금자리: int | None = None
    전체수: int = 0
    플러스수: int = 0
    막힌까닭: str = ""
    #: 1순위 지침의 이름과 두 전략의 값. 시트에는 안 나가고 문장에만 쓴다.
    #: 순위가 수익률로 나지 않으므로, 무엇으로 앞섰는지를 안 적으면 표에서
    #: 수익률이 더 낮은 전략이 1위로 올라온 이유를 알 수 없다.
    일순위이름: str = ""
    일순위단위: str = ""
    지금일순위: float | None = None
    후보일순위: float | None = None

    @property
    def 있나(self) -> bool:
        return bool(self.키)


def _앞서나(후보: float, 지금: float, 배수: float, 폭: float = 0.0) -> bool:
    """후보가 지금보다 충분히 앞서나.

    두 가지를 같이 본다. 하나는 비긴 폭이다. 이 폭 안의 차이는 같다고 본다.
    다른 하나는 배수인데, 지금 값이 플러스일 때만 건다.

    **음수에는 배수를 걸 수 없다.** -5의 1.15배는 -5.75라서 더 나쁜 값이
    기준이 된다. 가장 나빴던 구간처럼 값이 대체로 음수인 지침에서는 배수가
    뜻을 잃으므로, 그때는 폭 하나로 판단한다."""
    앞선폭 = 후보 - 지금
    if 앞선폭 <= 폭:
        return False
    if 지금 <= 0:
        return True
    return 후보 > 지금 * 배수


def 후보내기(
    순위: 구간순위,
    우위배수: float = 기본우위배수,
    막혔나: str = "",
) -> 변경후보:
    """한 구간의 순위에서 변경 후보를 낸다.

    `막혔나`가 비어 있지 않으면 계산과 무관하게 후보를 내지 않는다. 최소
    운용기간이나 데이터 이상처럼 이 구간 밖에서 정해지는 이유를 받는 자리다."""
    지금 = 순위.지금줄
    최고 = 순위.최고
    # 1순위 지침이 무엇인지에 따라 앞섰다는 말의 뜻이 달라진다. 지침이 없으면
    # (설정이 성하지 않으면) 수익률로 돌아간다. 순위를 아예 못 내면 검토가
    # 통째로 멈추는데, 그것이 지침 하나가 기본값인 것보다 나쁘다.
    일순위 = next(iter(순위.기준.지침들), None)
    잰값 = (lambda ㄱ: ㄱ.성적.수익률) if 일순위 is None else (lambda ㄱ: 일순위.값(ㄱ.성적))
    공통 = {
        "구간": 순위.구간,
        "지금키": 순위.지금키,
        "지금수익률": 지금.수익률 if 지금 else None,
        "지금자리": 순위.지금자리,
        "전체수": len(순위.차례),
        "플러스수": 순위.플러스수,
        "일순위이름": 일순위.이름 if 일순위 else "누적 수익률",
        "일순위단위": 일순위.단위 if 일순위 else "%",
        "지금일순위": 잰값(지금) if 지금 else None,
        "후보일순위": 잰값(최고) if 최고 else None,
    }

    if 막혔나:
        return 변경후보(등급="이상없음", 막힌까닭=막혔나, **공통)

    if 최고 is None:
        return 변경후보(
            등급="이상없음",
            막힌까닭="이 구간에 매수가 발생한 전략이 없습니다.",
            **공통,
        )

    if 최고.키 == 순위.지금키:
        return 변경후보(
            등급="이상없음",
            막힌까닭="이 구간의 1위가 현재 설정된 전략입니다.",
            **공통,
        )

    if 지금 is None:
        return 변경후보(
            등급="살펴볼것",
            막힌까닭=(
                "현재 설정된 전략이 이 구간에서 매수를 하지 않아 비교할 수 "
                "없습니다."
            ),
            **공통,
        )

    # 1순위 값을 못 잰 전략은 후보로 올리지 않는다. 못 잰 것을 0으로 놓고
    # 견주면 값이 없는 전략이 1위로 올라온다.
    if 공통["후보일순위"] is None or 공통["지금일순위"] is None:
        못잰쪽 = 최고.이름 if 공통["후보일순위"] is None else "현재 전략"
        return 변경후보(
            등급="살펴볼것",
            막힌까닭=(
                f"{못잰쪽}의 {공통['일순위이름']} 값을 계산하지 못해 견줄 수 "
                "없습니다."
            ),
            **공통,
        )

    폭 = 일순위.비긴폭 if 일순위 else 0.0
    if not _앞서나(공통["후보일순위"], 공통["지금일순위"], 우위배수, 폭):
        return 변경후보(
            등급="이상없음",
            막힌까닭=(
                f"1위 {최고.이름}{이가(최고.이름)} {공통['일순위이름']} "
                f"{공통['후보일순위']:+.2f}{공통['일순위단위']}로 앞서지만 "
                f"현재 전략 {공통['지금일순위']:+.2f}{공통['일순위단위']} 대비 "
                "차이가 기준에 못 미칩니다."
            ),
            **공통,
        )

    # 여기부터는 후보를 낸다. 표본이 모자라면 등급을 낮춘다.
    등급 = "확인필요" if 최고.거래수 >= 최소거래수 else "살펴볼것"
    까닭 = ""
    if 최고.거래수 < 최소거래수:
        까닭 = (
            f"거래가 {최고.거래수}건으로 {최소거래수}건에 못 미칩니다. "
            "일부 종목의 결과가 전체를 좌우할 수 있습니다."
        )

    return 변경후보(
        등급=등급,
        키=최고.키,
        이름=최고.이름,
        후보수익률=최고.수익률,
        거래수=최고.거래수,
        막힌까닭=까닭,
        **공통,
    )


def 모아등급(후보들: list[변경후보]) -> str:
    등급 = "이상없음"
    for ㄱ in 후보들:
        등급 = 더센등급(등급, ㄱ.등급)
    return 등급


def 겹치는후보(후보들: list[변경후보]) -> dict[str, list[str]]:
    """같은 전략을 가리킨 구간끼리 묶는다. 열쇠는 전략 키다.

    세 구간이 같은 전략을 가리키면 그 사실이 한 구간짜리보다 강한 근거다.
    화면과 알림이 그것을 앞에 놓을 수 있게 여기서 묶어 준다."""
    묶음: dict[str, list[str]] = {}
    for ㄱ in 후보들:
        if ㄱ.있나:
            묶음.setdefault(ㄱ.키, []).append(ㄱ.구간)
    return 묶음


def 후보글(후보: 변경후보) -> str:
    """후보 하나를 문장으로. 화면과 텔레그램과 시트가 같은 문장을 쓴다."""
    앞 = f"[{후보.구간}]"
    if not 후보.있나:
        return f"{앞} {후보.막힌까닭}" if 후보.막힌까닭 else f"{앞} 변경 후보가 없습니다."

    말 = [
        f"{앞} {후보.이름} {후보.후보수익률:+.2f}% (거래 {후보.거래수}건)."
    ]
    # 무엇으로 앞섰는지를 같이 적는다. 순위가 수익률로 나지 않으므로, 이 말이
    # 없으면 수익률이 더 낮은 전략이 1위인 표를 읽을 방법이 없다.
    if 후보.일순위이름 and 후보.후보일순위 is not None:
        ㄴ = f"{후보.일순위이름} {후보.후보일순위:+.2f}{후보.일순위단위}"
        if 후보.지금일순위 is not None:
            ㄴ += f" (현재 전략 {후보.지금일순위:+.2f}{후보.일순위단위})"
        말.append(f"순위 기준은 {ㄴ}입니다.")
    if 후보.지금수익률 is not None and 후보.지금자리:
        말.append(
            f"현재 전략은 {후보.전체수}개 중 {후보.지금자리}위, "
            f"{후보.지금수익률:+.2f}%입니다."
        )
    말.append(f"매수가 발생한 전략 {후보.전체수}개 중 플러스는 {후보.플러스수}개입니다.")
    if 후보.막힌까닭:
        말.append(후보.막힌까닭)
    return " ".join(말)


def 총평(후보들: list[변경후보], 등급: str) -> str:
    """구간 여럿을 합쳐 한 문단.

    **어느 문장도 특정 전략으로 바꾸라고 말하지 않는다.** 무엇이 앞섰는지와
    구간끼리 답이 모이는지 갈리는지만 적는다."""
    있는것 = [ㄱ for ㄱ in 후보들 if ㄱ.있나]
    if not 있는것:
        return (
            "모든 구간에서 현재 설정된 전략을 변경할 사유가 나오지 않았습니다. "
            "수익성이 양호하다는 의미가 아니라, 다른 전략이 기준 이상으로 "
            "앞서지 않았다는 의미입니다."
        )

    묶음 = 겹치는후보(있는것)
    말: list[str] = []
    여럿 = {키: 구간들 for 키, 구간들 in 묶음.items() if len(구간들) > 1}
    if 여럿:
        for 키, 구간들 in 여럿.items():
            이름 = next(ㄱ.이름 for ㄱ in 있는것 if ㄱ.키 == 키)
            말.append(
                f"{이름}{이가(이름)} {', '.join(구간들)} 구간에서 함께 앞섭니다."
            )
    if len(묶음) > 1:
        말.append(
            f"구간별로 앞선 전략이 {len(묶음)}개로 갈립니다. "
            "특정 구간의 결과에 맞춰 선택하면 과최적화가 발생합니다."
        )

    말.append(
        "이 결과는 전략 변경을 권고하는 것이 아니라 검토 대상을 제시하는 "
        "것입니다. 변경 여부는 사람이 판단합니다."
    )
    if 등급 == "살펴볼것":
        말.append("표본이 기준에 못 미치는 구간이 있어 등급을 낮춰 표시했습니다.")
    return " ".join(말)
