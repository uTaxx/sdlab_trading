    # 손절 감시는 2026-09-02에 5분마다에서 30분마다로 줄었다. cron이
    # `0,30 9-14`와 `0 15`라 마지막 실행이 15:00이다. 화면은 15:20까지
    # 도는 것처럼 적고 있었고 2026-09-03에 고쳤다.
    assert 평일 == {
        "08:20", "08:30", "09:00~15:00", "09:05",
        "15:40", "17:30", "17:40", "17:50", "20:00",
    }, sorted(평일)
    assert 주말 == {"토 09:00"}, sorted(주말)


