  /* 전략을 다시 볼 이유가 있나.

     **문장은 파이썬이 만든다.** 화면은 등급에 맞는 색만 고른다. 여기서
     문장을 만들면 시트에 남은 기록과 화면이 다른 말을 하게 된다. */
  function 전략신호그리기(볼것) {
    const 있는것 = 볼것.find((ㄱ) => ㄱ.신호);
    if (!있는것) { $("전략신호").innerHTML = ""; return; }

    const 등급 = String(있는것.신호등급 || "이상없음");
    const 순한가 = 등급 === "이상없음";
    const 머리 = { 이상없음: "이상 없음. 전략을 재검토할 사유가 발견되지 않았습니다",
                 살펴볼것: "살펴볼 것. 확인이 권장되는 항목이 있습니다",
                 확인필요: "확인 필요. 즉시 확인이 필요한 항목이 있습니다" }[등급] || 등급;

    // 파이썬이 줄바꿈으로 나눠 보낸다. 한 줄이 신호 하나다.
    const 줄들 = String(있는것.신호).split("\n").filter((ㄱ) => ㄱ.trim());
    $("전략신호").innerHTML =
      `<div class="알림${순한가 ? " 순한" : ""}" style="margin-top:14px">
         <strong>${안전(머리)}</strong>
         ${줄들.map((ㄱ) => `<div style="margin-top:6px">${안전(ㄱ)}</div>`).join("")}
         <div class="곁말" style="margin-top:8px">
           ${안전(있는것.잰때)} 검증 결과를 기준으로 산출한 신호입니다.
         </div>
       </div>`;
  }

  //: 지난 회차. 한 회차만 보고 판단하지 않도록 흐름을 같이 보여 준다.
  function 검증이력그리기(줄들, 이번것) {
    const 이번때 = new Set(이번것.map((ㄱ) => `${ㄱ.잰때}|${ㄱ.기간}`));
    const 지난것 = 줄들
      .filter((ㄱ) => ㄱ.상태 === "됨" && !이번때.has(`${ㄱ.잰때}|${ㄱ.기간}`))
      .sort((ㄱ, ㄴ) => String(ㄴ.잰때).localeCompare(String(ㄱ.잰때)));

    보이기("검증이력싸개", 지난것.length > 0);
    if (!지난것.length) { $("검증이력몸").innerHTML = ""; return; }

    $("검증이력몸").innerHTML = 지난것.map((ㄱ) => `<tr>
      <td>${안전(ㄱ.잰때)}</td>
      <td>${안전(ㄱ.기간)}</td>
      <td class="${색(ㄱ.수익률)}">${퍼센트(ㄱ.수익률)}</td>
      <td class="내림">${퍼센트(ㄱ.최대낙폭)}</td>
      <td>${Number(ㄱ.거래수 ?? 0)}</td>
      <td>${안전(전략이름들(ㄱ.매수전략))}</td>
    </tr>`).join("");
  }

