def test_한_건도_안_샀으면_그렇다고_적는다():
    """0%가 "지켰다"로 읽히면 안 된다. 그 기간에 아무것도 안 산 것이다."""
    줄들 = [
        _잰줄(오늘, "3개월", "지금것", 5.3, 뒤거래수=3, 지금것=True, 자리=21),
        _잰줄(오늘, "3개월", "후보", 0.0, 뒤거래수=0, 제안것=True, 자리=1),
    ]
    (ㅂ,) = 비교하기(줄들)
    assert ㅂ.매수없었나 is True
    assert 모아보기([ㅂ]).매수없던수 == 1
    assert "한 종목도 매수하지 않아" in 학습글(모아보기([ㅂ]))


def test_양쪽_다_샀으면_그_문장은_안_나온다():
    """이유가 없는데 한 줄 붙이면 매번 뜨고, 매번 뜨는 것은 안 읽힌다."""
    줄들 = [
        _잰줄(오늘, "3개월", "지금것", 5.3, 뒤거래수=3, 지금것=True, 자리=21),
        _잰줄(오늘, "3개월", "후보", 1.0, 뒤거래수=2, 제안것=True, 자리=1),
    ]
    assert "매수하지 않아" not in 학습글(모아보기(비교하기(줄들)))
