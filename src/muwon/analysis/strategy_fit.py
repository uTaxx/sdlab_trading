"""구간마다 어느 전략이 좋았나, 그리고 바꿀 만한가.

## 이 파일이 하는 일

구간(1주·1개월·3개월)마다 등록된 전략을 전부 같은 시세로 계산한 결과를
받아, 순위를 내고 **구간마다 변경 후보를 하나씩** 낸다. 구간이 셋이면
후보도 최대 셋이고, 셋이 다른 전략일 수 있다. 어느 것을 고를지는 사람이
정한다.

## 왜 구간마다 따로 내나

한 구간의 1위를 그대로 걸면 그 구간에 맞춘 것이 된다. 구간마다 따로 내면
**세 답이 갈리는지 모이는지가 보인다.** 세 구간이 같은 전략을 가리키면 그
근거는 한 구간짜리보다 강하고, 갈리면 갈린다는 사실 자체가 정보다.

2026-08-28 검증에서 3개월 1위가 12개월에서는 하위권이었다. 그때 3개월만
봤으면 그 사실을 못 봤다.

## 제안을 막는 자리

아래 중 하나라도 걸리면 후보를 내지 않고 **왜 안 냈는지를 적는다.**

- 거래가 문턱에 못 미친다 (구간이 짧으면 거의 항상 걸린다)
- 1위가 지금 걸린 전략이다
- 전략을 바꾼 지 최소 운용기간이 안 지났다
- 계산이 실패했거나 시세가 모자랐다

**막힌 이유를 적는 것이 후보를 내는 것만큼 중요하다.** 아무 말도 없으면
"오늘은 볼 것이 없다"와 "오늘은 계산이 안 됐다"가 구별되지 않는다.

## 등급

`period_check`와 같은 세 등급을 쓴다. 같은 말이 두 화면에서 다른 뜻이면
안 된다.

- 이상없음: 지금 걸린 전략을 바꿀 이유가 이 구간에서 안 나왔다
- 살펴볼것: 다른 전략이 앞서지만 표본이나 폭이 판단하기에 모자라다
- 확인필요: 다른 전략이 표본과 폭을 다 갖추고 앞선다

**어느 등급도 "바꿔라"라고 말하지 않는다.** 후보를 보여 주고 판단을 사람에게
넘긴다.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from muwon.analysis.period_check import 기간성적

#: 이 배수만큼 앞서야 후보로 올린다. 조금 앞서는 것으로 바꾸면 매번 바뀐다.
#: 지침서 8.1의 Score Hysteresis와 같은 장치다.
기본우위배수 = 1.15

#: 전략을 바꾼 뒤 이만큼 거래일이 지나기 전에는 후보를 내지 않는다.
기본최소운용일 = 30

#: 이 구간에서 이만큼은 거래가 있어야 순위를 판단에 쓴다. period_check와
#: 같은 값이어야 한다. 두 곳이 어긋나면 같은 줄이 화면마다 다르게 보인다.
최소거래수 = 20

등급들 = ("이상없음", "살펴볼것", "확인필요")


def 조사(말: str, 받침있을때: str, 받침없을때: str) -> str:
    """앞말의 받침에 따라 조사를 고른다. "변동성 돌파이"는 안 읽힌다.

    전략 이름이 설정에서 오므로 무엇이 올지 모른다. 한글이 아니면(영문 키가
    그대로 나오는 경우) 받침 없는 쪽으로 둔다. 둘 중 하나는 골라야 하고,
    "volume_surge_3d가"가 "volume_surge_3d이"보다 낫다."""
    끝 = (말 or "").strip()[-1:]
    if not 끝 or not ("가" <= 끝 <= "힣"):
        return 받침없을때
    return 받침있을때 if (ord(끝) - 0xAC00) % 28 else 받침없을때


def 이가(말: str) -> str:
    return 조사(말, "이", "가")


def 은는(말: str) -> str:
    return 조사(말, "은", "는")


def 더센등급(ㄱ: str, ㄴ: str) -> str:
    return 등급들[max(등급들.index(ㄱ), 등급들.index(ㄴ))]


@dataclass(frozen=True)
class 전략줄:
    """한 구간에서 전략 하나의 성적."""

    키: str
    이름: str
    성적: 기간성적

    @property
    def 수익률(self) -> float:
        return self.성적.수익률

    @property
    def 거래수(self) -> int:
        return self.성적.metrics.num_trades


@dataclass(frozen=True)
class 구간순위:
    """한 구간의 전략 순위.

    **매수가 한 건도 없던 전략은 순위에서 뺀다.** 수익률 0%로 위에 올라오는데
    그건 손실을 막은 것이 아니라 거래가 없었던 것이다."""

    구간: str
    줄들: list[전략줄] = field(default_factory=list)
    지금키: str = ""

    @property
    def 산것(self) -> list[전략줄]:
        return [ㄱ for ㄱ in self.줄들 if ㄱ.거래수 > 0]

    @property
    def 차례(self) -> list[전략줄]:
        return sorted(self.산것, key=lambda ㄱ: -ㄱ.수익률)

    @property
    def 최고(self) -> 전략줄 | None:
        차 = self.차례
        return 차[0] if 차 else None

    @property
    def 지금줄(self) -> 전략줄 | None:
        return next((ㄱ for ㄱ in self.줄들 if ㄱ.키 == self.지금키), None)

    @property
    def 지금자리(self) -> int | None:
        차 = self.차례
        return next((i for i, ㄱ in enumerate(차, 1) if ㄱ.키 == self.지금키), None)

    @property
    def 플러스수(self) -> int:
        return sum(1 for ㄱ in self.차례 if ㄱ.수익률 > 0)


@dataclass(frozen=True)
class 변경후보:
    """한 구간이 낸 답. 후보가 없으면 `키`가 비고 `막힌까닭`이 찬다."""

    구간: str
    등급: str
    지금키: str = ""
    키: str = ""
    이름: str = ""
    지금수익률: float | None = None
    후보수익률: float | None = None
    거래수: int = 0
    지금자리: int | None = None
    전체수: int = 0
    플러스수: int = 0
    막힌까닭: str = ""

    @property
    def 있나(self) -> bool:
        return bool(self.키)


def _앞서나(후보: float, 지금: float, 배수: float) -> bool:
    """후보가 지금보다 충분히 앞서나.

    수익률은 음수가 될 수 있어서 그냥 곱하면 부호에서 뒤집힌다. 지금이
    마이너스일 때는 '덜 잃었나'를 보고, 플러스일 때만 배수를 건다."""
    if 지금 <= 0:
        return 후보 > 0
    return 후보 > 지금 * 배수


def 후보내기(
    순위: 구간순위,
    우위배수: float = 기본우위배수,
    막혔나: str = "",
) -> 변경후보:
    """한 구간의 순위에서 변경 후보를 낸다.

    `막혔나`가 비어 있지 않으면 계산과 무관하게 후보를 내지 않는다. 최소
    운용기간이나 데이터 이상처럼 이 구간 밖에서 정해지는 이유를 받는 자리다."""
    지금 = 순위.지금줄
    최고 = 순위.최고
    공통 = {
        "구간": 순위.구간,
        "지금키": 순위.지금키,
        "지금수익률": 지금.수익률 if 지금 else None,
        "지금자리": 순위.지금자리,
        "전체수": len(순위.차례),
        "플러스수": 순위.플러스수,
    }

    if 막혔나:
        return 변경후보(등급="이상없음", 막힌까닭=막혔나, **공통)

    if 최고 is None:
        return 변경후보(
            등급="이상없음",
            막힌까닭="이 구간에 매수가 발생한 전략이 없습니다.",
            **공통,
        )

    if 최고.키 == 순위.지금키:
        return 변경후보(
            등급="이상없음",
            막힌까닭="이 구간의 1위가 현재 설정된 전략입니다.",
            **공통,
        )

    if 지금 is None:
        return 변경후보(
            등급="살펴볼것",
            막힌까닭=(
                "현재 설정된 전략이 이 구간에서 매수를 하지 않아 비교할 수 "
                "없습니다."
            ),
            **공통,
        )

    if not _앞서나(최고.수익률, 지금.수익률, 우위배수):
        return 변경후보(
            등급="이상없음",
            막힌까닭=(
                f"1위 {최고.이름}{이가(최고.이름)} {최고.수익률:+.2f}%로 앞서지만 "
                f"현재 전략 {지금.수익률:+.2f}% 대비 차이가 기준에 못 미칩니다."
            ),
            **공통,
        )

    # 여기부터는 후보를 낸다. 표본이 모자라면 등급을 낮춘다.
    등급 = "확인필요" if 최고.거래수 >= 최소거래수 else "살펴볼것"
    까닭 = ""
    if 최고.거래수 < 최소거래수:
        까닭 = (
            f"거래가 {최고.거래수}건으로 {최소거래수}건에 못 미칩니다. "
            "일부 종목의 결과가 전체를 좌우할 수 있습니다."
        )

    return 변경후보(
        등급=등급,
        키=최고.키,
        이름=최고.이름,
        후보수익률=최고.수익률,
        거래수=최고.거래수,
        막힌까닭=까닭,
        **공통,
    )


def 모아등급(후보들: list[변경후보]) -> str:
    등급 = "이상없음"
    for ㄱ in 후보들:
        등급 = 더센등급(등급, ㄱ.등급)
    return 등급


def 겹치는후보(후보들: list[변경후보]) -> dict[str, list[str]]:
    """같은 전략을 가리킨 구간끼리 묶는다. 열쇠는 전략 키다.

    세 구간이 같은 전략을 가리키면 그 사실이 한 구간짜리보다 강한 근거다.
    화면과 알림이 그것을 앞에 놓을 수 있게 여기서 묶어 준다."""
    묶음: dict[str, list[str]] = {}
    for ㄱ in 후보들:
        if ㄱ.있나:
            묶음.setdefault(ㄱ.키, []).append(ㄱ.구간)
    return 묶음


def 후보글(후보: 변경후보) -> str:
    """후보 하나를 문장으로. 화면과 텔레그램과 시트가 같은 문장을 쓴다."""
    앞 = f"[{후보.구간}]"
    if not 후보.있나:
        return f"{앞} {후보.막힌까닭}" if 후보.막힌까닭 else f"{앞} 변경 후보가 없습니다."

    말 = [
        f"{앞} {후보.이름} {후보.후보수익률:+.2f}% (거래 {후보.거래수}건)."
    ]
    if 후보.지금수익률 is not None and 후보.지금자리:
        말.append(
            f"현재 전략은 {후보.전체수}개 중 {후보.지금자리}위, "
            f"{후보.지금수익률:+.2f}%입니다."
        )
    말.append(f"매수가 발생한 전략 {후보.전체수}개 중 플러스는 {후보.플러스수}개입니다.")
    if 후보.막힌까닭:
        말.append(후보.막힌까닭)
    return " ".join(말)


def 총평(후보들: list[변경후보], 등급: str) -> str:
    """구간 여럿을 합쳐 한 문단.

    **어느 문장도 특정 전략으로 바꾸라고 말하지 않는다.** 무엇이 앞섰는지와
    구간끼리 답이 모이는지 갈리는지만 적는다."""
    있는것 = [ㄱ for ㄱ in 후보들 if ㄱ.있나]
    if not 있는것:
        return (
            "모든 구간에서 현재 설정된 전략을 변경할 사유가 나오지 않았습니다. "
            "수익성이 양호하다는 의미가 아니라, 다른 전략이 기준 이상으로 "
            "앞서지 않았다는 의미입니다."
        )

    묶음 = 겹치는후보(있는것)
    말: list[str] = []
    여럿 = {키: 구간들 for 키, 구간들 in 묶음.items() if len(구간들) > 1}
    if 여럿:
        for 키, 구간들 in 여럿.items():
            이름 = next(ㄱ.이름 for ㄱ in 있는것 if ㄱ.키 == 키)
            말.append(
                f"{이름}{이가(이름)} {', '.join(구간들)} 구간에서 함께 앞섭니다."
            )
    if len(묶음) > 1:
        말.append(
            f"구간별로 앞선 전략이 {len(묶음)}개로 갈립니다. "
            "특정 구간의 결과에 맞춰 선택하면 과최적화가 발생합니다."
        )

    말.append(
        "이 결과는 전략 변경을 권고하는 것이 아니라 검토 대상을 제시하는 "
        "것입니다. 변경 여부는 사람이 판단합니다."
    )
    if 등급 == "살펴볼것":
        말.append("표본이 기준에 못 미치는 구간이 있어 등급을 낮춰 표시했습니다.")
    return " ".join(말)
