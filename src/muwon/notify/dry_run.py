"""흉내만 내는 실행이 보내는 알림에 그렇다고 적는다.

2026-08-25 아침, `--dry-run`으로 실행한 실행이 텔레그램에 이렇게 보냈다:

    🟢 매수 체결
    종목: ACE KRX금현물(411060)
    수량: 51주
    가격: 29,065원

실제 체결과 **글자 하나 안 다르다.** 받은 사람은 산 줄 알았고, 계좌를
열어 확인하고 나서야 아니라는 걸 알았다. 폰으로 알림만 보는 자리에서는
그 확인조차 못 한다.

알림은 "지금 무슨 일이 일어났는지"를 알리는 것이다. 안 일어난 일을
일어난 것처럼 알리면 알림이 아니라 거짓말이다.
"""

from __future__ import annotations

머리 = "🧪 모의 실행입니다. 실제 주문이 아닙니다."


class 모의알림:
    """감싼 알림기로 보내되 맨 위에 모의라는 줄을 붙인다.

    감싸는 쪽으로 만든 이유는, 알림을 보내는 곳이 엔진 안(매수·매도 체결)과
    스크립트 끝(결과 요약) 둘로 나뉘어 있기 때문이다. 각자 붙이게 하면
    한쪽을 빠뜨리고, 빠뜨린 줄도 모른다.
    """

    def __init__(self, 진짜):
        self._진짜 = 진짜

    def send(self, message: str, *, 꼬리: bool = True) -> None:
        self._진짜.send(f"{머리}\n\n{message}", 꼬리=꼬리)

    def send_long(self, message: str) -> int:
        return self._진짜.send_long(f"{머리}\n\n{message}")
