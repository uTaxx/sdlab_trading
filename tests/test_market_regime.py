    # 하락에서 조정으로 나오려면 −17%보다 위여야 한다.
    assert ㄱ.이름표(-18.0) == ㄱ.조정
    assert ㄱ.이름표(-18.0, 앞국면=ㄱ.하락) == ㄱ.하락
    assert ㄱ.이름표(-16.0, 앞국면=ㄱ.하락) == ㄱ.조정


