def _지표(수익률: float, 거래: int = 30) -> BacktestMetrics:
    return BacktestMetrics(
        total_return_pct=수익률,
        cagr_pct=수익률,
        max_drawdown_pct=-10.0,
        sharpe=1.0,
        sortino=1.0,
        profit_factor=1.2,
        expectancy_pct=0.5,
        win_rate_pct=45.0,
        num_trades=거래,
        avg_holding_days=5.0,
        exposure_pct=80.0,
        turnover=1.0,
    )


def _성적(수익률: float, 거래: int = 30, 모자람: str = "") -> 기간성적:
    return 기간성적(
        이름="30일 뒤",
        시작=오늘 - timedelta(days=30),
        끝=오늘,
        metrics=_지표(수익률, 거래),
        모자람=모자람,
    )


def _순위(줄들: list[tuple[str, float, int]], 지금키: str) -> 구간순위:
    return 구간순위(
        구간="3개월",
        지금키=지금키,
        줄들=[
            전략줄(키=키, 이름=f"{키} 이름", 성적=_성적(수익률, 거래))
            for 키, 수익률, 거래 in 줄들
        ],
    )


def _남기기(ㅅ, 제안일, 구간, 전략, **칸):
    줄 = StrategyShadowRow(제안일=제안일, 구간=구간, 전략=전략, **칸)
    ㅅ.add(줄)
    ㅅ.flush()
    return 줄


