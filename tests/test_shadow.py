def test_바꾸라는_말은_하지_않는다():
    """한 구간에서 좋았던 쪽으로 옮기는 것이 곧 과최적화다."""
    글 = 학습글(모아보기(_비교들([5.0] * 25)))
    for 금지 in ("바꾸", "추천", "권장", "좋은 전략", "갈아"):
        assert 금지 not in 글


def test_사람에게_가는_글에_줄표를_안_쓴다():
    for 차이들 in ([], [1.0, 2.0], [5.0] * 25):
        assert "—" not in 학습글(모아보기(_비교들(차이들)))


