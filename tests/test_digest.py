"""텔레그램 요약 검증.

안 읽는 알림은 없는 것과 같고, 오히려 진짜 중요한 알림을 묻는다.
그래서 짧아야 하고, 짧게 줄이는 과정에서 경고가 빠지면 안 된다.

## 2026-08-26에 다시 쓴 이유

8월 25일에 "한 줄도 이해할 수 없다"는 말을 듣고 모든 용어를 풀어 썼는데
반대로 망가졌다. 받아 보는 사람이 "단어도 문장도 하나도 이해가 안 된다"고
했다. 이 파일도 그때 문구를 글자 그대로 고정하고 있었다. "이런 자리는 몇
해에 한 번 볼까 말까 합니다", "동전을 그만큼 던져도", "우연 범위 안" 같은
것들이다. 그 검사들은 문장을 검사한 것이지 내용을 검사한 것이 아니라서,
글을 고치려면 먼저 이 파일을 고쳐야 하는 상태였다.

지금 이 파일이 지키는 것은 내용 넷뿐이다.

1. z점수가 사용자에게 그대로 나가지 않는다.
2. 값이 없으면 지어내지 않는다.
3. 숫자 옆에 견줄 값이 있다.
4. 기각됐다는 사실과 표본 수가 요약에서 살아남는다.

문장이 어떻게 생겼는지는 검사하지 않는다.
"""

from datetime import date

import pandas as pd

from muwon.market.analog import Baseline, Forecast
from muwon.market.digest import MAX_LEN, state_line, summarize


def _상태(추세=1.0, 낙폭=-2.0, 변동성=0.5):
    """z점수 표. 0이 평소, ±2면 드문 자리다. 이제는 화면에 안 나간다."""
    return pd.DataFrame(
        {"kospi_추세20": [추세], "kospi_고점대비": [낙폭], "kospi_변동성": [변동성]},
        index=[date(2026, 8, 19)],
    )


def _지수(값들=(3080.0, 3095.0, 3101.0, 3106.0, 3124.5)):
    """코스피 종가. 마지막 값이 오늘이다."""
    from datetime import timedelta

    날들 = [date(2026, 8, 19) - timedelta(days=len(값들) - 1 - ㄱ) for ㄱ in range(len(값들))]
    return pd.Series(list(값들), index=날들)


def _원시(추세=0.018, 낙폭=-0.123, 변동성=0.0142):
    """원래 단위 표. 고점대비 -0.123은 '고점에서 12.3% 아래'다."""
    return pd.DataFrame(
        {"kospi_추세20": [추세], "kospi_고점대비": [낙폭], "kospi_변동성": [변동성]},
        index=[date(2026, 8, 19)],
    )


def _전망(대상="반도체", 상승확률=70.0, 기준선=55.0, 구간수=16, 낼수있나=True):
    return Forecast(
        기준일=date(2026, 8, 19), 대상=대상, 구간수=구간수, 총일수=200, 지평=20,
        중앙값=2.0 if 낼수있나 else None,
        상위25=6.0 if 낼수있나 else None,
        하위25=-1.0 if 낼수있나 else None,
        하위10=-8.0 if 낼수있나 else None,
        상승확률=상승확률 if 낼수있나 else None,
        구간들=[],
        사유="" if 낼수있나 else "비슷했던 때가 3번뿐입니다",
        기준선=Baseline(표본수=1000, 중앙값=1.0, 하위10=-9.0, 상승확률=기준선),
    )


# ── 장 상태 ──────────────────────────────────────────────────────────────


def test_z점수를_숫자로_내보내지_않는다():
    """z점수는 '평소에 견줘 얼마나 벗어났나'이지 퍼센트가 아니다.

    `고점대비 -2.8`을 그대로 찍었더니 "고점에서 2.8% 빠졌다"로 읽혔다."""
    글 = state_line(_상태(추세=0.8, 낙폭=-2.8), _원시(), _지수())

    assert "-2.8" not in 글 and "+0.8" not in 글
    assert "12.3%" in 글, "z점수 대신 원래 값이 있어야 한다"


def test_지수_값과_어제_대비를_맨_위에_적는다():
    글 = state_line(_상태(), _원시(), _지수())

    assert "3,124" in 글
    assert "어제보다 +0.6%" in 글


def test_숫자마다_견줄_값이_옆에_있다():
    """비율만으로는 무엇과 견준 것인지 안 보인다."""
    글 = state_line(_상태(), _원시(), _지수())

    assert "3,069" in 글, "20일 평균값이 있어야 한다"
    assert "1.8%" in 글
    assert "12.3%" in 글


def test_1년_최고가_얼마였는지도_적는다():
    글 = state_line(_상태(), _원시(), _지수())

    assert "1년 최고 3,563" in 글, "3124.5 / (1-0.123)"


def test_지수를_못_받으면_지어내지_않는다():
    글 = state_line(_상태(), _원시(), None)

    assert "3,124" not in 글
    assert "20일 평균보다 1.8% 위입니다." in 글, "기준값 없이 비율만 적는다"


def test_내리는_중이면_아래라고_적는다():
    글 = state_line(_상태(추세=-1.2), _원시(추세=-0.021), _지수())

    assert "2.1% 아래입니다" in 글


def test_원시값이_없으면_그_줄을_아예_쓰지_않는다():
    """말로 때우느니 비우는 편이 낫다. 지어낸 숫자는 나중에 검증이 안 된다."""
    글 = state_line(_상태(), None, None)

    assert "%" not in 글
    assert "지표를 못 읽었습니다" in 글


def test_평소_등락과_견준다():
    """2.8%만 보면 그게 큰 건지 작은 건지 알 수가 없다."""
    from datetime import timedelta

    날들 = [date(2026, 8, 19) - timedelta(days=1200 - ㄱ) for ㄱ in range(1200)]
    원시 = pd.DataFrame({"kospi_변동성": [0.012] * 1199 + [0.028]}, index=날들)
    상태 = pd.DataFrame({"kospi_변동성": [1.6]}, index=[날들[-1]])

    글 = state_line(상태, 원시, None)

    assert "2.8%" in 글
    assert "평소 1.2%" in 글
    assert "손절선에 걸리기 쉽습니다" in 글, "평소의 1.5배가 넘으면 뜻까지 적는다"


def test_평소를_모르면_평소를_말하지_않는다():
    글 = state_line(_상태(), _원시(), None)

    assert "2.8%" not in 글
    assert "평소" not in 글


def test_잴_수_없으면_그렇게_말한다():
    assert "아직 잴 수 없습니다" in state_line(pd.DataFrame())


# ── 요약 전체 ────────────────────────────────────────────────────────────


def test_기각됐다는_말이_요약에서_살아남는다():
    글 = summarize(_상태(), [_전망()], date(2026, 8, 19), 원시=_원시(), 지수=_지수())

    assert "매매에는 쓰지 않습니다" in 글
    assert "51.8%" in 글 and "56.3%" in 글, "왜 못 믿는지 숫자로 보여야 한다"
    assert "주문은 한 건도 내지 않았습니다" in 글


def test_경고가_섹터_숫자보다_먼저_나온다():
    글 = summarize(_상태(), [_전망(상승확률=94.0, 기준선=58.0)], date(2026, 8, 19),
                  원시=_원시(), 지수=_지수())

    assert 글.index("기각했습니다") < 글.index("올랐습니다")


def test_섹터줄에_표본수가_있다():
    """'94%'만 보면 대단해 보인다. '16번 중 15번'이 있어야 표본이 보인다."""
    글 = summarize(_상태(), [_전망(상승확률=94.0, 기준선=58.0, 구간수=16)],
                  date(2026, 8, 19), 원시=_원시(), 지수=_지수())

    assert "16번 중 15번(94%)" in 글
    assert "아무 날에나 샀다면 58%입니다" in 글


def test_우연과_구분_안_되는_섹터는_숫자를_안_적는다():
    """구간 16개면 우연만으로도 ±24%p가 벌어진다. 그걸 줄줄이 적으면
    경고를 아무리 위에 둬도 숫자가 이긴다."""
    글 = summarize(
        _상태(),
        [_전망(대상="바이오", 상승확률=94.0, 기준선=58.0, 구간수=16),
         _전망(대상="반도체", 상승확률=67.0, 기준선=62.0, 구간수=18)],
        date(2026, 8, 19), 원시=_원시(), 지수=_지수(),
    )

    assert "바이오" in 글
    assert "반도체" not in 글
    assert "나머지 1개 섹터" in 글


def test_눈에_띈_섹터가_없으면_없다고_말한다():
    글 = summarize(_상태(), [_전망(상승확률=57.0, 기준선=55.0)],
                  date(2026, 8, 19), 원시=_원시(), 지수=_지수())

    assert "눈에 띄게 벌어진 섹터가 없습니다" in 글


