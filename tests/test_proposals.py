"""기준 제안.

**규칙 하나가 전부다. 근거 없는 제안은 하지 않는다.** 그래서 시험도
'무엇을 제안하나'만큼 '언제 입을 다무나'를 본다."""

from muwon.settings.proposals import (
    권함,
    도달할_수_없는_수인가,
    모아서,
    아직_모르는것,
    완전자동인가,
    최소기준에_걸린_종목,
    현금이_모자라나,
)


def test_비중과_동시보유가_100을_넘으면_제안한다():
    """의견이 아니라 산수다. 15% × 8 = 120%인데 현금은 100%뿐이다."""
    p = 현금이_모자라나(15, 8)
    assert p is not None
    assert p.바꿀값 == 6      # 100 // 15
    assert p.급한가 == 권함
    assert "120%" in p.근거
    assert "/설정 max_concurrent_positions 6" in p.글()


def test_100을_안_넘으면_아무_말도_안_한다():
    assert 현금이_모자라나(12, 8) is None   # 96%
    assert 현금이_모자라나(10, 10) is None  # 100% 딱


def test_닿을_수_없는_동시보유_수를_알려준다():
    """숫자가 있으면 지키고 있다고 착각하게 된다."""
    p = 도달할_수_없는_수인가(동시보유=8, 섹터수=3, 섹터당=2)
    assert p is not None and p.바꿀값 == 6


def test_섹터_제한이_없으면_그_말은_안_한다():
    assert 도달할_수_없는_수인가(동시보유=8, 섹터수=7, 섹터당=0) is None
    assert 도달할_수_없는_수인가(동시보유=8, 섹터수=7, 섹터당=2) is None  # 14 ≥ 8


def test_최소기준에_걸린_종목을_세어_준다():
    p = 최소기준에_걸린_종목(50, {"A": 10, "B": 100, "C": 30}, {"A": "가나", "C": "다라"})
    assert p is not None
    assert "2개(67%)" in p.근거
    assert "가나 10억" in p.근거
    assert p.급한가 == 권함           # 30% 이상이면 권함


def test_아무도_안_걸리면_말을_안_한다():
    assert 최소기준에_걸린_종목(50, {"A": 100, "B": 200}) is None


def test_문턱을_낮추라고_하지_않는다():
    """문턱은 슬리피지를 막는 장치다. 낮추면 보호가 통째로 풀린다."""
    p = 최소기준에_걸린_종목(50, {"A": 10, "B": 100})
    assert "시트에서 끄는 쪽" in p.근거
    assert p.이름 == ""   # 값을 바꾸라는 제안이 아니다


def test_매매가_켜졌는데_승인이_꺼져_있으면_알린다():
    p = 완전자동인가(킬스위치=True, 승인필요=False)
    assert p is not None and p.바꿀값 is True


def test_매매가_꺼져_있으면_그_말은_안_한다():
    assert 완전자동인가(킬스위치=False, 승인필요=False) is None
    assert 완전자동인가(킬스위치=True, 승인필요=True) is None


def test_표본이_없으면_모른다고_말한다():
    """없는 근거를 지어내는 것보다 모른다고 하는 편이 낫다."""
    것들 = 아직_모르는것(매매수=0)
    assert len(것들) == 1
    assert "슬리피지 실측 표본이 없" in 것들[0].근거
    assert 것들[0].이름 == ""   # 무엇으로 바꾸라는 말은 안 한다


def test_표본이_생기면_그_말을_그만한다():
    assert 아직_모르는것(매매수=12) == []


def test_제안이_없으면_없다고_말한다():
    글 = 모아서([None, None])
    assert "못 찾았습니다" in 글


def test_급한_것이_위로_온다():
    글 = 모아서([아직_모르는것(0)[0], 현금이_모자라나(15, 8)])
    assert 글.index("동시 보유") < 글.index("슬리피지 실측 표본이 없")
