"""**기준을 이렇게 바꾸는 게 어떻겠냐고 제안한다.** 바꾸지는 않는다.

## 규칙 하나. 근거 없는 제안은 하지 않는다

"손절선을 -4%로 낮추면 좋을 것 같습니다" 같은 말은 안 한다. 그걸 뒷받침할
실측이 없기 때문이다. 대신 **"손절선은 근거가 없으니 아직 못 정한다"**고
말한다. 그게 정확한 상태다.

제안할 수 있는 것은 두 종류뿐이다.

**① 산수로 확인되는 것.** 한 종목 15% × 동시보유 8종목 = 120%인데 현금은
100%뿐이다. 이건 의견이 아니라 계산이다.

**② 세어 보면 나오는 것.** 유니버스 45종목 중 몇 개가 거래대금 문턱에
걸리나. 이것도 의견이 아니다.

나머지(손절선을 얼마로, 익절을 켤지)는 **모의투자를 돌려 표본이 쌓여야**
말할 수 있다. 그때까지는 모른다고 적는다.

## 왜 텔레그램으로 보내나

기준을 고칠 일은 폰을 보고 있을 때 생긴다. 제안과 고치는 수단이 같은 곳에
있어야 실제로 고쳐진다. 제안은 텔레그램으로 오고, 답도 텔레그램으로
`/설정 ...` 하면 된다.
"""

from __future__ import annotations

from dataclasses import dataclass

from muwon.settings.from_sheet import 값글자, 기준표

#: 급한 정도. 화면에서 눈이 먼저 가야 할 순서다.
권함, 생각, 알림 = "권함", "생각해 보세요", "알림"
순서 = {권함: 0, 생각: 1, 알림: 2}


@dataclass(frozen=True)
class 제안:
    이름: str          # 어느 기준인가 ("" 이면 그냥 알림)
    지금: object
    바꿀값: object
    근거: str
    급한가: str = 생각

    def 글(self) -> str:
        if not self.이름:
            return f"[{self.급한가}] {self.근거}"
        b = 기준표[self.이름]
        return "\n".join([
            f"[{self.급한가}] **{b.표시}** {값글자(b, self.지금)} → {값글자(b, self.바꿀값)}",
            f"    {self.근거}",
            f"    바꾸려면: /설정 {self.이름} {_명령값(b, self.바꿀값)}",
        ])


def _명령값(b, 것) -> str:
    if b.종류 == "참거짓":
        return "true" if 것 else "false"
    if b.종류 == "정수":
        return str(int(것))
    return f"{float(것):g}"


def 현금이_모자라나(비중_퍼센트: float, 동시보유: int) -> 제안 | None:
    """한 종목 비중 × 동시보유 수가 100%를 넘으면 뒤쪽 종목은 못 산다.

    **이건 의견이 아니라 산수다.** 넘는 만큼은 신호가 나도 현금이 없어서
    거부되는데, 로그에는 '리스크 매니저 거부'로만 남아 왜인지 알기 어렵다."""
    총합 = 비중_퍼센트 * 동시보유
    if 총합 <= 100:
        return None
    쓸수있는수 = max(1, int(100 // 비중_퍼센트))
    return 제안(
        이름="max_concurrent_positions",
        지금=동시보유,
        바꿀값=쓸수있는수,
        근거=(
            f"한 종목 {비중_퍼센트:g}% × {동시보유}종목 = {총합:g}%인데 현금은 100%입니다. "
            f"실제로는 {쓸수있는수}종목까지만 채워지고, 나머지는 신호가 나도 현금이 없어 "
            "거부됩니다. 로그에는 이유가 '리스크 매니저 거부'로만 남습니다."
        ),
        급한가=권함,
    )


def 도달할_수_없는_수인가(동시보유: int, 섹터수: int, 섹터당: int) -> 제안 | None:
    """섹터 수 × 섹터당 상한보다 동시보유 수가 크면, 그 수는 도달할 수 없다."""
    if 섹터당 <= 0 or 섹터수 <= 0:
        return None
    닿는곳 = 섹터수 * 섹터당
    if 동시보유 <= 닿는곳:
        return None
    return 제안(
        이름="max_concurrent_positions",
        지금=동시보유,
        바꿀값=닿는곳,
        근거=(
            f"섹터 {섹터수}개 × 섹터당 {섹터당}종목 = {닿는곳}종목이 실제 상한입니다. "
            f"{동시보유}은 닿을 수 없는 수라 제한 구실을 못 합니다. 숫자가 있으면 "
            "지키고 있다고 착각하게 됩니다."
        ),
        급한가=생각,
    )


def 최소기준에_걸린_종목(최소기준_억: float, 거래대금_억: dict[str, float], 이름표=None) -> 제안 | None:
    """유니버스 중 몇이 거래대금 문턱에 걸리나. **세어 보면 나오는 것이다.**"""
    if not 거래대금_억:
        return None
    이름표 = 이름표 or {}
    걸린것 = sorted(
        (심볼 for 심볼, 억 in 거래대금_억.items() if 억 < 최소기준_억),
        key=lambda s: 거래대금_억[s],
    )
    if not 걸린것:
        return None
    비율 = len(걸린것) / len(거래대금_억) * 100
    보기 = ", ".join(f"{이름표.get(s, s)} {거래대금_억[s]:.0f}억" for s in 걸린것[:5])
    급함 = 권함 if 비율 >= 30 else 알림
    return 제안(
        이름="",
        지금=None,
        바꿀값=None,
        근거=(
            f"유니버스 {len(거래대금_억)}종목 중 **{len(걸린것)}개({비율:.0f}%)**가 "
            f"거래대금 최소 기준 {최소기준_억:g}억에 걸려 못 삽니다: {보기}"
            + (" 등" if len(걸린것) > 5 else "")
            + "\n    문턱을 낮추기보다 **그 종목을 시트에서 끄는 쪽**을 권합니다. "
            "문턱은 슬리피지를 막는 장치라 낮추면 그 보호가 통째로 풀립니다."
        ),
        급한가=급함,
    )


def 완전자동인가(킬스위치: bool, 승인필요: bool) -> 제안 | None:
    """매매가 켜져 있는데 승인이 꺼져 있으면 사람 손이 안 닿는다."""
    if not 킬스위치 or 승인필요:
        return None
    return 제안(
        이름="require_approval",
        지금=False,
        바꿀값=True,
        근거=(
            "매매가 켜져 있는데 승인이 꺼져 있습니다. **사람 손을 거치지 않고 삽니다.** "
            "일부러 그러셨다면 그대로 두시면 됩니다. 다만 슬리피지 실측이 아직 0건이라 "
            "실제 체결이 어떻게 되는지 아무도 본 적이 없습니다."
        ),
        급한가=권함,
    )


def 아직_모르는것(매매수: int) -> list[제안]:
    """**모른다고 말하는 것도 제안이다.** 없는 근거를 지어내는 것보다 낫다."""
    if 매매수 > 0:
        return []
    return [
        제안("", None, None,
             "손절선·익절선은 아직 제안할 근거가 없습니다. 실거래 매매가 0건이라 "
             "**슬리피지 실측 표본이 없고**, 지금 백테스트 숫자는 전부 '종가에 딱 "
             "체결됐다'는 가정 위에 있습니다. 모의투자를 며칠 실행해야 말할 수 있습니다.",
             알림),
    ]


def 모아서(제안들) -> str:
    """텔레그램 한 통. 급한 것부터 위로."""
    것들 = [p for p in 제안들 if p is not None]
    if not 것들:
        return "📋 지금 기준에서 고칠 것을 못 찾았습니다.\n\n산수로 확인되는 것과 세어 보면 나오는 것만 봅니다. 나머지는 표본이 쌓여야 말할 수 있습니다."
    것들.sort(key=lambda p: 순서.get(p.급한가, 9))
    바꿀것 = sum(1 for p in 것들 if p.이름)
    머리 = f"📋 **기준 제안 {len(것들)}건** (그중 바꿀 것 {바꿀것}건)"
    return "\n\n".join([머리, *(p.글() for p in 것들), "고치실 것이 없으면 아무것도 안 하셔도 됩니다."])
