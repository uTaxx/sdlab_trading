"""리포트 전문을 텔레그램에 보낼 짧은 요약으로 줄인다.

## 왜 줄이나

시장·섹터 리포트 전문은 200줄이 넘는다. 그걸 매일 텔레그램으로 보내면
**아무도 안 읽는다.** 안 읽는 알림은 없는 것과 같고, 오히려 진짜 중요한
알림이 묻힌다.

## 2026-08-25에 다시 쓴 이유

받아 보는 사람이 **한 줄도 이해할 수 없다**고 했다. 다시 읽어 보니 맞았다.
"그냥 찍었을 때", "우연폭", "전망 못 냄", "렌즈 확장" — 전부 이 저장소
안에서만 통하는 말이었고, 밖에서 보면 무슨 소린지 알 수 없는 글이었다.

고치면서 지킨 것 넷.

1. **처음 쓰는 말은 그 자리에서 푼다.** 뜻만이 아니라 "그래서 그걸 보고
   뭘 판단하나"까지 적는다.
2. **숫자마다 단위와 조건을 붙인다.** `-2.8`이 퍼센트인지 z점수인지
   안 적으면 읽는 사람이 퍼센트로 읽는다. 실제로 그랬다.
3. **별표(★)나 `**굵게**` 같은 기호로 뜻을 대신하지 않는다.** 텔레그램에
   parse_mode를 안 주고 있어서 `**기각**`이 그대로 별 네 개로 도착한다.
   기호가 필요하면 말로 쓴다.
4. **제일 중요한 말을 맨 위에 둔다.** 이 전망은 검증에서 떨어진 실험
   기록이다. 그 말이 맨 아래 있으면 위쪽 숫자를 먼저 믿게 된다.
"""

from __future__ import annotations

import math

#: 텔레그램 한 통의 안전한 길이.
MAX_LEN = 3500

_요일 = ("월", "화", "수", "목", "금", "토", "일")

#: 앞으로 며칠을 보는가. analog.HORIZON과 같아야 한다.
_지평_거래일 = 20


def _날짜글(기준일) -> str:
    try:
        return f"{기준일.month}월 {기준일.day}일({_요일[기준일.weekday()]})"
    except AttributeError:
        return str(기준일)


def _얼마나드문가(z: float) -> str:
    """지금 값이 평소에 견줘 얼마나 드문 자리인가를 **한 문장으로**.

    예전에는 `"아주 드물게 " + "깊이 빠져 있습니다"`처럼 부사를 앞에 붙였다.
    그런데 **'아주 드물게'는 빈도를 뜻하는 말**이라, "아주 드물게 깊이 빠져
    있습니다"가 "가끔씩만 깊이 빠진다"로 읽힌다 — 지금 상태가 아니라 습관을
    말하는 문장이 된다.

    그래서 상태와 드문 정도를 **문장 두 개로 나눈다.** 앞에서 지금이 어떤지를
    말하고, 여기서 그게 흔한 일인지 아닌지를 따로 말한다."""
    셈 = abs(z)
    if 셈 >= 2:
        return "이런 자리는 몇 해에 한 번 볼까 말까 합니다"
    if 셈 >= 1:
        return "평소보다 뚜렷하게 벗어나 있습니다"
    if 셈 >= 0.3:
        return "평소보다 조금 벗어나 있습니다"
    return "평소와 비슷한 수준입니다"


def _센말(z: float, 위: str, 아래: str, 보통: str) -> str:
    """숫자가 없을 때 쓰는 말. 방향과 드문 정도를 한 줄에 담는다."""
    if abs(z) < 0.3:
        return 보통
    return f"{위 if z > 0 else 아래} {_얼마나드문가(z)}"


def state_line(state, 원시=None) -> str:
    """오늘 장 상태를 여러 줄로 풀어 쓴다.

    ## 숫자를 두 번 고쳤다

    처음에는 `단기추세 ▲+0.8 | 고점대비 -2.8`처럼 **z점수를 그대로** 찍었다.
    z점수는 "평소에 견줘 얼마나 벗어났나"이지 퍼센트가 아닌데 단위를 안 적어,
    받아 보는 사람이 -2.8을 "고점에서 2.8% 빠졌다"로 읽었다.

    그래서 숫자를 지우고 말만 남겼더니 이번에는 **"얼마나 깊이?"에 답을 못
    했다.** 고점대비는 원래 퍼센트로 말할 수 있는 값인데(지수 ÷ 1년 최고 − 1)
    같이 지워 버린 것이다.

    지금은 둘을 나눈다.
      - **원시값**은 그대로 쓴다 — "최고점보다 12.3% 아래입니다"
      - **z점수**는 "그게 흔한 일인가"를 판단하는 데만 쓰고 숫자로는 안 낸다

    `원시`를 못 받으면 말만으로 적는다(숫자를 지어내지 않는다)."""
    if len(state) == 0:
        return "  아직 잴 수 없습니다 — 견줄 과거(3년)가 안 쌓였습니다."
    오늘 = state.iloc[-1]
    원시오늘 = None
    if 원시 is not None and len(원시):
        같은날 = 원시.loc[:state.index[-1]]
        if len(같은날):
            원시오늘 = 같은날.iloc[-1]

    def _z(이름: str):
        return float(오늘[이름]) if 이름 in 오늘.index else None

    def _raw(이름: str):
        if 원시오늘 is None or 이름 not in 원시오늘.index:
            return None
        값 = float(원시오늘[이름])
        return None if math.isnan(값) else 값  # 값이 비어 있으면 지어내지 않는다

    줄 = []

    if (추세 := _z("kospi_추세20")) is not None:
        몫 = _raw("kospi_추세20")
        if 몫 is not None:
            어디 = f"20일 평균보다 {abs(몫):.1%} {'위' if 몫 >= 0 else '아래'}에 있습니다"
            줄.append(f"  · 최근 흐름: {어디}")
            줄.append(f"      {_얼마나드문가(추세)}")
        else:
            줄.append(
                "  · 최근 흐름: "
                + _센말(추세, "20일 평균 위입니다.", "20일 평균 아래입니다.", "20일 평균 근처입니다.")
            )

    if (낙폭 := _z("kospi_고점대비")) is not None:
        몫 = _raw("kospi_고점대비")
        if 몫 is not None:
            줄.append(f"  · 1년 최고점에서: {abs(몫):.1%} 아래에 있습니다")
            줄.append(f"      {_얼마나드문가(낙폭)}")
        else:
            줄.append(
                "  · 1년 최고점에서: "
                + _센말(낙폭, "고점에 가깝습니다.", "깊이 빠져 있습니다.", "평소만큼입니다.")
            )

    if (변동 := _z("kospi_변동성")) is not None:
        몫 = _raw("kospi_변동성")
        뒷말 = " 손절선에 잘 걸리는 장입니다." if 변동 >= 1 else ""  # 앞 문장이 마침표로 끝난다
        if 몫 is not None:
            줄.append(f"  · 하루 등락 폭: 요즘 하루에 평균 {몫:.1%}씩 움직입니다")
            줄.append(f"      {_얼마나드문가(변동)}.{뒷말}")
        else:
            줄.append(
                "  · 하루 등락 폭: "
                + _센말(변동, "출렁입니다.", "조용합니다.", "평소만큼입니다.")
                + 뒷말
            )

    return "\n".join(줄) if 줄 else "  지표를 못 읽었습니다."


def _섹터줄(f) -> str:
    """섹터 한 줄. 숫자마다 무엇인지가 줄 안에 들어 있어야 한다."""
    이번 = f"{f.상승확률:.0f}%"
    if f.기준선 is None or f.더한것_상승확률 is None:
        return f"  · {f.대상} {이번}"

    벌어짐 = f.더한것_상승확률
    차이 = "차이 없음" if abs(벌어짐) < 0.5 else f"차이 {벌어짐:+.0f}%p"
    판정 = "우연보다 큼" if f.우연을_넘었나 else "우연 범위 안"
    # 구분자로 '—'를 안 쓴다 — 섹터 이름에 이미 들어 있다(원자재 ETF — 금 선물).
    # 한 줄에 대시가 둘이면 어디까지가 이름인지 안 보인다.
    return f"  · {f.대상} {이번}  (평소 {f.기준선.상승확률:.0f}% / {차이} / {판정})"


def summarize(state, forecasts, 기준일, 렌즈: str = "", 지평: int = _지평_거래일,
              원시=None) -> str:
    """텔레그램 한 통짜리 요약."""
    낸것 = [f for f in forecasts if f.낼수있나]
    못낸것 = [f for f in forecasts if not f.낼수있나]

    줄 = [
        f"📊 {_날짜글(기준일)} 장 마감 기록",
        "",
        "이 알림은 보기만 합니다. 주문은 한 건도 내지 않았습니다.",
        "",
        "─────────────",
        "오늘 코스피",
        state_line(state, 원시),
        "",
        "─────────────",
        "아래는 실험 기록입니다. 매매에 쓰지 마세요.",
        "",
        "무엇을 센 것인가",
        f"  지금과 비슷했던 과거 시점들을 찾아, 거기서 {지평}거래일(약 한 달)",
        "  뒤에 값이 올라 있었는지를 센 것입니다. 앞날을 맞히는 계산이 아닙니다.",
        "  '이런 상태 뒤에는 이런 일들이 있었다'는 기록입니다.",
        "",
        "왜 쓰면 안 되는가",
        "  과거로 되돌아가 실제로 맞히는지 세어 봤더니 51.8%였습니다.",
        "  아무 날에나 샀을 때가 56.3%였으니, 이 방식이 오히려 못했습니다.",
        "  그래서 기각했습니다. 지금은 '그때 뭐라고 했었나'를 나중에",
        "  되짚기 위한 기록으로만 남깁니다. (설계안 §29)",
    ]

    if 낸것:
        줄 += [
            "",
            "─────────────",
            "섹터별 기록",
            "",
            "보는 법",
            "  '반도체 62% (평소 55% / 차이 +7%p / 우연 범위 안)'이라면",
            f"  62%    비슷했던 과거 뒤 {지평}거래일에 값이 올라 있던 비율",
            "  평소   아무 날에나 그냥 샀어도 올라 있던 비율",
            "  차이   62 빼기 55. 클수록 '이번은 좀 다르다'는 뜻",
            "  우연   비슷했던 때가 열몇 번뿐이라, 동전을 그만큼 던져도 이만큼은",
            "         벌어집니다. '우연 범위 안'이면 차이가 없다고 봐야 합니다.",
            "",
        ]
        줄 += [_섹터줄(f) for f in 낸것]

    if 못낸것:
        줄 += [
            "",
            "─────────────",
            f"숫자를 못 낸 것 {len(못낸것)}개",
            "  비슷했던 과거가 너무 적으면 비율을 내지 않고 비웁니다.",
            "  네 번 중 세 번 올랐다고 '75%'라고 적으면, 그건 확률이 아니라",
            "  우연을 확률처럼 보이게 적은 것이기 때문입니다.",
            "",
        ]
        줄 += [f"  · {f.대상}: {f.사유}" for f in 못낸것[:5]]
        if len(못낸것) > 5:
            줄.append(f"  · 그 밖에 {len(못낸것) - 5}개")

    if 렌즈:
        줄 += ["", "─────────────", f"이 기록이 본 자료: {_렌즈설명(렌즈)}"]

    글 = "\n".join(줄)
    if len(글) > MAX_LEN:
        글 = 글[: MAX_LEN - 20] + "\n… (줄임)"
    return 글


def _렌즈설명(렌즈: str) -> str:
    """'렌즈 확장'만 적으면 무슨 말인지 알 수 없다. 무엇을 봤는지 적는다."""
    from muwon.market.series import LENSES, SERIES

    if 렌즈 not in LENSES:
        return 렌즈
    키들, 시작연도, _ = LENSES[렌즈]
    이름들 = ", ".join(SERIES[k].이름 for k in 키들 if k in SERIES)
    return f"{이름들} ({시작연도}년부터)"
