"""**우리 기록과 증권사 기록을 맞대는 규칙**을 고정한다.

이 저장소의 전략 평가 결과(승률·손익비·슬리피지)는 전부 `orders` 표 위에서 계산된다.
표가 틀리면 그 위의 숫자가 전부 틀리고, **틀렸다는 사실조차 안 보인다.**

2026-08-25에 두 가지가 동시에 일어났다.
  - 12주가 체결됐는데 기록에는 4주 (어긋남)
  - 흉내 실행이 사지도 않은 종목을 기록에 씀 (우리만)

둘 다 우리 기록만 봐서는 알 수 없다. 여기서 지키는 것은 그 둘을 서로 다른
것으로 가르는 일이다. 섞으면 고치는 방법도 섞인다.
"""

from __future__ import annotations

from datetime import UTC, datetime

from muwon.domain.types import OrderSide
from muwon.execution.order_audit import 대조하기, 우리주문, 파싱


def _행(**덮개) -> dict:
    바탕 = {
        "odno": "0000012345",
        "pdno": "066970",
        "prdt_name": "엘앤에프",
        "sll_buy_dvsn_cd": "02",
        "ord_qty": "12",
        "tot_ccld_qty": "12",
        "avg_prvs": "118241",
        "ord_dt": "20260825",
        "cncl_yn": "N",
    }
    return {**바탕, **덮개}


def _우리(**덮개) -> 우리주문:
    바탕 = {
        "row_id": 1, "order_id": "0000012345", "symbol": "066970", "side": "BUY",
        "quantity": 12, "price": 118241.0, "when": datetime(2026, 8, 25, 9, 12, tzinfo=UTC),
        "reference_price": 121600.0, "fill_confirmed": True,
    }
    return 우리주문(**{**바탕, **덮개})


# ── 파싱 ─────────────────────────────────────────────────────────────────


def test_체결_행을_읽는다():
    (주문,) = 파싱([_행()])

    assert 주문.order_id == "0000012345"
    assert 주문.symbol == "066970"
    assert 주문.side == OrderSide.BUY
    assert (주문.ordered_quantity, 주문.filled_quantity) == (12, 12)
    assert 주문.avg_price == 118241
    assert 주문.체결됐나


def test_매도_행도_읽는다():
    (주문,) = 파싱([_행(sll_buy_dvsn_cd="01")])

    assert 주문.side == OrderSide.SELL


def test_주문번호가_없는_행은_버린다():
    assert 파싱([_행(odno="")]) == []
    assert 파싱([_행(odno="000000")]) == []


# ── 대조 ─────────────────────────────────────────────────────────────────


def test_같으면_맞음이다():
    결과 = 대조하기([_우리()], 파싱([_행()]))

    assert len(결과.맞음) == 1
    assert not 결과.문제있나


def test_수량이_다르면_어긋남이다():
    """오늘 그대로다. 12주 체결됐는데 기록엔 4주. 그 8주에는 손절이 없었다."""
    결과 = 대조하기([_우리(quantity=4)], 파싱([_행()]))

    (짝,) = 결과.어긋남
    assert 짝.수량다름 and not 짝.체결가다름
    assert "수량 4주 → 12주" in 짝.한줄
    assert 결과.문제있나


def test_체결가가_다르면_어긋남이다():
    결과 = 대조하기([_우리(price=118300.0)], 파싱([_행()]))

    (짝,) = 결과.어긋남
    assert 짝.체결가다름 and not 짝.수량다름


def test_1원_미만_차이는_어긋남이_아니다():
    """반올림으로 기록을 고치면 잡음만 남는다."""
    결과 = 대조하기([_우리(price=118241.4)], 파싱([_행()]))

    assert len(결과.맞음) == 1
    assert not 결과.어긋남


def test_주문번호_앞의_0은_무시하고_짝짓는다():
    """우리가 '12345'로 적었어도 KIS의 '0000012345'와 같은 주문이다."""
    결과 = 대조하기([_우리(order_id="12345")], 파싱([_행()]))

    assert len(결과.맞음) == 1


def test_우리_기록에만_있으면_유령이다():
    """흉내 실행이 운영 DB에 써 넣은 그것. 그 주식은 실제로 없다."""
    결과 = 대조하기([_우리(order_id="9999999", symbol="411060")], 파싱([_행()]))

    assert [o.symbol for o in 결과.우리만] == ["411060"]
    assert [ㄴ.주문.symbol for ㄴ in 결과.증권사만] == ["066970"]


def test_증권사에만_있고_보유로도_모르면_위험하다():
    """아무도 안 지키는 주식이다. 손절이 안 걸린다."""
    결과 = 대조하기([], 파싱([_행()]))

    (놓친것,) = 결과.증권사만
    assert 놓친것.주문.symbol == "066970"
    assert 놓친것.위험한가
    assert "손절이 안 걸립니다" in 놓친것.뜻
    assert 결과.위험한것 == [놓친것]
    assert 결과.문제있나


def test_보유로는_알고_있으면_손절은_걸린다():
    """2026-08-25 첫 대조의 HPSP가 이 경우였다. 손절은 보유를 보고 걸리지
    주문 기록을 보고 걸리지 않는다. 뭉뚱그리면 멀쩡한 것을 보고 놀란다."""
    결과 = 대조하기([], 파싱([_행()]), 보유종목={"066970"})

    (놓친것,) = 결과.증권사만
    assert not 놓친것.위험한가
    assert 결과.위험한것 == []
    assert "전략 평가" in 놓친것.뜻
    assert 결과.문제있나, "전략 평가에서 빠지는 것도 문제는 문제다"


def test_사고_판_흔적은_위험하지_않다():
    """verify_kis_order가 주문 경로를 확인하려고 1주 샀다 파는 그것.
    지금 보유가 아니라 손절할 것도 없다."""
    행들 = 파싱([
        _행(odno="1", pdno="005930", ord_qty="1", tot_ccld_qty="1", sll_buy_dvsn_cd="02"),
        _행(odno="2", pdno="005930", ord_qty="1", tot_ccld_qty="1", sll_buy_dvsn_cd="01"),
    ])

    결과 = 대조하기([], 행들)

    assert all(ㄴ.닫힘 and not ㄴ.위험한가 for ㄴ in 결과.증권사만)
    assert 결과.위험한것 == []


def test_사고_덜_판_것은_닫힌_것이_아니다():
    """2주 사고 1주만 팔았으면 1주가 남아 있다. 그건 지켜야 한다."""
    행들 = 파싱([
        _행(odno="1", pdno="005930", ord_qty="2", tot_ccld_qty="2", sll_buy_dvsn_cd="02"),
        _행(odno="2", pdno="005930", ord_qty="1", tot_ccld_qty="1", sll_buy_dvsn_cd="01"),
    ])

    결과 = 대조하기([], 행들)

    assert all(not ㄴ.닫힘 for ㄴ in 결과.증권사만)
    assert len(결과.위험한것) == 2


def test_체결이_0인_주문은_대조_대상이_아니다():
    """취소·미체결은 보유를 안 만든다. 우리 기록에 없는 것이 맞다."""
    결과 = 대조하기([], 파싱([_행(tot_ccld_qty="0", cncl_yn="Y")]))

    assert 결과.증권사만 == []
    assert 결과.체결없음 == 1
    assert not 결과.문제있나


def test_부분_체결된_주문은_체결된_만큼으로_대조한다():
    """잔여 8주는 아직 안 산 것이다. 기록에 4주가 맞다."""
    결과 = 대조하기([_우리(quantity=4)], 파싱([_행(tot_ccld_qty="4")]))

    assert len(결과.맞음) == 1
    assert not 결과.문제있나


def test_주문번호가_없는_우리_기록은_대조불가로_따로_센다():
    """없는 것이 아니라 **모르는 것**이다. 유령으로 몰면 멀쩡한 기록을 지운다."""
    결과 = 대조하기([_우리(order_id="")], 파싱([_행()]))

    assert len(결과.대조불가) == 1
    assert 결과.우리만 == [], "짝을 못 찾은 것을 '증권사에 없음'으로 몰면 안 된다"


def test_대조한_건수는_맞음과_어긋남의_합이다():
    우리것 = [_우리(), _우리(row_id=2, order_id="222", symbol="411060", quantity=1)]
    증권사것 = 파싱([_행(), _행(odno="222", pdno="411060", ord_qty="2", tot_ccld_qty="2")])

    결과 = 대조하기(우리것, 증권사것)

    assert 결과.대조한건수 == 2
    assert len(결과.맞음) == 1 and len(결과.어긋남) == 1


def test_증권사만_목록은_날짜와_종목으로_정렬한다():
    """사람이 읽을 목록이라 순서가 흔들리면 매번 다른 보고서로 보인다."""
    행들 = 파싱([
        _행(odno="3", pdno="411060", ord_dt="20260825"),
        _행(odno="1", pdno="066970", ord_dt="20260820"),
        _행(odno="2", pdno="005930", ord_dt="20260825"),
    ])

    결과 = 대조하기([], 행들)

    assert [(ㄴ.주문.ord_dt, ㄴ.주문.symbol) for ㄴ in 결과.증권사만] == [
        ("20260820", "066970"), ("20260825", "005930"), ("20260825", "411060"),
    ]
