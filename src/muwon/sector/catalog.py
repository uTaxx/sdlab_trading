    #: "국제시세"  — 국내 종목이 아니라 국제 시세로 전망한다.
    #:
    #: 원자재가 후자다. 국내 금·은 ETF는 둘뿐이라 그걸로 만든 '지수'는
    #: 사실상 두 종목의 평균이다. 반면 국제 금·은 선물은 2000년부터
    #: 6,500일이 있다 — 훨씬 나은 표본으로 같은 것을 잰다.
    전망출처: str = "섹터지수"

    @property
    def 활성종목(self) -> list[SectorMember]:
        return [m for m in self.종목 if m.활성]


