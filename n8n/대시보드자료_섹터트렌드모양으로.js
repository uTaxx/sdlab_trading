// n8n 워크플로 `무원406 대시보드 자료`(wj3pZvpHJPekTaoI)의
// **「섹터 트렌드 모양으로」 노드 사본**이다.
//
// 진짜로 도는 것은 n8n에 있다. 여기 있는 것은 시험이 읽는 사본이라,
// 고칠 때는 **두 곳을 같이** 고쳐야 한다.
//
// 칸 순서는 파이썬 `analysis/sector_trend.py`의 `머리`와 같다. 그 목록을
// 고치면 여기 칸 번호도 같이 고쳐야 하고, `tests/test_n8n_gateway_fields.py`가
// 둘을 묶어 둔다. **한 칸만 밀려도 표의 모든 줄이 어긋나는데 화면은 멀쩡히
// 그려진다.** 등락률 칸에 종목 수가 들어가 있어도 숫자라서 안 보인다.
//
// 왜 「화면 모양으로」에 같이 안 넣었나. 그 노드는 표마다 칸 번호를 들고
// 있어서 통째로 옮겨 적다 하나만 틀리면 관계없는 표가 조용히 망가진다.
// 그래서 이 표는 열쇠 검사 뒤에서 갈라져 따로 읽고 따로 모양을 만든다.
const 줄들 = ((($input.first().json.valueRanges || [])[0]) || {}).values || [];
const 값 = (줄, i) => String(줄 && 줄[i] != null ? 줄[i] : "").trim();
// 못 잰 칸은 빈 글자로 온다. 0으로 바꾸면 안 움직인 것과 섞인다.
const 수 = (글) => {
  const g = String(글 == null ? "" : 글).trim();
  if (!g) return null;
  const n = Number(g.replace(/[^0-9.eE+-]/g, ""));
  return Number.isFinite(n) ? n : null;
};
const 몸줄 = 줄들.slice(1).filter((ㅈ) => 값(ㅈ, 0));
// 한 회차가 섹터 아홉에 코스피 한 줄이라 열 줄쯤이다. 지난 회차를 화면에서
// 고를 수 있어야 하므로 넉넉히 싣는다.
const 최근 = 몸줄.slice(-600);

return [{ json: { 섹터트렌드: 최근.map((ㅈ) => ({
  잰때: 값(ㅈ, 1),
  코드: 값(ㅈ, 2),
  섹터: 값(ㅈ, 3),
  종목수: 수(값(ㅈ, 4)),
  d5: 수(값(ㅈ, 5)),
  d20: 수(값(ㅈ, 6)),
  d60: 수(값(ㅈ, 7)),
  상대강도: 수(값(ㅈ, 8)),
  이평위: 값(ㅈ, 9) === "예" ? true : (값(ㅈ, 9) === "아니오" ? false : null),
  못잰종목: 값(ㅈ, 10),
})) } }];
