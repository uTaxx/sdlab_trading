기본일순위 = "window_cagr"
기본이순위 = "plus_ratio"
기본삼순위 = "p10"


@dataclass(frozen=True)
class 기준:
    """무엇을 먼저 볼지. 순위를 내는 자리는 전부 이것을 지나간다.

    `judgment.판단기준`과 모양이 같지만 지침 목록이 다르다. 저기는 연 단위
    성적에서, 여기는 구간 성적에서 값을 꺼낸다. 하나로 합치면 화면에서 고를
    때 서로 다른 자료를 보는 지침이 한 목록에 섞인다."""

    일순위: str = 기본일순위
    이순위: str = 기본이순위
    삼순위: str = 기본삼순위

    @property
    def 열쇠들(self) -> tuple[str, str, str]:
        return (self.일순위, self.이순위, self.삼순위)

    @property
    def 지침들(self) -> list[지침]:
        """아는 것만, 순서대로. 모르는 열쇠와 중복은 빠진다."""
        나온것: list[지침] = []
        본것: set[str] = set()
        for 열쇠 in self.열쇠들:
            ㄱ = 찾기(열쇠)
            if ㄱ is None or ㄱ.갈래 != 순위갈래 or ㄱ.열쇠 in 본것:
                continue
            나온것.append(ㄱ)
            본것.add(ㄱ.열쇠)
        return 나온것

    @property
    def 성한가(self) -> bool:
        """**1순위가 순위를 낼 수 있는 지침이어야 한다.**

        1순위를 모르는 열쇠나 확인 지침으로 두면 실제로는 2순위가 순위를
        정하게 된다. 사람은 자기가 고른 1순위로 정렬됐다고 읽는데 화면은
        다른 값으로 줄을 세운다. 그 어긋남은 아무것도 빨갛게 만들지 않는다.
        그래서 그때는 기준 전체를 기본값으로 돌린다."""
        ㄱ = 찾기(self.일순위)
        return ㄱ is not None and ㄱ.갈래 == 순위갈래

    def 정렬키(self, 잰것):
        """앞 순위부터, 큰 값이 위로. 동점 범위 안이면 다음 순위로 넘어간다.

        못 잰 값은 맨 아래로 보낸다. **0으로 보지 않는다.** 계산하지 못한
        것을 0%로 두면 잃지도 벌지도 않은 전략과 같은 자리에 선다."""
        칸들 = []
        for ㄱ in self.지침들:
            값 = ㄱ.값(잰것)
            if 값 is None:
                칸들.append((1, 0.0))
                continue
            폭 = ㄱ.비긴폭 or 0.0
            칸들.append((0, -(round(값 / 폭) if 폭 > 0 else 값)))
        return tuple(칸들)


기본기준 = 기준()


def 줄세우기(잰것들, 기준값: 기준 | None = None) -> list:
    """판단 기준으로 정렬한 목록. 큰 값이 앞이다.

    **매매가 0건인 것은 부르는 쪽에서 미리 뺀다.** 한 건도 안 산 것을
    수익률 0%로 맨 위에 두지 않기 위해서다."""
    ㄱ준 = 기준값 or 기본기준
    return sorted(잰것들, key=ㄱ준.정렬키)


