class _시트:
    def __init__(self, 값들):
        self._값들 = 값들

    def 가져오기(self, 열쇠):
        return self._값들.get(열쇠, "")


def test_시트에_적힌_지침을_읽는다():
    일, 이, 삼 = ㅈ.시트칸
