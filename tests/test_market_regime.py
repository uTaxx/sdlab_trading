def test_국면_구간_수가_전환_구간_수의_합과_같다():
    """셋은 부모이고 여섯은 그 안을 나눈 것이다. 상승인 날은 상승에도 들고
    상승→조정에도 든다. 겹치는 것이 맞다."""
    # 상승 → 조정 → 상승 → 조정 → 하락 → (끝)
    값들 = (_쭉(100.0, 300) + _쭉(88.0, 20) + _쭉(100.0, 20)
          + _쭉(88.0, 20) + _쭉(70.0, 20))
    시세 = _시세(값들)
    표 = ㄱ.세분나누기(시세)

    for 국면 in ㄱ.국면들:
        부모 = sum(1 for ㅂ in 표["국면"].values() if ㅂ == 국면)
        자식 = sum(1 for ㅂ in 표["전환"].values() if ㅂ.startswith(f"{국면}→"))
        # 마지막 구간은 전환이 안 붙으므로 자식이 부모보다 적을 수 있다.
        assert 자식 <= 부모, 국면


