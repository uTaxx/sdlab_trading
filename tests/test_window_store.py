def test_쌓았다_읽으면_값이_같다():
    만들기 = make_session_factory("sqlite:///:memory:")
    원본 = _잰것()
    with 만들기() as 세션:
        ㅅ.쌓기(세션, [원본], 잰날=date(2026, 9, 3), 매매대상="sheet")
        [읽은것] = ㅅ.읽기(세션, 매매대상="sheet")

    assert 읽은것.전략 == 원본.전략
    assert 읽은것.상한 == 원본.상한
