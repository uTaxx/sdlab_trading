def test_기각됐다는_말이_요약에서_살아남는다():
    """이 전망은 이미 되돌려 검증에서 떨어졌다. 그 말이 빠지면 매일
    그럴듯한 숫자만 보게 되고, 그러다 어느 날 그걸 근거로 삼게 된다."""
    글 = summarize(_상태(), [_전망()], date(2026, 8, 19))

    assert "매매에 쓰지 마세요" in 글
    assert "51.8%" in 글 and "56.3%" in 글, "왜 못 믿는지 숫자로 보여야 한다"


def test_섹터_표를_알림에_싣지_않는다():
    """이 파일에서 제일 중요한 시험이다.

    기각된 방식의 표를 매일 밤 열 줄씩 보내면, 그 열 줄 중 여덟 줄이
    '차이 없음'이어도 사람은 읽는다. 그러다 어느 날 그걸 근거로 삼는다.
    그리고 그 전에, 매일 흘려보는 습관이 먼저 생겨서 **정작 중요한 줄도
    같이 놓치게 된다.**"""
    글 = summarize(
        _상태(),
        [_전망("반도체"), _전망("바이오"), _전망("방산")],
        date(2026, 8, 19),
    )

    assert "반도체" not in 글 and "바이오" not in 글 and "방산" not in 글
    assert "우연 범위 안" not in 글
    assert "보는 법" not in 글


def test_우연을_넘은_것이_몇_개인지는_알려준다():
    """표를 뺀다고 실험이 돈 사실까지 감추면, 나중에 기록을 되짚을 때
    '그날 이게 돌긴 했나'를 알 수 없다."""
    글 = summarize(
        _상태(),
        [_전망("가", 구간수=400), _전망("나"), _전망("다")],
        date(2026, 8, 19),
    )

    assert "3개 중 1개가 우연을 넘었습니다" in 글


def test_숫자를_하나도_못_내면_그렇게_적는다():
    """'0개가 우연을 넘었습니다'와 '잴 것이 아예 없었다'는 다른 말이다."""
    글 = summarize(_상태(), [_전망("로봇", 낼수있나=False)], date(2026, 8, 19))

    assert "비슷했던 과거가 없었습니다" in 글


def test_오늘_한_일이_들어간다():
    """이게 이 알림을 여는 이유다. 지표만 열 줄 있으면 읽고 닫는다."""
    글 = summarize(
        _상태(), [_전망()], date(2026, 8, 19),
        한일={
            "산것": [("풍산", 3, 87600.0)],
            "판것": [("HPSP", 2, 6900.0, 7.66)],
            "보유": [("엘앤에프", 12, 118241.0)],
        },
    )

    assert "오늘 한 일" in 글
    assert "풍산 3주" in 글
    assert "+6,900원 (+7.7%)" in 글
    assert "들고 있는 것 1종목: 엘앤에프" in 글


def test_산_값은_한_주_값과_합계를_둘_다_적는다():
    """'87,600원'만 적으면 한 주 값인지 다 합친 값인지 둘 중 하나로 읽고,
    어느 쪽으로 읽었는지는 본인도 모른다."""
    글 = summarize(
        _상태(), [_전망()], date(2026, 8, 19),
        한일={"산것": [("풍산", 3, 87600.0)]},
    )

    assert "1주 87,600원" in 글 and "모두 262,800원" in 글


def test_아무_일도_없었으면_없다고_적는다():
    """빈 줄로 두면 '이 알림이 매수 얘기를 안 한다'로 읽힌다. 그러면
    안 산 날과 알림이 고장 난 날이 구별되지 않는다."""
    글 = summarize(_상태(), [_전망()], date(2026, 8, 19), 한일={})

    assert "산 것 없음" in 글
    assert "판 것 없음" in 글
    assert "들고 있는 것 없음" in 글


def test_기록을_못_읽으면_없었다고_하지_않는다():
    """안 산 날과 DB를 못 읽은 날이 화면에서 같아 보이면, 매수가 통째로
    막힌 날을 평범한 날로 읽게 된다. 실제로 그런 날이 있었다."""
    글 = summarize(
        _상태(), [_전망()], date(2026, 8, 19), 한일={"못읽음": "OperationalError"}
    )

    assert "읽지 못했습니다" in 글
    assert "산 것 없음" not in 글
    assert "OperationalError" in 글


def test_텔레그램에_안_먹는_기호를_안_쓴다():
    """send_message에 parse_mode를 안 주고 있어서 `**기각**`이 그대로
    별 네 개로 도착한다. 강조가 필요하면 말로 쓴다."""
    글 = summarize(_상태(), [_전망()], date(2026, 8, 19))

    assert "**" not in 글
    assert "★" not in 글, "별표는 무슨 뜻인지 아무도 모른다"


def test_한_통을_넘지_않는다():
    """텔레그램 한 통을 넘기면 잘려서 도착한다."""
    많은것 = [_전망(f"섹터{i}") for i in range(200)]
    글 = summarize(
        _상태(), 많은것, date(2026, 8, 19),
        한일={"보유": [(f"종목{i}", 1, 1000.0) for i in range(300)]},
    )

    assert len(글) <= MAX_LEN


