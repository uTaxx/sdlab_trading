from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class SectorMember:
    """섹터에 속한 종목 하나."""

    symbol: str  # KIS 6자리
    name: str
    market: str  # KOSPI | KOSDAQ
    활성: bool = True
    메모: str = ""

    @property
    def yahoo_symbol(self) -> str:
        return f"{self.symbol}.{'KS' if self.market == 'KOSPI' else 'KQ'}"


