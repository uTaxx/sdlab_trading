def test_되돌아_나오는_문턱이_더_위에_있다():
    """조정에서 상승으로 나오려면 −7%보다 위로 올라와야 한다. 이것이 없으면
    −10% 언저리에서 국면이 하루 단위로 뒤집힌다."""
