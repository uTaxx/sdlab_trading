"""보유 상한을 정해 놓고 그 길이의 구간으로 전략을 재는 계산.

## 왜 이 파일이 생겼나

이 시스템의 목적은 단기 매매로 수익을 누적하는 것이고, 한 종목을 정해진
영업일수보다 오래 들고 있지 않는다. 그런데 지금까지의 성과 측정은 전부
연 단위였다. 한 매매가 최대 20영업일이면 1년은 그 주기를 열두 번 넘게
반복한 것이라, 연 수익률은 그 열두 번을 뭉뚱그린 값이다. 한 번의 매매가
어땠는지도, 아무 날에 들어갔을 때 어땠는지도 말해 주지 못한다.

여기서는 세 층으로 나눠서 잰다. 설계안은 `docs/단기매매_재설계.md`다.

1. **매매 하나**: 진입부터 청산까지. 보유일수와 청산 사유를 본다.
2. **구간**: 보유 상한과 같은 길이로 계좌를 잘라 본 수익률의 분포.
3. **누적**: 구간을 반복했을 때 쌓이는 값. 연환산으로 낸다.

## 구간이 겹치는 것을 반드시 밝힌다

오늘 시작한 구간과 내일 시작한 구간은 대부분의 날을 공유한다. 겹치는
구간 1,380개를 서로 다른 1,380번의 시험으로 읽으면 표본이 실제보다 스무
배 많아 보인다. **대표 숫자는 겹치지 않는 구간으로 내고, 겹치는 구간은
그림을 그릴 때만 쓴다.** `구간성적.겹침`이 어느 쪽인지를 들고 다닌다.

## 못 잰 것을 0으로 채우지 않는다

구간이 하나도 없거나 매매가 없으면 None을 돌려준다. 0%는 "안 움직였다"는
뜻이고 None은 "잴 수 없었다"는 뜻이다. 섞이면 분포가 실제보다 밋밋해진다.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from datetime import date

import pandas as pd

#: 재 볼 보유 상한. 영업일 기준이다.
#:
#: 주인이 정했다(2026-09-03). 전략마다 잘 맞는 길이가 따로 있을 것으로
#: 보고, 3일부터 20일까지 늘려 가며 봉우리가 어디인지 확인한다.
상한들: tuple[int, ...] = (3, 5, 7, 10, 15, 20)

#: 1년의 영업일 수. 연환산에 쓴다. 한국 증시는 해마다 245~250일 사이인데
#: 여기서는 자료의 실제 일수를 세지 않고 이 값으로 고정한다. 전략끼리
#: 비교하는 데 쓰는 값이라 모든 줄에 같은 값이 걸리면 된다.
영업일1년 = 252

#: 이만큼은 있어야 구간 분포를 놓고 이야기한다. 겹치지 않는 구간 기준이다.
최소구간수 = 30


# ── 구간 ────────────────────────────────────────────────────────


@dataclass(frozen=True)
class 구간:
    """계좌를 보유 상한만큼 잘라 본 것."""

    시작일: date
    끝일: date
    #: 구간 첫날의 평가금액에서 마지막 날까지의 수익률(%)
    수익률: float
    #: 구간 안에서 고점 대비 가장 많이 빠졌던 폭(%). 0 이하다.
    최대낙폭: float


def 구간나누기(자산곡선: pd.DataFrame, 길이: int, 겹치게: bool = False) -> list[구간]:
    """날마다의 평가금액에서 길이만큼의 구간을 뽑는다.

    **달력이 아니라 영업일로 센다.** 자산 곡선에는 장이 열린 날만 들어
    있으므로 줄 번호가 곧 영업일이다.

    `겹치게`가 참이면 하루씩 밀며 전부 뽑고, 거짓이면 길이만큼 건너뛴다.
    대표 숫자는 겹치지 않는 쪽으로 낸다."""
    if 자산곡선 is None or len(자산곡선) < 길이 + 1 or 길이 < 1:
        return []
    날들 = list(자산곡선["trade_date"])
    값들 = [float(ㄱ) for ㄱ in 자산곡선["equity"]]
    걸음 = 1 if 겹치게 else 길이

    나온것: list[구간] = []
    for 처음 in range(0, len(값들) - 길이, 걸음):
        끝 = 처음 + 길이
        시작값 = 값들[처음]
        if 시작값 <= 0:
            continue
        토막값 = 값들[처음:끝 + 1]
        꼭지 = 토막값[0]
        낙폭 = 0.0
        for ㄱ in 토막값:
            꼭지 = max(꼭지, ㄱ)
            if 꼭지 > 0:
                낙폭 = min(낙폭, (ㄱ - 꼭지) / 꼭지 * 100)
        나온것.append(구간(
            시작일=날들[처음], 끝일=날들[끝],
            수익률=(값들[끝] / 시작값 - 1) * 100,
            최대낙폭=낙폭,
        ))
    return 나온것


def _백분위(값들: list[float], 비율: float) -> float | None:
    """정렬한 값에서 아래에서 `비율`만큼 올라간 자리의 값.

    가운데 값이 없으면 이웃 둘을 비율로 섞는다. 넘파이를 부르지 않는 것은
    이 계산이 시험에서 손으로 확인되기를 바라기 때문이다."""
    if not 값들:
        return None
    ㄱ = sorted(값들)
    if len(ㄱ) == 1:
        return ㄱ[0]
    자리 = 비율 * (len(ㄱ) - 1)
    아래 = math.floor(자리)
    위 = min(아래 + 1, len(ㄱ) - 1)
    남은것 = 자리 - 아래
    return ㄱ[아래] + (ㄱ[위] - ㄱ[아래]) * 남은것


@dataclass(frozen=True)
class 구간성적:
    """구간 분포에서 뽑은 값들. 화면의 판단 기준이 여기서 나온다."""

    길이: int
    겹침: bool
    구간수: int
    #: 한 구간에서 복리로 쌓이는 속도(%). 산술평균이 아니다.
    기하평균: float | None = None
    #: 기하평균을 1년치로 환산한 값(%). 상한이 다른 전략을 같은 줄에 놓는다.
    연환산: float | None = None
    산술평균: float | None = None
    중앙값: float | None = None
    #: 수익이 난 구간의 비율(%)
    플러스비율: float | None = None
    하위10: float | None = None
    하위25: float | None = None
    최악: float | None = None
    최고: float | None = None
    표준편차: float | None = None
    #: 기하평균을 하락 쪽 흔들림으로 나눈 값. 위험 대비 수익이다.
    하락대비수익: float | None = None
    #: 구간 안 최대낙폭의 가운데값(%)
    구간낙폭중앙값: float | None = None

    @property
    def 믿을만한가(self) -> bool:
        """겹치는 구간은 표본 수를 부풀리므로 이 판정에 쓰지 않는다."""
        return (not self.겹침) and self.구간수 >= 최소구간수


def 구간재기(구간들: list[구간], 길이: int, 겹침: bool = False) -> 구간성적:
    """구간 목록에서 판단에 쓸 값을 뽑는다.

    **기하평균을 로그로 계산한다.** 수익률을 그대로 곱해 나가면 구간이
    천 개일 때 값이 넘치거나 0으로 뭉개진다.

    구간 하나라도 -100%면(계좌가 0이 되면) 기하평균이 정의되지 않는다.
    그때는 None으로 두고 그 사실을 화면이 적게 한다."""
    if not 구간들:
        return 구간성적(길이=길이, 겹침=겹침, 구간수=0)

    값들 = [ㄱ.수익률 for ㄱ in 구간들]
    낙폭들 = [ㄱ.최대낙폭 for ㄱ in 구간들]

    기하 = None
    if all(ㄱ > -100 for ㄱ in 값들):
        로그합 = sum(math.log(1 + ㄱ / 100) for ㄱ in 값들)
        기하 = (math.exp(로그합 / len(값들)) - 1) * 100

    연환산 = None
    if 기하 is not None and 길이 > 0:
        반복 = 영업일1년 / 길이
        연환산 = ((1 + 기하 / 100) ** 반복 - 1) * 100

    평균 = sum(값들) / len(값들)
    편차 = (
        math.sqrt(sum((ㄱ - 평균) ** 2 for ㄱ in 값들) / (len(값들) - 1))
        if len(값들) > 1 else None
    )
    아래쪽 = [ㄱ for ㄱ in 값들 if ㄱ < 0]
    하락흔들림 = (
        math.sqrt(sum(ㄱ ** 2 for ㄱ in 아래쪽) / len(아래쪽)) if 아래쪽 else None
    )

    return 구간성적(
        길이=길이, 겹침=겹침, 구간수=len(값들),
        기하평균=기하, 연환산=연환산, 산술평균=평균,
        중앙값=_백분위(값들, 0.5),
        플러스비율=sum(1 for ㄱ in 값들 if ㄱ > 0) / len(값들) * 100,
        하위10=_백분위(값들, 0.10),
        하위25=_백분위(값들, 0.25),
        최악=min(값들), 최고=max(값들),
        표준편차=편차,
        하락대비수익=(기하 / 하락흔들림 if 기하 is not None and 하락흔들림 else None),
        구간낙폭중앙값=_백분위(낙폭들, 0.5),
    )


# ── 매매 하나하나 ───────────────────────────────────────────────

#: 매매가 끝난 까닭. 화면과 DB가 같은 말을 쓰게 이 목록만 쓴다.
청산갈래들: tuple[str, ...] = ("손절", "익절", "트레일링", "매도신호", "기간만료")


def 청산갈래(사유: str) -> str:
    """엔진이 남긴 사유 글자를 다섯 갈래 중 하나로 옮긴다.

    엔진의 사유는 사람이 읽는 문장이라 그대로 세면 갈래가 수십 개가 된다.
    `보유 상한 5거래일에 닿아 청산`과 `보유 상한 5거래일을 넘겨 청산
    (실제 7거래일 보유)`이 다른 갈래로 세어지면 비율이 뜻을 잃는다.

    **모르는 사유는 매도신호로 본다.** 전략이 직접 만든 문장이기 때문이다."""
    글 = str(사유 or "")
    if "보유 상한" in 글:
        return "기간만료"
    if "트레일링" in 글:
        return "트레일링"
    if "손절" in 글:
        return "손절"
    if "익절" in 글:
        return "익절"
    return "매도신호"


@dataclass(frozen=True)
class 매매성적:
    """매매 분포에서 뽑은 값들."""

    매매수: int
    승률: float | None = None
    손익비: float | None = None
    #: 매매 한 번의 평균 수익률(%)
    기대수익: float | None = None
    중앙값: float | None = None
    평균보유일수: float | None = None
    #: 갈래마다 몇 %인지. 열쇠는 `청산갈래들`과 같다.
    갈래비율: dict[str, float] = field(default_factory=dict)
    #: 끝까지 안 팔고 남은 종목 수. 백테스트 마지막 날의 보유다.
    미청산수: int = 0

    @property
    def 기간만료비율(self) -> float | None:
        """이 값이 높으면 정해진 상한 안에 답이 나오지 않는 전략이다."""
        return self.갈래비율.get("기간만료")


def 매매재기(매매들, 미청산수: int = 0) -> 매매성적:
    """엔진이 남긴 청산 매매 목록에서 값을 뽑는다.

    `매매들`은 `backtest.engine.ClosedTrade`를 담은 목록이다. 여기서는
    `pnl_pct`, `entry_date`, `exit_date`, `exit_reason`만 쓴다."""
    것들 = list(매매들 or [])
    if not 것들:
        return 매매성적(매매수=0, 미청산수=미청산수)

    수익들 = [float(ㄱ.pnl_pct) for ㄱ in 것들]
    번것 = [ㄱ for ㄱ in 수익들 if ㄱ > 0]
    잃은것 = [ㄱ for ㄱ in 수익들 if ㄱ < 0]
    잃은합 = abs(sum(잃은것))

    갈래수 = dict.fromkeys(청산갈래들, 0)
    보유일들 = []
    for ㄱ in 것들:
        갈래수[청산갈래(getattr(ㄱ, "exit_reason", ""))] += 1
        시작 = getattr(ㄱ, "entry_date", None)
        끝 = getattr(ㄱ, "exit_date", None)
        보유일 = getattr(ㄱ, "보유일수", None)
        if 보유일 is None and 시작 is not None and 끝 is not None:
            # 달력 날짜 차이다. 영업일이 필요하면 부르는 쪽이 시세를 보고
            # 다시 센다. 여기서는 시세를 들고 있지 않다.
            보유일 = (끝 - 시작).days
        if 보유일 is not None:
            보유일들.append(float(보유일))

    return 매매성적(
        매매수=len(것들),
        승률=len(번것) / len(것들) * 100,
        손익비=(sum(번것) / 잃은합 if 잃은합 > 0 else None),
        기대수익=sum(수익들) / len(수익들),
        중앙값=_백분위(수익들, 0.5),
        평균보유일수=(sum(보유일들) / len(보유일들) if 보유일들 else None),
        갈래비율={ㅋ: 갈래수[ㅋ] / len(것들) * 100 for ㅋ in 청산갈래들},
        미청산수=미청산수,
    )


# ── 시장 국면으로 나누기 ────────────────────────────────────────


def 국면고르기(구간들: list[구간], 국면표: dict, 볼국면: str) -> list[구간]:
    """그 국면에서 시작한 구간만 남긴다.

    **구간의 시작일로 가른다.** 20영업일 구간 하나가 조정에서 시작해 하락에서
    끝나는 일이 흔한데, 그때 어느 국면으로 셀지를 정해야 한다. 시작일을 쓰는
    이유는 그날이 실제로 알 수 있는 날이기 때문이다. 끝일로 가르면 그 구간을
    시작할 때는 몰랐던 정보로 나누는 것이 된다.

    국면을 모르는 날(자료가 모자란 앞부분)에서 시작한 구간은 뺀다. 모르는
    것을 상승으로 채우지 않는다."""
    return [ㄱ for ㄱ in 구간들 if 국면표.get(ㄱ.시작일) == 볼국면]


def 국면매매(매매들, 국면표: dict, 볼국면: str) -> list:
    """그 국면에서 산 매매만 남긴다. 진입일로 가른다."""
    나온것 = []
    for ㄱ in 매매들 or []:
        진입 = getattr(ㄱ, "entry_date", None)
        if 진입 is not None and 국면표.get(진입) == 볼국면:
            나온것.append(ㄱ)
    return 나온것


# ── 한 전략을 한 조건에서 잰 결과 ───────────────────────────────


@dataclass(frozen=True)
class 잰것:
    """전략 하나를 상한 하나, 슬리피지 하나로 잰 것.

    **조건을 값과 같이 들고 다닌다.** 조건 없는 숫자는 나중에 확인할 수
    없다. 어느 종목 목록으로 언제 잰 것인지가 숫자만큼 중요하다."""

    전략: str
    상한: int
    슬리피지: float
    매매대상: str
    시작일: date
    끝일: date
    잰날: date
    #: 겹치지 않는 구간으로 잰 것. 판단은 이쪽을 쓴다.
    구간: 구간성적
    #: 겹치는 구간으로 잰 것. 그림에 쓴다.
    겹친구간: 구간성적 | None
    매매: 매매성적
    #: 전 기간을 이어서 굴렸을 때의 누적 수익률(%)과 최대낙폭(%)
    누적수익률: float | None = None
    최대낙폭: float | None = None
    #: 몇 종목을 놓고 잰 것인가. 목록 이름만으로는 나중에 알 수 없다.
    #: 시트 종목은 주마다 바뀌어서, 같은 "sheet"라도 잰 날에 따라 수가 다르다.
    종목수: int = 0
    #: 어느 시장 국면만 모아 잰 것인가. "전체"면 안 나눈 것이다.
    #: 상승·조정·하락은 `analysis/market_regime.py`가 정한다.
    #:
    #: **국면별로 나눈 것에는 누적 수익률과 최대낙폭이 없다.** 그 값들은
    #: 처음부터 끝까지 이어 굴렸을 때의 값인데, 국면 구간은 띄엄띄엄
    #: 떨어져 있어서 이어 붙이면 없는 매매를 만든 셈이 된다.
    국면: str = "전체"

    @property
    def 이_상한에_맞나(self) -> bool | None:
        """기간 만료로 끝난 매매가 절반을 넘으면 이 상한에 안 맞는 전략이다.

        **자동으로 빼지는 않는다.** 화면에 표시만 하고 판단은 사람이 한다."""
        ㄱ = self.매매.기간만료비율
        return None if ㄱ is None else ㄱ < 50.0


# ── 파일에 적힌 줄을 다시 읽기 ──────────────────────────────────


def 구간성적으로(칸: dict | None) -> 구간성적 | None:
    """JSON에 적힌 칸을 다시 `구간성적`으로. 없는 값은 None 그대로 둔다."""
    if not 칸:
        return None
    return 구간성적(
        길이=int(칸.get("길이") or 0), 겹침=bool(칸.get("겹침")),
        구간수=int(칸.get("구간수") or 0),
        기하평균=칸.get("기하평균"), 연환산=칸.get("연환산"),
        산술평균=칸.get("산술평균"), 중앙값=칸.get("중앙값"),
        플러스비율=칸.get("플러스비율"), 하위10=칸.get("하위10"),
        하위25=칸.get("하위25"), 최악=칸.get("최악"), 최고=칸.get("최고"),
        표준편차=칸.get("표준편차"), 하락대비수익=칸.get("하락대비수익"),
        구간낙폭중앙값=칸.get("구간낙폭중앙값"),
    )


def 잰것으로(줄: dict) -> 잰것:
    """측정 결과 파일의 줄 하나를 `잰것`으로 되돌린다.

    **판단 기준이 이 모양에서 값을 꺼낸다.** 파일에서 읽어 순위를 낼 때와
    방금 계산해서 순위를 낼 때가 같은 길을 지나가야, 화면에 뜬 순위와
    계산이 낸 순위가 어긋나지 않는다."""
    매매칸 = 줄.get("매매") or {}
    return 잰것(
        전략=str(줄.get("전략") or ""), 상한=int(줄.get("상한") or 0),
        슬리피지=float(줄.get("슬리피지") or 0.0),
        매매대상=str(줄.get("매매대상") or ""),
        시작일=date.fromisoformat(줄["시작일"]) if 줄.get("시작일") else date.min,
        끝일=date.fromisoformat(줄["끝일"]) if 줄.get("끝일") else date.min,
        잰날=date.min,
        구간=구간성적으로(줄.get("구간")) or 구간성적(길이=0, 겹침=False, 구간수=0),
        겹친구간=구간성적으로(줄.get("겹친구간")),
        매매=매매성적(
            매매수=int(매매칸.get("매매수") or 0),
            승률=매매칸.get("승률"), 손익비=매매칸.get("손익비"),
            기대수익=매매칸.get("기대수익"), 중앙값=매매칸.get("중앙값"),
            평균보유일수=매매칸.get("평균보유일수"),
            갈래비율=dict(매매칸.get("갈래비율") or {}),
            미청산수=int(매매칸.get("미청산수") or 0),
        ),
        누적수익률=줄.get("누적수익률"), 최대낙폭=줄.get("최대낙폭"),
        종목수=int(줄.get("종목수") or 0),
        # 국면을 안 적던 판의 파일도 받는다. 그때는 전체로 잰 것이다.
        국면=str(줄.get("국면") or "전체"),
    )
