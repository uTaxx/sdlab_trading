def test_요약글이_상승_섹터_수와_시장을_같이_적는다():
    시장 = _시세(0.0005, 7).set_index("trade_date")["close"]
    움 = ㅅ.재기(_섹터시세({"SEMI": (0.002, 5), "BIO": (-0.002, 5)}), 이름표, 시장)
    글 = ㅅ.요약글(움, "d20")
    assert "20거래일" in 글
    assert "코스피" in 글
    assert "—" not in 글


def test_요약글이_무엇을_사라고_말하지_않는다():
    """섹터 강도로 종목을 거르는 것은 이미 재 보고 기각했다."""
    움 = ㅅ.재기(_섹터시세({"SEMI": (0.002, 5), "BIO": (-0.002, 5)}), 이름표)
    글 = ㅅ.요약글(움)
    for ㅁ in ("사세요", "추천", "유망", "주목", "매수하"):
        assert ㅁ not in 글, ㅁ


def test_계산한_섹터가_없으면_그렇게_적는다():
    글 = ㅅ.요약글(ㅅ.재기(_섹터시세({"ROBO": (0.001, 2)}), 이름표))
    assert "계산하지 못했습니다" in 글
