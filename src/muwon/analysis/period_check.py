"""지금 설정된 전략을 최근 1주·1개월·3개월·12개월·5년에 실행해 본다.

## 전략 평가 결과와 무엇이 다른가

`docs/전략평가.json`의 전략 평가 결과는 **2021~2025년을 해마다** 실행한 숫자다.
전략을 고를 때 쓰는 자료라 그렇게 잰다. 그런데 화면을 여는 사람이 묻는
것은 다른 질문이다.

    지금 걸어 둔 이 전략, 최근에는 어땠나.

이 두 질문의 답은 다르다. 전략 평가 결과는 다섯 해를 각각 재고, 여기서는
**한 구간을 통째로 이어서** 잰다. 3개월을 잰다는 것은 그 3개월을 처음부터
끝까지 굴렸다는 뜻이지, 3개월씩 여러 번 잰 평균이 아니다.

## 짧은 구간의 숫자는 거의 못 믿는다

3개월이면 거래가 스무 건 안팎이다(2026-08-28에 실제로 21건). 그중 크게
움직인 한두 종목이 숫자의 대부분을 만든다. 그것이 실력인지 운인지 구별할
방법이 없다. 그래서 이 모듈은 **거래 수를 언제나 같이 돌려준다.**
수익률만 보고 판단하면 안 되는 자리다.

거래 수 문턱(20건)은 **정말 표본이 없는 경우를 걸러 내는 값이지, 넘었다고
믿어도 된다는 값이 아니다.** 3개월은 그 문턱을 겨우 넘는 일이 잦다.

1주와 1개월은 그 문턱을 **거의 언제나 못 넘는다.** 1주는 거래가 0건인
회차가 흔하고, 그럴 때 수익률 0%가 표 맨 위에 온다. 지킨 것이 아니라
아무 일도 안 한 것이다. 이 둘은 "지금 뭘 하고 있나"를 보는 자리이지
"이 전략이 좋은가"를 묻는 자리가 아니다. 그래서 **전략 신호는 이 둘을
아예 안 본다**(`전략신호()`는 3개월·12개월·5년만 읽는다). 노이즈로 신호를
내면 매주 뭔가 뜨고, 매주 뜨는 것은 진짜일 때도 안 읽힌다.

## 평균이 아니라 제일 나빴던 구간을 같이 낸다

이 저장소의 1순위 판단 기준이다. 5년을 통째로 재면 +80%인데 그 안의 한
해가 -30%였을 수 있다. 그 해에 대부분 그만두고, 그러면 +80%는 받아 보지도
못한다. 그래서 구간마다 안을 나눠서 제일 나빴던 토막을 같이 낸다.
1주는 날로, 1개월은 주로, 3개월과 12개월은 달로, 5년은 해로 나눈다.
나눈 토막이 하나뿐이면 "제일 나빴던 토막"이 구간 전체와 같아져서 뜻이
없다. 1개월을 달이 아니라 주로 나누는 이유다.
"""

