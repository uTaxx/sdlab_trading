@dataclass(frozen=True)
class 기간정의:
    """화면에서 고를 수 있는 구간 하나."""

    이름: str
    #: 달 단위로 거슬러 올라갈 길이. 1주처럼 달로 안 떨어지면 0을 두고
    #: 날수를 쓴다.
    달수: int
    #: 안을 무엇으로 나눠 제일 나빴던 토막을 찾을 것인가.
    나눔: str  # "날" | "주" | "달" | "해"
    설명: str
    #: 달수가 0일 때 쓰는 길이. 달로 안 떨어지는 구간을 위한 것이다.
    날수: int = 0


#: **여기가 한 군데다.** 화면의 목록, 워크플로 입력, 스크립트 인자가 전부
#: 이 표를 읽는다. 세 곳에 따로 적으면 하나만 고치고 둘을 잊는다.
기간들: tuple[기간정의, ...] = (
    기간정의(
        "1주", 0, "날",
        "거래가 한 건도 없는 주가 흔합니다. 숫자가 나와도 그건 전략의 성적이 "
        "아니라 그 주에 걸린 한두 종목의 성적입니다. 방금 건 것이 돌기는 하는지 "
        "보는 용도이지, 잘하는지 보는 자리가 아닙니다",
        7,
    ),
    기간정의(
        # 달로 나누면 토막이 하나뿐이라 "제일 나빴던 달"이 구간 전체와 같아진다.
        "1개월", 1, "주",
        "거래가 열 건을 넘기기 어렵습니다. 이 숫자로 전략을 판단하면 안 됩니다. "
        "최근에 무슨 일이 있었는지 훑어보는 용도입니다",
    ),
    기간정의(
        "3개월", 3, "달",
        "한 분기 한 번뿐입니다. 거래는 스무 건 안팎이고, 크게 움직인 한두 종목이 "
        "숫자의 대부분을 만듭니다. 방금 바꾼 것이 돌고는 있는지 보는 용도입니다",
    ),
    기간정의(
        "12개월", 12, "달",
        "한 해치입니다. 상승장 한 번과 조정 한 번쯤은 들어갑니다",
    ),
    기간정의(
        "5년", 60, "해",
        "전략 평가 결과와 같은 길이입니다. 판단은 이 숫자로 합니다",
    ),
)

기간표: dict[str, 기간정의] = {ㄱ.이름: ㄱ for ㄱ in 기간들}

#: 나눈 단위를 사람 말로 부를 때의 이름과 조사. 받침이 있으면 "이/은",
#: 없으면 "가/는"이다. "제일 나빴던 해이"는 안 읽힌다.
_조사: dict[str, tuple[str, str, str]] = {
    "날": ("날", "이", "은"),
    "주": ("주", "가", "는"),
    "달": ("달", "이", "은"),
    "해": ("해", "가", "는"),
}


def 달빼기(끝: date, 달수: int) -> date:
    """달 단위로 거슬러 올라간다. 31일에서 한 달 빼면 그 달의 마지막 날."""
    해 = 끝.year
    달 = 끝.month - 달수
    while 달 <= 0:
        달 += 12
        해 -= 1
    return date(해, 달, min(끝.day, calendar.monthrange(해, 달)[1]))


def 구간(정의: 기간정의, 끝: date) -> tuple[date, date]:
    if 정의.날수:
        return 끝 - timedelta(days=정의.날수), 끝
    return 달빼기(끝, 정의.달수), 끝


def slice_for_range(
    histories: dict[str, pd.DataFrame], 시작: date, 끝: date
) -> dict[str, pd.DataFrame]:
    """매매할 구간 앞에 예열을 붙여 잘라 준다.

    예열이 모자라면 200일 이동평균 같은 것이 안 채워진 채로 돈다. 그러면
    "전략이 나빴다"인지 "전략이 켜지지도 않았다"인지 구별이 안 된다."""
    처음 = 시작 - timedelta(days=WARMUP_DAYS)
    잘린것 = {}
    for symbol, df in histories.items():
        창 = df[(df["trade_date"] >= 처음) & (df["trade_date"] <= 끝)]
        if len(창):
            잘린것[symbol] = 창
    return 잘린것


def 구간수익률(equity_curve: pd.DataFrame, 나눔: str) -> list[tuple[str, float]]:
    """평가금액 곡선을 달(또는 해)로 나눠 토막마다의 수익률을 낸다.

    토막의 시작값은 **앞 토막의 끝값**이다. 토막 안의 첫 값을 쓰면 토막이
    바뀌는 사이에 난 움직임이 어느 쪽에도 안 잡힌다."""
    if equity_curve is None or len(equity_curve) < 2:
        return []
    if "equity" not in equity_curve or "trade_date" not in equity_curve:
        return []

    def 이름(ㄴ) -> str:
        if 나눔 == "해":
            return f"{ㄴ.year}년"
        if 나눔 == "날":
            return f"{ㄴ.year}-{ㄴ.month:02d}-{ㄴ.day:02d}"
        if 나눔 == "주":
            # ISO 주차다. 연말연시에 해가 바뀌어도 순서가 안 꼬인다.
            해, 주, _ = ㄴ.isocalendar()
            return f"{해}-{주:02d}주"
        return f"{ㄴ.year}-{ㄴ.month:02d}"

    키 = [이름(ㄴ) for ㄴ in equity_curve["trade_date"]]
    나온것: list[tuple[str, float]] = []
    앞끝: float | None = None
    for 이름값, 묶음 in equity_curve.groupby(키, sort=True):
        시작값 = 앞끝 if 앞끝 is not None else float(묶음["equity"].iloc[0])
        끝값 = float(묶음["equity"].iloc[-1])
        if 시작값 > 0:
            나온것.append((str(이름값), (끝값 / 시작값 - 1) * 100))
        앞끝 = 끝값
    return 나온것


@dataclass(frozen=True)
class 기간성적:
    """한 구간을 통째로 실행한 결과."""

    이름: str
    시작: date
    끝: date
    metrics: BacktestMetrics
    #: 안을 나눈 구간들. 제일 나빴던 것을 찾는 데 쓴다.
    구간들: list[tuple[str, float]] = field(default_factory=list)
    #: 시세가 모자라 실제로는 이만큼밖에 못 실행한 경우 그 사실을 적는다.
    모자람: str = ""

    @property
    def 수익률(self) -> float:
        return self.metrics.total_return_pct

    @property
    def 최악토막(self) -> tuple[str, float] | None:
        """성과가 가장 낮은 구간. **평균보다 이것을 먼저 본다.**

        이름만 아직 "토막"인 이유가 있다. 이 값은 시트 `기간검증` 탭의 칸
        이름이자 n8n이 화면으로 넘기는 칸 이름이라, 여기서 바꾸면 세 곳을
        같이 바꿔야 한다. `tests/test_n8n_gateway_fields.py`가 그 셋을
        묶어 두고 있다."""
        return min(self.구간들, key=lambda ㅌ: ㅌ[1]) if self.구간들 else None

    @property
    def 믿을만한가(self) -> bool:
        """거래가 스무 건은 넘어야 숫자를 놓고 이야기할 수 있다.

        그 아래면 크게 오른 한 종목이 결과의 대부분을 만든다. 그것이 실력인지
        운인지 구별할 방법이 없다."""
        return self.metrics.num_trades >= 20


def 돌려보기(
    정의: 기간정의,
    전략만들기,
    histories: dict[str, pd.DataFrame],
    끝: date,
    policy: RiskPolicy,
    costs: TransactionCosts | None = None,
    entry_at_open: bool = True,
    exit_at_open: bool = True,
    섹터표: dict[str, str] | None = None,
    섹터상한: int = 0,
    섹터상한셈: str = "하루후보",
    점수순: bool = False,
    결제일수: int = 0,
    예수금: float = 10_000_000.0,
) -> 기간성적 | None:
    """한 구간을 통째로 실행한다. 시세가 없으면 None.

    **체결은 다음 날 시가가 기본이다.** 실거래 엔진이 실제로 그렇게 한다.
    종가 체결로 재면 그날 종가를 보고 그날 종가에 산 것이 되어, 실제로는
    낼 수 없는 성적이 나온다."""
    시작, 마지막 = 구간(정의, 끝)
    잘린것 = slice_for_range(histories, 시작, 마지막)
    if not 잘린것:
        return None

    있는날 = [df["trade_date"].max() for df in 잘린것.values()]
    처음날 = min(df["trade_date"].min() for df in 잘린것.values())
    모자람 = ""
    if 처음날 > 시작:
        모자람 = f"시세가 {처음날}부터라 그 앞은 못 실행했습니다"

    결과 = BacktestEngine(
        strategy=전략만들기(),
        risk_manager=RiskManager(policy_provider=lambda p=policy: p),
        costs=costs,
        exit_at_open=exit_at_open,
        entry_at_open=entry_at_open,
        # 순위를 내는 조건과 실제로 굴리는 조건이 다르면, "이 전략이 1위였다"가
        # 실제로 그 전략을 걸었을 때의 성적을 설명하지 못한다.
        섹터표=섹터표,
        섹터상한=섹터상한,
        섹터상한셈=섹터상한셈,
        점수순=점수순,
        결제일수=결제일수,
        initial_cash=예수금,
    ).run(잘린것, trade_from=시작)

    return 기간성적(
        이름=정의.이름,
        시작=시작,
        끝=max(있는날) if 있는날 else 마지막,
        metrics=compute_metrics(결과),
        구간들=구간수익률(결과.equity_curve, 정의.나눔),
        모자람=모자람,
    )


def 검증용정책(정책: RiskPolicy) -> RiskPolicy:
    """스위치 둘을 켠 채로 실행한다. **이건 무시가 아니라 질문이 다른 것이다.**

    킬스위치는 "오늘 실제로 주문을 낼 것인가"를 정하는 값이다. 여기서 묻는
    것은 "이 전략을 실행했으면 어땠을까"라 그 값과 상관이 없다.

    끄고 실행하면 한 주도 안 사서 수익률이 0.0%으로 나오는데, 화면에는 그것이
    "이 전략은 아무것도 못 번다"로 보인다. 조용히 틀린 답이라 막아야 한다.

    나머지 값(손절·익절·보유기간·비중·동시보유·하루손실)은 그대로 쓴다.
    지금 걸어 둔 기준으로 실행했을 때의 숫자를 보는 것이 이 기능의 목적이다."""
    from dataclasses import replace

    return replace(정책, trading_enabled=True, sell_enabled=True)


def 기준글(정책: RiskPolicy, 유니버스수: int, 유니버스종류: str) -> str:
    """이 숫자가 어느 조건에서 나온 것인지. **조건 없는 숫자는 검증이 안 된다.**"""
    익절 = f"{정책.take_profit_pct * 100:.0f}%" if 정책.take_profit_pct else "끔"
    보유 = f"{정책.max_holding_days}일" if 정책.max_holding_days else "전략이 정한 대로"
    return (
        f"손절 {정책.stop_loss_pct * 100:.0f}% · 익절 {익절} · 보유 {보유} · "
        f"비중 {정책.max_position_weight * 100:.0f}% · "
        f"동시보유 {정책.max_concurrent_positions}종목 · "
        f"유니버스 {유니버스종류} {유니버스수}종목 · 다음 날 시가 체결 · 슬리피지 0"
    )


def _낙폭말(낙폭: float) -> str:
    """최대낙폭을 사람 말로. **이 저장소가 제일 먼저 보는 숫자다.**"""
    if 낙폭 > -10:
        return "일반적인 변동 범위로 볼 수 있는 수준입니다."
    if 낙폭 > -20:
        return "적지 않은 하락폭입니다."
    if 낙폭 > -30:
        return "평가금액이 고점 대비 20% 이상 감소한 시점이 있었다는 의미입니다."
    return (
        "평가금액이 고점 대비 30% 이상 감소한 시점이 있었다는 의미입니다. "
        "이 구간에서 운용을 중단하면 이후 수익률은 실현되지 않습니다."
    )


def 평가글(성적: 기간성적, 정의: 기간정의) -> str:
    """한 구간의 숫자를 사람이 읽을 문장으로 옮긴다.

    **여기가 한 군데다.** 시트에 이 문장을 같이 쌓고 화면이 그대로 읽는다.
    화면에서 따로 문장을 만들면 시트에 남은 기록과 화면이 다른 말을 하게
    되고, 나중에 "그때 뭐라고 적혀 있었지"에 답할 수가 없다.

    **지어내지 않는다.** 숫자에서 바로 나오는 말만 적는다. 왜 그랬는지는
    이 함수가 알 수 없다."""
    ㅁ = 성적.metrics

    # 표본부터 본다. 표본이 없으면 뒤의 문장은 전부 뜻이 없다.
    if ㅁ.num_trades == 0:
        return (
            "이 기간에 매수가 발생하지 않았습니다. 손실을 방어한 것이 아니라 "
            "거래 자체가 없었던 것이므로, 수익률 0%를 성과로 해석하면 안 됩니다."
        )

    말: list[str] = []
    if 성적.믿을만한가:
        말.append(
            f"{정의.이름} 수익률 {ㅁ.total_return_pct:+.2f}%, 거래 {ㅁ.num_trades}건입니다."
        )
    else:
        말.append(
            f"{정의.이름} 수익률 {ㅁ.total_return_pct:+.2f}%이나 거래가 "
            f"{ㅁ.num_trades}건에 불과합니다. 일부 종목의 결과가 전체 성과를 "
            "좌우하므로 이 수치로 전략을 판단하기 어렵습니다."
        )

    최악 = 성적.최악토막
    if 최악:
        # 받침에 따라 조사가 달라진다. "해이 없습니다"는 안 읽힌다.
        단위, 이가, 은는 = _조사[정의.나눔]
        if 최악[1] >= 0:
            말.append(
                f"{단위} 단위로 나누면 손실이 발생한 {단위}{이가} 없습니다"
                f"(성과가 가장 낮은 {단위}{은는} {최악[0]}, {최악[1]:+.2f}%)."
            )
        else:
            말.append(
                f"성과가 가장 낮은 {단위}{은는} {최악[0]}, {최악[1]:+.2f}%입니다."
            )

    말.append(f"최대낙폭은 {ㅁ.max_drawdown_pct:.2f}%입니다. "
              + _낙폭말(ㅁ.max_drawdown_pct))

    if ㅁ.exposure_pct < 40:
        말.append(
            f"노출은 {ㅁ.exposure_pct:.0f}%입니다. 전체 거래일 중 종목을 보유한 "
            "날이 적어, 손실도 수익도 제한적으로 발생했을 수 있습니다."
        )
    elif ㅁ.exposure_pct > 90:
        말.append(
            f"노출은 {ㅁ.exposure_pct:.0f}%입니다. 검증 기간 대부분에서 종목을 "
            "보유한 상태였습니다."
        )

    if 성적.모자람:
        말.append(성적.모자람 + ".")
    return " ".join(말)


def 비교총평(정의: 기간정의, 줄들, 지금키: str = "", 기준=None) -> str:
    """전략을 여럿 견줬을 때의 한 문단.

    줄들은 (전략키, 기간성적) 목록이다. 순위는 `기준`이 정한 순서로 매긴다
    (2026-09-03에 바꿈). 전에는 수익률 하나로만 매겼는데, 저장소가 적어 둔
    1순위 판단 기준은 가장 나빴던 구간이었다.

    **1등을 고르라는 말은 절대 안 적는다.** 한 구간에서 제일 좋았던 것을
    고르는 일이 곧 과최적화다."""
    from muwon.analysis.judgment import 기본기준, 줄세우기

    ㄱ준 = 기준 or 기본기준
    산것 = [(ㅋ, ㅅ) for ㅋ, ㅅ in 줄들 if ㅅ.metrics.num_trades > 0]
    if not 산것:
        return "이 기간에 매수가 발생한 전략이 없습니다."

    차례 = 줄세우기(산것, ㄱ준, lambda ㄱ: ㄱ[1])
    플러스 = [ㄱ for ㄱ in 차례 if ㄱ[1].metrics.total_return_pct > 0]
    안산것 = len(줄들) - len(산것)

    말 = [
        (
            f"{정의.이름} 기준, 매수가 발생한 전략 {len(차례)}개 중 "
            f"수익률이 플러스인 전략은 {len(플러스)}개입니다."
        ),
        # 어떤 순서로 세운 표인지를 적는다. 순위가 수익률로 나지 않으므로,
        # 이 말이 없으면 수익률이 낮은 전략이 위에 있는 표를 읽을 수 없다.
        ㄱ준.설명글(),
    ]
    if len(플러스) <= len(차례) // 4:
        말.append(
            "대부분의 전략이 마이너스입니다. 개별 전략의 문제라기보다 "
            "해당 기간의 시장 영향으로 보입니다."
        )

    if 안산것:
        말.append(f"매수가 발생하지 않은 전략 {안산것}개는 순위에서 제외했습니다.")

    if 지금키:
        자리 = next((i for i, (ㅋ, _) in enumerate(차례, 1) if ㅋ == 지금키), 0)
        if 자리:
            ㅅ = dict(차례)[지금키]
            말.append(
                f"현재 설정된 전략은 {len(차례)}개 중 {자리}위, "
                f"{ㅅ.metrics.total_return_pct:+.2f}%입니다."
            )

    낙폭작은것 = min(차례, key=lambda ㄱ: -ㄱ[1].metrics.max_drawdown_pct)
    말.append(
        f"최대낙폭이 가장 작은 전략은 {낙폭작은것[1].metrics.max_drawdown_pct:.2f}%입니다."
    )
    말.append(
        "이 순위의 1위를 그대로 선택하는 것은 권장하지 않습니다. 특정 기간의 "
        "결과에 맞춰 전략을 선택하면 과최적화가 발생합니다."
    )
    return " ".join(말)


# ── 전략을 다시 볼 때가 됐나 ────────────────────────────────────────
#
# **이 신호는 "바꿔라"가 아니라 "봐야 한다"다.** 한 구간에서 제일 좋았던
# 것으로 갈아타는 일이 곧 과최적화라, 그런 말은 여기서 절대 안 만든다.
#
# 여기서 묻는 것은 하나다. **지금 설정된 전략이 예상 밖으로 굴러가고 있나.**
# 장이 나빠서 다 같이 마이너스인 것과, 이 전략만 유난히 나쁜 것은 다르다.
# 전자는 신호가 아니고 후자는 신호다.

등급들 = ("이상없음", "살펴볼것", "확인필요")


@dataclass(frozen=True)
class 신호:
    등급: str
    제목: str
    설명: str


def 더센등급(ㄱ: str, ㄴ: str) -> str:
    return 등급들[max(등급들.index(ㄱ), 등급들.index(ㄴ))]


def 전략신호(성적들: dict, 순위: dict | None = None) -> list[신호]:
    """지금 설정된 전략을 다시 볼 이유가 있는지 본다.

    성적들은 {구간이름: 기간성적}이다. 순위는 전략을 여럿 견줬을 때만
    있고 {구간이름: (자리, 산것수, 플러스수)} 꼴이다.

    **아무 이유도 못 찾으면 빈 목록을 돌려준다.** 억지로 한 줄 만들면
    매번 뭔가 뜨게 되고, 그러면 진짜 신호가 왔을 때 안 읽는다."""
    난것: list[신호] = []
    # **1주와 1개월은 일부러 안 본다.** 거래가 몇 건뿐이라 한 종목이 숫자를
    # 통째로 만든다. 그것으로 신호를 내면 매주 뭔가 뜨고, 매주 뜨는 것은
    # 진짜 신호가 왔을 때도 안 읽힌다.
    긴것 = 성적들.get("5년")
    한해 = 성적들.get("12개월")
    석달 = 성적들.get("3개월")

    # ── 걸어 둘 근거 자체가 없는 경우 ────────────────────────────
    if 긴것 and 긴것.metrics.num_trades >= 20 and 긴것.수익률 <= 0:
        난것.append(신호(
            "확인필요", "5년 전체 기간에서도 수익률이 플러스가 아닙니다",
            f"5년 수익률이 {긴것.수익률:+.2f}%입니다. 최근 구간만 부진한 것이 "
            "아니라, 현재 데이터로는 이 전략을 유지할 근거를 확인하기 어렵습니다.",
        ))

    # ── 신호가 아예 안 나오는 경우 ──────────────────────────────
    if 석달 and 석달.metrics.num_trades == 0:
        난것.append(신호(
            "확인필요", "최근 3개월간 매수가 발생하지 않았습니다",
            "매수 신호가 한 건도 산출되지 않았습니다. 매수 조건이 지나치게 "
            "제한적이거나, 매매 대상 종목 구성이 전략과 맞지 않을 수 있습니다.",
        ))
    elif 석달 and 석달.metrics.exposure_pct < 10:
        난것.append(신호(
            "살펴볼것", "최근 3개월간 보유 기간이 매우 짧습니다",
            f"노출이 {석달.metrics.exposure_pct:.0f}%입니다. 전체 거래일 중 "
            "종목을 보유한 날이 거의 없어, 손실과 수익 모두 제한적입니다.",
        ))

    # ── 5년 중 제일 나빴던 구간이 최근에 몰려 있나 ───────────────
    #
    # 12개월 낙폭이 5년 낙폭에 거의 닿으면, 5년을 통틀어 제일 나빴던 구간이
    # 바로 최근 1년 안에 있다는 뜻이다. 옛날 얘기가 아니다.
    if 긴것 and 한해 and 긴것.metrics.max_drawdown_pct < -1:
        몫 = 한해.metrics.max_drawdown_pct / 긴것.metrics.max_drawdown_pct
        if 몫 >= 0.9:
            난것.append(신호(
                "살펴볼것", "최근 1년 최대낙폭이 5년 전체 최대낙폭과 거의 같습니다",
                f"최근 1년간 평가금액이 고점 대비 "
                f"{abs(한해.metrics.max_drawdown_pct):.1f}%까지 감소했습니다. "
                f"5년 전체 최대낙폭은 "
                f"{abs(긴것.metrics.max_drawdown_pct):.1f}%입니다. "
                "5년 중 손실이 가장 컸던 구간이 최근 1년에 포함되어 있다는 "
                "의미입니다.",
            ))

    # ── 장 탓인가, 이 전략 탓인가 ────────────────────────────────
    #
    # 다 같이 마이너스면 구간 문제라 신호가 아니다. 남들은 버텼는데 이것만
    # 하위권이면 그때가 다시 볼 때다.
    for 이름 in ("3개월", "12개월"):
        자리 = (순위 or {}).get(이름)
        if not 자리:
            continue
        순, 전체, 플러스 = 자리
        if 전체 < 10:
            continue
        버틴쪽 = 플러스 / 전체
        하위인가 = 순 > 전체 * 2 / 3
        if 버틴쪽 >= 1 / 3 and 하위인가:
            난것.append(신호(
                "살펴볼것", f"{이름} 기준으로 다른 전략 대비 하위권입니다",
                f"전략 {전체}개 중 {플러스}개가 플러스인데 현재 설정된 전략은 "
                f"{순}위입니다. 시장 전체의 영향이라기보다 이 전략이 해당 "
                "구간과 맞지 않았을 가능성이 있습니다.",
            ))
        elif 버틴쪽 < 1 / 4 and 하위인가:
            난것.append(신호(
                "이상없음", f"최근 {이름} 부진은 시장 영향이 큰 것으로 보입니다",
                f"비교한 전략 {전체}개 중 플러스는 {플러스}개이고 현재 설정된 "
                f"전략은 {순}위입니다. 이 전략만의 문제가 아니라 해당 기간에 "
                "전반적으로 성과가 낮았습니다.",
            ))
    return 난것


def 신호글(난것: list[신호]) -> tuple[str, str]:
    """(등급, 사람이 읽을 글). 아무것도 없으면 이상없음."""
    if not 난것:
        return "이상없음", (
            "현재 설정된 전략을 재검토할 사유가 발견되지 않았습니다. 수익성이 "
            "양호하다는 의미가 아니라, 예상 범위를 벗어난 동작이 없다는 의미입니다."
        )
    등급 = "이상없음"
    줄들 = []
    # 신호가 여럿이면 줄마다 등급이 다를 수 있어서 딱지를 붙인다. 하나뿐이면
    # 머리말의 등급과 똑같은 말이 되므로 안 붙인다.
    딱지 = len(난것) > 1
    for ㅅ in 난것:
        등급 = 더센등급(등급, ㅅ.등급)
        줄들.append((f"[{ㅅ.등급}] " if 딱지 else "") + f"{ㅅ.제목}. {ㅅ.설명}")
    # 맺음말 앞을 한 줄 띄운다. 폰에서 신호와 붙어 있으면 어디까지가 무슨
    # 일이 났다는 말이고 어디부터가 할 일인지 구별이 안 된다.
    줄들.append("")
    줄들.append(
        "즉시 조치가 필요한 항목은 없습니다. 이 신호는 전략 변경을 지시하는 "
        "것이 아니라 검토를 권고하는 것입니다. 변경 여부를 판단할 때는 다른 "
        "전략도 같은 조건으로 다시 검증한 뒤 비교해야 합니다."
    )
    return 등급, "\n".join(줄들)


