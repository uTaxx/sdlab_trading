def test_열쇠가_결정일과_종목으로_한_줄만_만든다():
    """같은 날 같은 종목이 두 줄이면 화면이 어느 것을 그릴지 모른다."""
    줄들 = ㅅ.줄들만들기(_여럿(1, 1, 5.0, -5.0), date(2026, 9, 30))
    assert len({ㄱ[0] for ㄱ in 줄들}) == 2
    assert 줄들[0][0].startswith("A2026-09-01|")


def test_못_잰_칸은_빈_글자로_남긴다():
    줄 = ㅅ.줄들만들기(
        [ㅅ.되짚기(결정=_결정(), 기준가=100.0, 등락={"d5": 3.0, "d20": None})],
        date(2026, 9, 10),
    )[0]
    assert 줄[ㅅ.머리.index("5거래일%")] == "3.00"
    assert 줄[ㅅ.머리.index("20거래일%")] == ""


def test_줄의_칸수가_머리와_같다():
    for 줄 in ㅅ.줄들만들기(_여럿(2, 2, 5.0, -5.0), date(2026, 9, 30)):
        assert len(줄) == len(ㅅ.머리)


def test_승인_여부를_예와_아니오로_적는다():
    """True/False로 적으면 시트에서 읽는 쪽이 글자와 참거짓을 둘 다
    다뤄야 한다."""
    줄들 = ㅅ.줄들만들기(_여럿(1, 1, 5.0, -5.0), date(2026, 9, 30))
    값들 = {줄[ㅅ.머리.index("승인")] for 줄 in 줄들}
    assert 값들 == {"예", "아니오"}


# ── n8n 사본과 칸 번호가 맞는가 ─────────────────────────────────


def test_창구_사본의_칸번호가_머리와_같다():
    """**한 칸만 밀려도 표의 모든 줄이 어긋나는데 화면은 멀쩡히 그려진다.**
    등락률 칸에 예상가가 들어가 있어도 숫자라서 안 보인다."""
    사본 = (뿌리 / "n8n" / "대시보드자료_승인되짚기모양으로.js").read_text(
        encoding="utf-8"
    )
    번호표 = {
        이름: int(번호)
        for 이름, 번호 in re.findall(
            r"^\s+([가-힣A-Za-z0-9]+): (?:수\()?값\(ㅈ, (\d+)\)", 사본, re.MULTILINE
        )
    }
    쓰는이름 = {
        "잰때": "잰때", "결정일": "결정일", "종목코드": "종목코드",
        "종목명": "종목명", "예상가": "예상가", "기준가": "기준가",
        "d5": "5거래일%", "d20": "20거래일%", "상태": "상태",
    }
    for 창구이름, 시트이름 in 쓰는이름.items():
        assert 창구이름 in 번호표, f"창구 사본이 {창구이름}을 안 읽습니다"
        assert 번호표[창구이름] == ㅅ.머리.index(시트이름), (
            f"{창구이름}이 {번호표[창구이름]}번인데 시트에서는 "
            f"{ㅅ.머리.index(시트이름)}번입니다"
        )


def test_창구_사본이_승인_칸을_참거짓으로_바꾼다():
    사본 = (뿌리 / "n8n" / "대시보드자료_승인되짚기모양으로.js").read_text(
        encoding="utf-8"
    )
    자리 = ㅅ.머리.index("승인")
    assert f'승인: 값(ㅈ, {자리}) === "예"' in 사본
