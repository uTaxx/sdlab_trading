"""매수 후보 밑에 붙는 **승인 / 거절 버튼.**

## 왜 버튼인가

지금은 `/승인 005930`을 손으로 쳐야 한다. 종목코드 여섯 자리를 폰에서
정확히 치는 일은 생각보다 귀찮고, **귀찮으면 안 하게 되고, 안 하면 승인
스텝이 없는 것과 같다.**

버튼은 한 번 누르면 끝이고, **무엇을 누르는지 이름으로 보인다** — 코드를
잘못 치면 엉뚱한 종목을 승인하지만 버튼은 그럴 수가 없다.

## 누른 뒤에 무엇이 남나

**거절을 빈 칸이 아니라 `N`으로 적는다.** 지금 규칙상 빈 칸도 안 사는
것이라 매매 결과는 같지만, 나중에 기록을 볼 때 **"안 봤다"와 "보고
거절했다"는 전혀 다른 이야기**다. 앞의 것은 알림이 안 갔거나 놓친 것이고,
뒤의 것은 판단이다. 구별해 두지 않으면 승인 스텝이 실제로 쓰이고 있는지
알 수가 없다.

## 눌러도 안 되는 것

**매매를 켜는 버튼은 만들지 않는다.** 폰 화면에서 손가락이 스치는 일이 실제로
일어나고, 그 결과가 '매매 켜짐'이면 안 된다. 끄는 것은 반대 방향이라 괜찮다.

## 전략 변경 버튼은 두 단계다 (2026-09-01)

전략을 바꾸는 버튼은 원래 만들지 않기로 해 두었던 것이다. 같은 이유였다.
그런데 전략 검토 결과를 폰에서 받고 시트를 열어야만 승인할 수 있으면, 열기
귀찮아서 안 하게 되고 그러면 검토가 없는 것과 같다. 매수 승인에서 이미 겪은
문제다.

그래서 만들되 **손가락이 스쳐도 그것만으로는 안 바뀌게** 한다.

1. 전략 버튼을 누르면 **예약만** 된다. 그 자리에 확인 버튼과 취소 버튼이 뜬다.
2. 확인을 눌러야 예약이 확정된다.
3. 확정돼도 그날 바뀌지 않는다. **다음 거래일 08:20**에 반영한다. 그 사이에
   취소 버튼을 누르면 없던 일이 된다.

구간마다 앞선 전략이 다를 수 있어서 버튼이 여럿이다. 하나를 확정하면 나머지
버튼은 사라진다. 둘을 동시에 예약하면 무엇이 반영되는지 알 수 없다.

## 64바이트

텔레그램은 버튼에 붙일 수 있는 자료를 **64바이트**로 제한한다. 그래서
`a|2026-08-20|005930`(19바이트)처럼 짧게 적는다. 종목명 같은 것을 넣으면
한글 몇 자에 넘어간다.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from datetime import date

from muwon.notify import footer

#: 버튼 하나에 붙는 자료의 최대 길이(텔레그램 제한).
MAX_CALLBACK_BYTES = 64
#: 버튼에 적을 종목명 길이. 길면 버튼이 두 줄로 접혀 목록이 안 읽힌다.
NAME_LEN = 9

승인, 거절, 전부승인, 전부거절 = "a", "r", "A", "R"

#: 전략 변경 버튼. 매수 승인과 글자를 겹치지 않게 둔다 — 겹치면 옛 메시지의
#: 버튼이 엉뚱한 일을 한다.
전략고름, 전략확정, 전략취소 = "s", "c", "x"

#: 전략 키가 이 길이를 넘으면 버튼 자료가 64바이트를 넘는다. 지금 제일 긴
#: 키가 24자라 여유가 있지만, 새 전략을 등록할 때 여기서 걸리게 해 둔다.
MAX_KEY_LEN = 40


@dataclass(frozen=True)
class 버튼항목:
    """버튼 하나를 그리는 데 필요한 전부. 후보 전체를 끌고 다닐 필요가 없다."""

    symbol: str
    name: str


@dataclass(frozen=True)
class 누름:
    종류: str            # 승인 / 거절 / 전부승인 / 전부거절 / 전략고름 /
                        # 전략확정 / 전략취소 / 모름
    날짜: date | None = None
    symbol: str = ""
    말: str = ""         # 못 알아들었을 때 돌려줄 말
    #: 전략 버튼일 때만 찬다. 매수 승인 버튼에서는 언제나 빈 값이다.
    전략키: str = ""


def callback_data(종류: str, 날짜: date, 꼬리: str = "") -> str:
    """`꼬리`는 매수 버튼이면 종목코드, 전략 버튼이면 전략 키다."""
    값 = f"{종류}|{날짜.isoformat()}" + (f"|{꼬리}" if 꼬리 else "")
    if len(값.encode()) > MAX_CALLBACK_BYTES:
        raise ValueError(f"버튼 자료가 {MAX_CALLBACK_BYTES}바이트를 넘습니다: {값!r}")
    return 값


def parse_callback(값: str) -> 누름:
    """버튼에서 온 자료 → 무엇을 눌렀나. **네트워크도 상태도 없다.**"""
    조각 = (값 or "").split("|")
    종류 = 조각[0] if 조각 else ""
    if 종류 not in (승인, 거절, 전부승인, 전부거절, 전략고름, 전략확정, 전략취소):
        return 누름("모름", 말="모르는 버튼입니다. 새로 온 목록에서 눌러 주세요.")
    if len(조각) < 2:
        return 누름("모름", 말="날짜가 없는 버튼입니다.")
    try:
        날 = date.fromisoformat(조각[1])
    except ValueError:
        return 누름("모름", 말="날짜를 못 읽었습니다.")

    if 종류 == 전략취소:
        return 누름("전략취소", 날짜=날)
    if 종류 in (전략고름, 전략확정):
        키 = 조각[2] if len(조각) > 2 else ""
        # 전략 키는 영문 소문자·숫자·밑줄만 쓴다. 다른 글자가 오면 우리가
        # 만든 버튼이 아니다.
        if not 키 or not all(ㄱ.isascii() and (ㄱ.isalnum() or ㄱ == "_") for ㄱ in 키):
            return 누름("모름", 말="전략 이름이 이상한 버튼입니다.")
        return 누름(
            "전략고름" if 종류 == 전략고름 else "전략확정", 날짜=날, 전략키=키
        )

    if 종류 in (전부승인, 전부거절):
        return 누름("전부승인" if 종류 == 전부승인 else "전부거절", 날짜=날)

    if len(조각) < 3 or not (조각[2].isdigit() and len(조각[2]) == 6):
        return 누름("모름", 말="종목코드가 이상한 버튼입니다.")
    return 누름("승인" if 종류 == 승인 else "거절", 날짜=날, symbol=조각[2])


def keyboard(후보들, 날짜: date, 결정: dict[str, str] | None = None) -> dict:
    """후보 목록 → 버튼 판. `결정`을 주면 이미 누른 것이 표시된다.

    누를 때마다 이 판을 다시 만들어 갈아 끼운다 — **화면이 지금 상태를
    보여 주지 않으면 방금 누른 게 먹었는지 알 수가 없다.**"""
    결정 = 결정 or {}
    줄들 = []
    for c in 후보들:
        d = 결정.get(c.symbol, "")
        이름 = c.name if len(c.name) <= NAME_LEN else c.name[: NAME_LEN - 1] + "…"
        승인칸 = f"☑️ {이름} 승인함" if d == "Y" else f"✅ {이름}"
        거절칸 = "🚫 거절함" if d == "N" else "❌"
        줄들.append([
            {"text": 승인칸, "callback_data": callback_data(승인, 날짜, c.symbol)},
            {"text": 거절칸, "callback_data": callback_data(거절, 날짜, c.symbol)},
        ])
    if len(후보들) > 1:
        줄들.append([
            {"text": "✅ 전부 승인", "callback_data": callback_data(전부승인, 날짜)},
            {"text": "❌ 전부 거절", "callback_data": callback_data(전부거절, 날짜)},
        ])
    return {"inline_keyboard": 줄들}


#: 상태 블록의 시작 표시. 다시 그릴 때 여기서부터 잘라 낸다.
상태표시 = "──────────"


def 상태블록(후보들, 결정: dict[str, str] | None = None) -> str:
    """지금 무엇이 승인이고 무엇이 거절인지 **글로도 적는다.**

    버튼 글자만 바꾸면 나중에 대화를 훑을 때 무슨 일이 있었는지 안 보인다.
    버튼은 지금 누르는 것이고, 이 블록은 **남는 기록**이다.

    아직 안 정한 것을 따로 세는 이유는, 0이 되어야 다 본 것이기 때문이다 —
    승인 1건이라는 말만으로는 나머지를 봤는지 알 수 없다."""
    결정 = 결정 or {}
    승인된것 = [c.name for c in 후보들 if 결정.get(c.symbol) == "Y"]
    거절된것 = [c.name for c in 후보들 if 결정.get(c.symbol) == "N"]
    아직 = [c.name for c in 후보들 if c.symbol not in 결정]

    줄 = [상태표시, "지금 상태"]
    줄.append(f"  ✅ 승인 {len(승인된것)}종목" + (f" — {', '.join(승인된것)}" if 승인된것 else ""))
    줄.append(f"  ❌ 거절 {len(거절된것)}종목" + (f" — {', '.join(거절된것)}" if 거절된것 else ""))
    if 아직:
        줄.append(f"  ⬜ 아직 안 정함 {len(아직)}종목 — {', '.join(아직)}")
    else:
        줄.append("  ⬜ 아직 안 정함 없음 — 다 보셨습니다")
    if 승인된것:
        줄.append("")
        줄.append("승인한 것은 다음 매수 때 삽니다. 그 전까지는 다시 눌러 되돌릴 수 있습니다.")
    return "\n".join(줄)


def 글에_상태붙이기(원래글: str, 후보들, 결정: dict[str, str] | None = None) -> str:
    """이미 보낸 글에 상태 블록을 갈아 끼운다.

    앞선 상태 블록을 잘라 내고 새로 붙인다 — 안 자르면 누를 때마다 글이
    길어져서 정작 후보 목록이 화면 밖으로 밀려난다.

    **대시보드 링크도 먼저 떼야 한다.** 링크는 글 맨 아래에 붙는데, 상태
    블록이 아직 없는 첫 글에서는 `상태표시`로 자를 자리가 없어 링크가 몸통에
    남는다. 그러면 상태 블록이 링크 **아래**로 가고, 다음 번에 링크를 떼면
    그 아래 것까지 같이 떨어져 나가 상태 블록이 통째로 사라진다."""
    몸통 = footer.떼기(원래글 or "").split(상태표시)[0].rstrip()
    return 몸통 + "\n\n" + 상태블록(후보들, 결정)


def 누른뒤말(누름값: 누름, 이름: str = "") -> str:
    """버튼을 누르면 화면 위에 잠깐 뜨는 한 줄. **짧아야 읽힌다.**"""
    if 누름값.종류 == "승인":
        return f"{이름 or 누름값.symbol} 승인"
    if 누름값.종류 == "거절":
        return f"{이름 or 누름값.symbol} 거절"
    if 누름값.종류 == "전부승인":
        return "전부 승인"
    if 누름값.종류 == "전부거절":
        return "전부 거절"
    return 누름값.말


# ── 전략 변경 버튼 ────────────────────────────────────────────────
#
# 매수 승인 버튼과 파일을 같이 쓰는 이유는 하나다. **콜백 글자가 겹치면
# 안 되기 때문이다.** 옛 메시지의 버튼이 그대로 살아 있어서, 글자를 재사용하면
# 어제 누른 자리가 오늘 다른 일을 한다. 한 곳에 모아 두면 겹치는 것이 보인다.


@dataclass(frozen=True)
class 전략버튼:
    """버튼 하나를 그리는 데 필요한 전부."""

    키: str
    이름: str
    구간: str
    #: 그 구간에서 이 전략의 수익률(%). 버튼 글자에 같이 적는다.
    수익률: float | None = None


#: 버튼에 적을 전략 이름 길이. 길면 버튼이 두 줄로 접혀 목록이 안 읽힌다.
전략이름길이 = 14


def _줄인이름(이름: str) -> str:
    return 이름 if len(이름) <= 전략이름길이 else 이름[: 전략이름길이 - 1] + "…"


def 전략키보드(버튼들: Sequence[전략버튼], 날짜: date) -> dict | None:
    """1단계. 구간마다 앞선 전략을 하나씩 버튼으로 낸다.

    **누르면 예약만 된다.** 같은 전략이 여러 구간에서 앞서면 버튼은 하나로
    합치고 구간을 모아 적는다. 같은 것을 두 번 누르게 하면 무엇이 다른지
    찾느라 시간을 쓴다."""
    if not 버튼들:
        return None

    묶음: dict[str, list[전략버튼]] = {}
    for ㅂ in 버튼들:
        묶음.setdefault(ㅂ.키, []).append(ㅂ)

    줄들 = []
    for 키, 것들 in 묶음.items():
        if len(키) > MAX_KEY_LEN:
            # 버튼을 못 만드는 것이 조용히 넘어가면 그 전략만 승인할 길이
            # 없어진다. 여기서 멈추고 이름을 줄이게 한다.
            raise ValueError(f"전략 키가 {MAX_KEY_LEN}자를 넘어 버튼을 못 만듭니다: {키}")
        구간글 = "·".join(ㄱ.구간 for ㄱ in 것들)
        줄들.append([{
            "text": f"🔁 {_줄인이름(것들[0].이름)} ({구간글})",
            "callback_data": callback_data(전략고름, 날짜, 키),
        }])
    return {"inline_keyboard": 줄들}


def 확인키보드(키: str, 이름: str, 날짜: date) -> dict:
    """2단계. 손가락이 스쳐도 이 판까지 눌러야 확정된다."""
    return {"inline_keyboard": [[
        {"text": f"✅ {_줄인이름(이름)}으로 확정",
         "callback_data": callback_data(전략확정, 날짜, 키)},
        {"text": "↩️ 취소", "callback_data": callback_data(전략취소, 날짜)},
    ]]}


def 예약키보드(날짜: date) -> dict:
    """확정된 뒤에 남는 판. 반영 전까지 되돌릴 수 있어야 한다."""
    return {"inline_keyboard": [[
        {"text": "↩️ 예약 취소", "callback_data": callback_data(전략취소, 날짜)},
    ]]}


def 전략상태블록(예약: str = "", 이름: str = "", 확정됐나: bool = False) -> str:
    """글 아래에 붙는 지금 상태. 매수 승인의 상태 블록과 같은 자리다."""
    if not 예약:
        return (
            f"{상태표시}\n"
            "예약된 전략 변경이 없습니다. 위 버튼을 누르면 예약만 되고, "
            "확인을 한 번 더 눌러야 확정됩니다."
        )
    if not 확정됐나:
        return (
            f"{상태표시}\n"
            f"{이름 or 예약}을 고르셨습니다. 아직 확정되지 않았습니다. "
            "아래 확정 버튼을 눌러 주세요."
        )
    return (
        f"{상태표시}\n"
        f"{이름 or 예약}으로 변경이 예약되었습니다. 다음 거래일 매수 후보 산출 "
        "전에 반영합니다. 그 전까지 아래 취소 버튼으로 되돌릴 수 있습니다."
    )
