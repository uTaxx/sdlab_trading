def test_화면이_자료의_칸_이름을_지어내지_않는다():
    """화면은 칸 이름으로 자리를 찾는다. 파이썬이 칸 이름을 바꾸면 화면은
    그 자리를 못 찾아 전부 줄표로 그리는데, 아무것도 빨갛게 되지 않는다."""
    import importlib.util

    자리 = importlib.util.spec_from_file_location(
        "export_window_data", 뿌리 / "scripts" / "export_window_data.py")
    뽑기 = importlib.util.module_from_spec(자리)
    자리.loader.exec_module(뽑기)

    쓰는것 = set(re.findall(r'찾기값\([^,]+,\s*[^,]+,\s*"([^"]+)"\)', 글))
    assert 쓰는것, "찾기값을 쓰는 곳을 못 찾았습니다. 시험이 아무것도 안 봅니다."
    없는것 = 쓰는것 - set(뽑기.칸들)
    assert not 없는것, f"뽑는 자료에 없는 칸을 읽습니다: {sorted(없는것)}"


def _찾기덩이() -> str:
    """전략 찾기 탭의 글만. 길이로 자르면 탭이 길어질 때 조용히 짧아진다.

    줄바꿈과 들여쓰기는 지운다. HTML은 문단 중간에서 줄이 바뀌므로 그대로
    두면 화면에 있는 문장을 시험이 못 찾는다."""
    자리 = 쪽.index('id="쪽-찾기"')
    끝 = 쪽.index("</section>", 자리)
    return re.sub(r"\s+", " ", 쪽[자리:끝])


