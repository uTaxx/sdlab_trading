def test_지침을_바꾸면_순위가_실제로_바뀐다():
    """화면에서 고른 것이 아무 일도 안 하는 것이 제일 나쁘다."""
    줄들 = [_줄("많이번것", 수익률=40.0, 최악=-20.0),
          _줄("덜잃은것", 수익률=10.0, 최악=-2.0)]

    최악먼저 = 구간순위(구간="3개월", 줄들=줄들,
                  기준=ㅈ침.판단기준("worst_slice", "max_drawdown", "total_return"))
    수익먼저 = 구간순위(구간="3개월", 줄들=줄들,
                  기준=ㅈ침.판단기준("total_return", "max_drawdown", "worst_slice"))

    assert [ㄱ.키 for ㄱ in 최악먼저.차례] == ["덜잃은것", "많이번것"]
    assert [ㄱ.키 for ㄱ in 수익먼저.차례] == ["많이번것", "덜잃은것"]


