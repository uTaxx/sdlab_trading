"""보유 상한 길이의 구간으로 전략을 재는 계산을 본다.

## 여기서 꼭 잡아야 하는 것

**구간이 겹치는지가 값과 같이 다녀야 한다.** 겹치는 구간 1,380개를 서로
다른 시험 1,380번으로 읽으면 표본이 스무 배 많아 보인다. 그러면 우연히
좋았던 전략이 확실해 보인다.

**연환산은 상한이 다른 전략을 같은 줄에 놓기 위한 값이다.** 3일 상한은
1년에 여든 번 넘게 반복하는 것으로 계산되므로, 구간당 작은 차이가 크게
벌어진다. 계산이 틀리면 짧은 상한이 늘 이기는 것처럼 보인다.

**못 잰 것을 0으로 채우면 안 된다.** 구간이 없는 것과 수익률이 0인 것은
다른 말이다.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date, timedelta

import pandas as pd

from muwon.analysis import window_perf as ㅅ


def _곡선(값들: list[float], 시작: date = date(2026, 1, 5)) -> pd.DataFrame:
    """장이 열린 날만 늘어놓은 평가금액. 날짜 간격은 계산에 안 쓴다."""
    날들 = [시작 + timedelta(days=ㄱ) for ㄱ in range(len(값들))]
    return pd.DataFrame({"trade_date": 날들, "equity": 값들})


@dataclass
class _매매:
    pnl_pct: float
    exit_reason: str
    entry_date: date = date(2026, 1, 5)
    exit_date: date = date(2026, 1, 10)


# ── 구간 나누기 ────────────────────────────────────────────────


def test_겹치지_않게_나누면_길이만큼_건너뛴다():
    곡선 = _곡선([100, 101, 102, 103, 104, 105, 106])
    것들 = ㅅ.구간나누기(곡선, 3, 겹치게=False)
    assert len(것들) == 2
    assert 것들[0].시작일 == date(2026, 1, 5)
    assert 것들[1].시작일 == date(2026, 1, 8)


def test_겹치게_나누면_하루씩_민다():
    곡선 = _곡선([100, 101, 102, 103, 104, 105, 106])
    것들 = ㅅ.구간나누기(곡선, 3, 겹치게=True)
    assert len(것들) == 4
    assert [ㄱ.시작일.day for ㄱ in 것들] == [5, 6, 7, 8]


def test_구간_수익률은_첫날_대비_마지막날이다():
    것 = ㅅ.구간나누기(_곡선([100, 90, 110]), 2)[0]
    assert round(것.수익률, 6) == 10.0


def test_구간_안의_최대낙폭을_같이_잰다():
    """구간 수익률이 플러스여도 안에서 크게 빠졌을 수 있다."""
    것 = ㅅ.구간나누기(_곡선([100, 80, 110]), 2)[0]
    assert round(것.최대낙폭, 6) == -20.0


def test_자료가_모자라면_구간이_없다():
    """0으로 채우지 않는다. 아예 안 만든다."""
    assert ㅅ.구간나누기(_곡선([100, 101]), 5) == []
    assert ㅅ.구간나누기(None, 5) == []


# ── 구간 분포에서 값 뽑기 ──────────────────────────────────────


def test_기하평균은_산술평균과_다르다():
    """+50%와 -50%를 번갈아 하면 산술평균은 0이지만 실제로는 줄어든다.
    이 시스템은 번 돈을 다시 넣어 굴리므로 기하평균이 맞다."""
    구간들 = [ㅅ.구간(date(2026, 1, 5), date(2026, 1, 9), 50.0, 0.0),
            ㅅ.구간(date(2026, 1, 12), date(2026, 1, 16), -50.0, -50.0)]
    ㄱ = ㅅ.구간재기(구간들, 5)
    assert round(ㄱ.산술평균, 6) == 0.0
    assert ㄱ.기하평균 < 0
    assert round(ㄱ.기하평균, 4) == round((0.75 ** 0.5 - 1) * 100, 4)


def test_연환산은_상한이_짧을수록_크게_나온다():
    """같은 구간 수익률이면 짧은 상한이 1년에 더 여러 번 반복된다.
    이 성질을 모르고 표를 보면 짧은 상한이 늘 이기는 것처럼 읽힌다."""
    구간들 = [ㅅ.구간(date(2026, 1, 5), date(2026, 1, 9), 1.0, 0.0)] * 40
    짧은것 = ㅅ.구간재기(구간들, 3)
    긴것 = ㅅ.구간재기(구간들, 20)
    assert 짧은것.연환산 > 긴것.연환산
    # 3일 상한이면 1년에 252/3 = 84번이다.
    assert round(짧은것.연환산, 2) == round((1.01 ** 84 - 1) * 100, 2)


def test_계좌가_0이_되면_기하평균을_내지_않는다():
    """-100%가 섞이면 기하평균이 정의되지 않는다. 0으로 채우지 않는다."""
