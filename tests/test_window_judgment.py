"""보유 상한 시스템의 판단 지침 목록과 순위를 본다.

## 여기서 꼭 잡아야 하는 것

**1순위가 수익 쪽 값이어야 한다.** 앞선 기준(가장 나빴던 해 → 최대낙폭)은
손실만 보기 때문에, 5년 8개월 동안 한 번 사고 만 전략이 1위였다. 지키기만
하고 벌지 않는 쪽으로 순위가 기울면 안 된다.

**못 잰 값을 0으로 보면 안 된다.** 계산하지 못한 것을 0%로 두면 잃지도
벌지도 않은 전략과 같은 자리에 선다.

**작을수록 좋은 값은 부호를 뒤집어 둬야 한다.** 한 곳만 빠뜨려도 순위가
조용히 뒤집힌다.
"""

