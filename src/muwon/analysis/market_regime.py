"""날짜마다 그날 장이 상승인지 조정인지 하락인지 이름표를 붙인다.

## 무엇에 쓰나

**전략의 성적을 국면별로 나눠 보기 위해서다.** 5년 평균이 좋아도 하락장
구간에서만 크게 잃는 전략이면, 그 5년 평균은 실제로 받아 보기 어렵다.
지금이 조정 국면이면 과거의 조정 국면에서 어땠는지를 봐야 한다.

## 이것으로 매매를 켜고 끄지 않는다

이 저장소는 시장 지표로 매매를 켜고 끄는 규칙을 세 번 시험하고 세 번
기각했다. 설계안 §43(시장 지표로 매일 전략 갈아타기), §46(장이 나쁠 때
인버스), §47(나쁜 날 새로 안 사기)이다.

**여기서 하는 일은 그것과 다르다.** 지나간 구간에 이름을 붙여 성적을
나눠 보는 것이고, 매수·매도 판단에는 쓰지 않는다. 국면을 보고 오늘 살지
말지를 정하는 순간 §43·§46·§47이 기각한 것과 같은 규칙이 된다.

## 어떻게 가르나

증시 기사가 쓰는 기준을 그대로 쓴다.

| 국면 | 코스피가 고점 대비 |
|---|---|
| 상승 | 10% 미만 하락 |
| 조정 | 10% 이상 20% 미만 하락 |
| 하락 | 20% 이상 하락 |

고점은 **그날까지의 최근 250거래일 최고**다. 약 1년이다.

**되돌아 나오는 문턱은 3%p 위에 둔다.** 조정에서 상승으로 나오려면 −7%,
하락에서 조정으로 나오려면 −17%까지 올라와야 한다. 이것이 없으면 경계에서
국면이 하루 단위로 뒤집힌다. 실제 코스피로 확인했다.

**미래를 보지 않는다.** 그날까지의 자료만으로 정한다. 뒤를 보고 "여기가
바닥이었다"고 이름 붙이면 백테스트가 실제보다 좋게 나오고, 그 사실이
화면에 아무 표시도 안 남는다.

## 조심할 것

**바닥에서 올라오는 중에도 조정이라고 적힌다.** 30% 빠졌다가 12%까지
회복한 날은 오르는 중인데도 조정이다. 고점 대비로만 가르기 때문이다.
250거래일이 지나면 고점 자체가 내려와서 상승으로 바뀐다.

**국면마다 표본이 크게 다르다.** 하락 국면은 5년에 몇 달뿐이라 20영업일
구간이 몇 개 안 나온다. 구간 수를 반드시 같이 봐야 한다.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date

import pandas as pd

상승, 조정, 하락 = "상승", "조정", "하락"
전체 = "전체"

#: 화면과 저장에서 쓰는 이름. 순서도 이대로 보여 준다.
국면들: tuple[str, ...] = (상승, 조정, 하락)

#: 고점 대비 몇 %부터 조정이고 하락인가. 증시 기사의 기준을 그대로 쓴다.
조정문턱 = -10.0
하락문턱 = -20.0

#: 되돌아 나오는 문턱. 들어갈 때보다 3%p 위다.
#:
#: **이것이 없으면 경계에서 국면이 하루 단위로 뒤집힌다.** 실제 코스피로
#: 확인했다. 2021년 10월부터 12월까지 고점 대비가 −10% 언저리를 오가면서
#: 상승과 조정이 열 번 넘게 갈렸고, 1거래일짜리 구간이 여럿 나왔다.
#: 그렇게 나뉜 구간으로 성적을 모으면 국면별 표본이 뜻 없이 잘게 쪼개진다.
조정탈출 = -7.0
하락탈출 = -17.0

#: 고점을 어디까지 거슬러 보나(거래일). 약 1년이다.
#: `market/state.py`의 PEAK_WINDOW와 같은 값이다.
고점창 = 250

#: 이만큼은 쌓여야 고점을 말할 수 있다. 그전 날은 이름표를 안 붙인다.
#: **모르는 것을 상승으로 채우지 않는다.** 자료가 없어서 모르는 것과
#: 실제로 오르는 장은 다르다.
최소자료 = 고점창 // 2


def 고점대비(종가: pd.Series, 창: int = 고점창) -> pd.Series:
    """그날까지의 최근 고점 대비 몇 %인가. 늘 0 이하다."""
    고점 = 종가.rolling(창, min_periods=최소자료).max()
    return (종가 / 고점 - 1) * 100


def 이름표(값: float | None, 앞국면: str | None = None) -> str | None:
    """고점 대비 값 하나를 국면 이름으로. 모르면 None이다.

    앞 국면을 주면 되돌림 여유를 둔다. 조정에서 상승으로 나오려면 −7%보다
    위로, 하락에서 조정으로 나오려면 −17%보다 위로 올라와야 한다.
    **경계에서 하루 단위로 뒤집히는 것을 막는다.**"""
    if 값 is None or pd.isna(값):
        return None
    값 = float(값)

    if 앞국면 == 하락:
        return 하락 if 값 < 하락탈출 else (조정 if 값 <= 조정문턱 else 상승)
    if 앞국면 == 조정:
        if 값 <= 하락문턱:
            return 하락
        return 조정 if 값 < 조정탈출 else 상승

    # 처음 판정하거나 앞이 상승일 때는 들어가는 문턱을 그대로 쓴다.
    if 값 <= 하락문턱:
        return 하락
    if 값 <= 조정문턱:
        return 조정
    return 상승


def _날짜들(시세: pd.DataFrame) -> pd.Index:
    """일봉 표에서 날짜를 꺼낸다.

    이 저장소는 두 모양을 다 쓴다. 야후에서 받은 것은 `trade_date` 칸을
    두고 인덱스가 번호이고, 백테스트가 내는 자산 곡선은 인덱스가 날짜다.
    한쪽만 받으면 다른 쪽에서 날짜가 번호로 나와 국면이 통째로 어긋난다."""
    if "trade_date" in 시세.columns:
        return pd.to_datetime(시세["trade_date"])
    return pd.to_datetime(시세.index)


def 국면나누기(시세: pd.DataFrame) -> pd.Series:
    """일봉 표를 받아 날짜마다 국면 이름을 붙인다. 열쇠는 날짜다.

    자료가 모자란 앞부분은 None으로 둔다. 그 구간은 국면별 집계에서 빠진다."""
    if 시세 is None or not len(시세):
        return pd.Series(dtype="object")
    종가 = pd.Series(시세["close"].astype(float).to_numpy(), index=_날짜들(시세))

    # 되돌림 여유가 앞 국면을 보므로 한 줄씩 훑는다. map으로는 못 한다.
    앞 = None
    나온것 = []
    for 값 in 고점대비(종가):
        앞 = 이름표(값, 앞)
        나온것.append(앞)
    return pd.Series(나온것, index=종가.index, dtype="object")


@dataclass(frozen=True)
class 국면구간:
    """한 국면이 이어진 기간 하나. 화면에 언제가 어떤 장이었는지 보여 준다."""

    국면: str
    시작일: date
    끝일: date
    #: 시작일과 끝일을 둘 다 센다. 하루짜리 구간이 0일이 되면 안 된다.
    거래일수: int = 0


def 구간묶기(이름표들: pd.Series) -> list[국면구간]:
    """날짜별 이름표를 이어진 구간으로 묶는다.

    "2022년 6월부터 10월까지 하락"처럼 사람이 읽을 수 있는 모양으로 만든다.
    이름표가 없는 날은 구간을 끊는다."""
    나온것: list[국면구간] = []
    지금국면 = None
    시작 = 끝 = None
    센것 = 0

    for 날, 값 in 이름표들.items():
        날짜 = 날.date() if hasattr(날, "date") else 날
        if 값 is None or (isinstance(값, float) and pd.isna(값)):
            값 = None
        if 값 != 지금국면:
            if 지금국면 is not None:
                나온것.append(국면구간(지금국면, 시작, 끝, 센것))
            지금국면, 시작, 센것 = 값, 날짜, 0
        끝 = 날짜
        센것 += 1

    if 지금국면 is not None:
        나온것.append(국면구간(지금국면, 시작, 끝, 센것))
    return 나온것


def 지금국면(시세: pd.DataFrame) -> tuple[str | None, float | None]:
    """마지막 날의 국면과 고점 대비 값. 화면 맨 위에 적는다.

    **모르면 None을 돌려준다.** 자료가 모자란 것을 상승으로 채우면 화면이
    아는 척을 하게 된다."""
    if 시세 is None or not len(시세):
        return None, None
    이름들 = 국면나누기(시세)
    값들 = 고점대비(시세["close"].astype(float).reset_index(drop=True))
    if not len(이름들) or 이름들.iloc[-1] is None:
        return None, None
    마지막값 = 값들.iloc[-1]
    return 이름들.iloc[-1], (None if pd.isna(마지막값) else float(마지막값))


def 국면글(국면: str | None, 고점대비값: float | None) -> str:
    """사람에게 보여 줄 한 줄. 판단을 말하지 않고 사실만 적는다."""
    if 국면 is None:
        return "시장 국면을 판정할 자료가 모자랍니다."
    설명 = {
        상승: "코스피가 최근 1년 고점 대비 10% 미만으로 하락한 상태입니다.",
        조정: "코스피가 최근 1년 고점 대비 10% 이상 20% 미만으로 하락한 상태입니다.",
        하락: "코스피가 최근 1년 고점 대비 20% 이상 하락한 상태입니다.",
    }[국면]
    값글 = "" if 고점대비값 is None else f" 고점 대비 {고점대비값:+.1f}%입니다."
    return f"지금은 {국면} 국면입니다. {설명}{값글}"
