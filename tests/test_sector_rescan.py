def test_반영할행이_바뀐_종목만_고친다():
    """재평가 안 한 섹터·안 바뀐 종목은 시트에 있던 값 그대로 남는다."""
    내용 = _시트()
    sector = 내용.섹터[0]
    거래대금표 = {
        "005930": 1000.0, "000660": 900.0, "036930": 300.0,
        "240810": 400.0, "039030": 260.0, "108320": 70.0,
    }
    재평가들 = [다시고르기(sector, 거래대금표, 섹터당=3, 문턱=250.0)]
    _, 종목행 = 반영할행(내용, 재평가들, 섹터당=3, 문턱=250.0)

    표 = {줄[0]: 줄 for 줄 in 종목행[1:]}
    # 편입: 240810이 새로 활성이 되고 메모가 바뀐다.
    assert 표["240810"][4] == "Y"
    assert "400억" in 표["240810"][5]
    # 제외: 036930이 밀려나고 메모에 이유가 남는다.
    assert 표["036930"][4] == "N"
    assert "상한" in 표["036930"][5]
    # 안 바뀐 것: 이미 활성이던 삼성전자는 메모가 그대로다.
    assert 표["005930"][4] == "Y" and 표["005930"][5] == ""
    # 여전히 비활성인 것: 메모가 그대로 남는다.
    assert 표["039030"][4] == "N" and 표["039030"][5] == "기존에 밀림"
    assert 표["108320"][4] == "N"


def test_반영할행은_거래대금을_못_받은_섹터도_그대로_옮긴다():
    """재평가 대상이 아예 아닌 섹터(예: 이번에 못 잰 섹터)가 있어도
    죽지 않고 시트에 있던 값을 그대로 옮겨야 한다."""
    내용 = _시트()
    _, 종목행 = 반영할행(내용, [], 섹터당=5, 문턱=250.0)
    표 = {줄[0]: 줄 for 줄 in 종목행[1:]}
    assert 표["005930"][4] == "Y"
    assert 표["240810"][5] == "기존에 밀림"
