def test_기간_만료가_절반을_넘으면_이_상한에_안_맞는다고_본다():
    """자동으로 빼지는 않는다. 표시만 하고 판단은 사람이 한다."""
    def _만들기(만료수: int, 전체: int) -> ㅅ.잰것:
        매매들 = ([_매매(1.0, "보유 상한 5거래일에 닿아 청산")] * 만료수
                + [_매매(1.0, "손절")] * (전체 - 만료수))
        return ㅅ.잰것(
            전략="t", 상한=5, 슬리피지=0.1, 매매대상="실거래",
            시작일=date(2021, 1, 4), 끝일=date(2026, 9, 2), 잰날=date(2026, 9, 3),
            구간=ㅅ.구간재기([], 5), 겹친구간=None, 매매=ㅅ.매매재기(매매들),
        )
    assert _만들기(7, 10).이_상한에_맞나 is False
    assert _만들기(3, 10).이_상한에_맞나 is True
    assert _만들기(0, 0).이_상한에_맞나 is None


