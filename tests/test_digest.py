"""텔레그램 요약 검증.

**안 읽는 알림은 없는 것과 같고, 오히려 진짜 중요한 알림을 묻는다.**
그래서 짧아야 하고, 짧게 줄이는 과정에서 경고가 빠지면 안 된다.

## 2026-08-25에 다시 쓴 이유

받아 보는 사람이 **한 줄도 이해할 수 없다**고 했다. 다시 읽어 보니 맞았다.
"그냥 찍었을 때", "우연폭", "전망 못 냄", "렌즈 확장" — 전부 이 저장소
안에서만 통하는 말이었다.

그래서 이 파일이 지키는 것이 늘었다. 짧은 것만으로는 모자란다 —
**읽고 무슨 말인지 알 수 있어야** 한다.
"""

from datetime import date

import pandas as pd

from muwon.market.analog import Baseline, Forecast
from muwon.market.digest import MAX_LEN, state_line, summarize


def _상태(추세=1.0, 낙폭=-2.0, 변동성=0.5):
    return pd.DataFrame(
        {"kospi_추세20": [추세], "kospi_고점대비": [낙폭], "kospi_변동성": [변동성]},
        index=[date(2026, 8, 19)],
    )


def _전망(대상="반도체", 상승확률=70.0, 기준선=55.0, 구간수=16, 낼수있나=True):
    return Forecast(
        기준일=date(2026, 8, 19), 대상=대상, 구간수=구간수, 총일수=200, 지평=20,
        중앙값=2.0 if 낼수있나 else None,
        상위25=6.0 if 낼수있나 else None,
        하위25=-1.0 if 낼수있나 else None,
        하위10=-8.0 if 낼수있나 else None,
        상승확률=상승확률 if 낼수있나 else None,
        구간들=[],
        사유="" if 낼수있나 else "비슷했던 때가 3번뿐입니다",
        기준선=Baseline(표본수=1000, 중앙값=1.0, 하위10=-9.0, 상승확률=기준선),
    )


# ── 장 상태 ──────────────────────────────────────────────────────────────


def test_z점수를_숫자로_내보내지_않는다():
    """이게 이 파일에서 제일 중요한 시험이다.

    예전에는 `고점대비 -2.8`처럼 z점수를 그대로 찍었다. z점수는 '평소에
    견줘 얼마나 벗어났나'이지 퍼센트가 아닌데, 단위를 안 적으니 받아 보는
    사람이 '고점에서 2.8% 빠졌다'로 읽었다. 실제로 그렇게 읽혔다."""
    글 = state_line(_상태(추세=0.8, 낙폭=-2.8, 변동성=1.3))

    assert "-2.8" not in 글 and "+0.8" not in 글 and "1.3" not in 글
    assert "깊이 빠져 있습니다" in 글, "숫자 대신 뜻이 있어야 한다"


def test_방향을_말로_적는다():
    올라감 = state_line(_상태(추세=2.0))
    내려감 = state_line(_상태(추세=-2.0))

    assert "오르는 중입니다" in 올라감
    assert "내리는 중입니다" in 내려감


def test_평소면_평소라고_한다():
    """0 근처를 '조금 오르는 중'으로 적으면 없는 신호를 만들어 낸다."""
    글 = state_line(_상태(추세=0.1, 낙폭=0.1, 변동성=0.1))

    assert "방향이 없습니다" in 글
    assert "평소만큼" in 글


def test_많이_출렁이는_날은_그게_무슨_뜻인지까지_적는다():
    """'변동성 +1.3'만 보고 무엇을 판단할지 알 수 있는 사람은 없다."""
    글 = state_line(_상태(변동성=1.6))

    assert "손절선에 잘 걸리는 장입니다" in 글


def test_잴_수_없으면_그렇게_말한다():
    assert "잴 수 없습니다" in state_line(pd.DataFrame())


# ── 요약 전체 ────────────────────────────────────────────────────────────


def test_기각됐다는_말이_요약에서_살아남는다():
    """이 전망은 이미 되돌려 검증에서 떨어졌다. 그 말이 빠지면 매일
    그럴듯한 숫자만 보게 되고, 그러다 어느 날 그걸 근거로 삼게 된다."""
    글 = summarize(_상태(), [_전망()], date(2026, 8, 19))

    assert "매매에 쓰지 마세요" in 글
    assert "51.8%" in 글 and "56.3%" in 글, "왜 못 믿는지 숫자로 보여야 한다"
    assert "주문은 한 건도 내지 않았습니다" in 글


def test_경고가_숫자보다_먼저_나온다():
    """맨 아래 있으면 위쪽 숫자를 먼저 믿는다."""
    글 = summarize(_상태(), [_전망()], date(2026, 8, 19))

    assert 글.index("매매에 쓰지 마세요") < 글.index("섹터별 기록")


def test_텔레그램에_안_먹는_기호를_안_쓴다():
    """send_message에 parse_mode를 안 주고 있어서 `**기각**`이 그대로
    별 네 개로 도착한다. 강조가 필요하면 말로 쓴다."""
    글 = summarize(_상태(), [_전망()], date(2026, 8, 19))

    assert "**" not in 글
    assert "★" not in 글, "별표는 무슨 뜻인지 아무도 모른다"


def test_숫자마다_무슨_뜻인지가_같은_줄에_있다():
    글 = summarize(_상태(), [_전망(상승확률=70.0, 기준선=55.0)], date(2026, 8, 19))
    (줄,) = [ㄹ for ㄹ in 글.splitlines() if ㄹ.startswith("  · 반도체")]

    assert "70%" in 줄 and "평소 55%" in 줄 and "+15%p" in 줄


def test_우연_범위_안이면_그렇게_적는다():
    """예전에는 별표를 안 붙이는 것으로만 표시했다. 별이 없는 것을
    '평범하다'로 읽을 수는 있어도 '차이가 없다'로 읽을 수는 없다."""
    # 구간 16개면 우연 폭이 ±24.5%p. +5%p는 한참 안쪽이다.
    안쪽 = summarize(_상태(), [_전망(상승확률=60.0, 기준선=55.0)], date(2026, 8, 19))
    바깥 = summarize(
        _상태(), [_전망(상승확률=60.0, 기준선=55.0, 구간수=400)], date(2026, 8, 19)
    )

    assert "우연 범위 안" in 안쪽
    assert "우연보다 큼" in 바깥


def test_차이가_0이면_0퍼센트가_아니라_차이_없음이라고_쓴다():
    글 = summarize(_상태(), [_전망(상승확률=62.0, 기준선=62.0)], date(2026, 8, 19))

    assert "차이 없음" in 글
    assert "+0%p" not in 글


def test_보는_법이_같이_온다():
    """용어를 아는 사람만 읽을 수 있는 글이면 안 읽는 글과 같다."""
    글 = summarize(_상태(), [_전망()], date(2026, 8, 19))

    assert "보는 법" in 글
    assert "아무 날에나 그냥 샀어도" in 글, "'평소'가 무엇인지 풀어 줘야 한다"
    assert "동전을 그만큼 던져도" in 글, "'우연 범위'가 무엇인지 풀어 줘야 한다"


def test_숫자를_못_낸_이유를_말한다():
    """'없음'만 보이면 고장인지 표본이 모자란 건지 알 수 없다."""
    글 = summarize(_상태(), [_전망("로봇", 낼수있나=False)], date(2026, 8, 19))

    assert "3번뿐" in 글
    assert "확률이 아니라" in 글, "왜 비우는지까지 있어야 납득이 된다"


def test_렌즈_이름_대신_무엇을_봤는지_적는다():
    """'렌즈 확장'은 이 저장소 안에서만 통하는 말이다."""
    글 = summarize(_상태(), [_전망()], date(2026, 8, 19), 렌즈="확장")

    assert "렌즈" not in 글
    assert "코스피" in 글 and "2004년부터" in 글


def test_모르는_렌즈여도_안_터진다():
    글 = summarize(_상태(), [_전망()], date(2026, 8, 19), 렌즈="없는것")

    assert "없는것" in 글


def test_긴_글은_한_통으로_줄인다():
    """텔레그램 한 통을 넘기면 잘려서 도착한다."""
    많은것 = [_전망(f"섹터{i}") for i in range(200)]
    글 = summarize(_상태(), 많은것, date(2026, 8, 19))

    assert len(글) <= MAX_LEN
    assert "줄임" in 글


def test_못_낸_것이_많으면_몇_개_더_있는지_알려준다():
    """다섯 개만 보여 주고 나머지를 조용히 버리면 목록이 짧아 보인다."""
    글 = summarize(
        _상태(), [_전망(f"섹터{i}", 낼수있나=False) for i in range(9)], date(2026, 8, 19)
    )

    assert "그 밖에 4개" in 글


def test_머리글이_사람이_읽는_날짜다():
    """'2026-08-19'보다 '8월 19일(수)'가 폰에서 빨리 읽힌다."""
    머리 = summarize(_상태(), [_전망()], date(2026, 8, 19)).splitlines()[0]

    assert "8월 19일(수)" in 머리
