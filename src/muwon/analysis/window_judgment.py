최소매매수 = 20


def 걸린것(잰것) -> list[str]:
    """확인 지침 중 이 측정 하나로 판정할 수 있는 것을 보고, 걸린 것의
    이름을 돌려준다.

    **여섯 중 셋만 여기서 판정한다.** 구간 수, 매매 수, 이 상한에 맞는지
    셋이다. 나머지 셋은 측정 하나만 봐서는 답할 수 없다. 슬리피지를 넣어도
    남는지는 슬리피지가 다른 두 측정을 견줘야 하고, 실거래 종목에서도 같은지는
    매매 대상이 다른 두 측정이 있어야 하며, 파는 길이 있는지는 전략 정의를
    봐야 한다.

    **없는 것을 조용히 통과시키지 않는다.** 판정하지 않은 셋은 여기서 아예
    다루지 않고, 화면이 그 셋을 따로 계산해 보여 준다. 여기서 빈 목록을
    돌려주는 것은 "판정한 셋을 다 넘겼다"는 뜻이지 "여섯을 다 넘겼다"가
    아니다."""
    나온것: list[str] = []

    구간 = getattr(잰것, "구간", None)
    if 구간 is None or 구간.구간수 < 최소구간수:
        나온것.append("구간 수 부족")

    매매 = getattr(잰것, "매매", None)
    if 매매 is None or 매매.매매수 < 최소매매수:
        나온것.append("매매 수 부족")

    맞나 = getattr(잰것, "이_상한에_맞나", None)
    if 맞나 is False:
        나온것.append("이 상한에 안 맞음")

    return 나온것


def 시트에서(시트설정, 바탕: 기준 | None = None) -> 기준:
    """시트 `설정` 탭의 세 칸을 읽어 기준으로 만든다.

    시트를 못 읽었거나 값이 성하지 않으면 기본값으로 돌아간다. 순위를 아예
    못 내면 검토가 통째로 멈추는데, 그것이 지침 하나가 옛 값인 것보다 나쁘다."""
    바탕값 = 바탕 or 기본기준
    if 시트설정 is None:
        return 바탕값
    try:
        고른것 = replace(
            바탕값,
            일순위=str(시트설정.가져오기("rank_1st") or 바탕값.일순위),
            이순위=str(시트설정.가져오기("rank_2nd") or 바탕값.이순위),
            삼순위=str(시트설정.가져오기("rank_3rd") or 바탕값.삼순위),
        )
    except (AttributeError, KeyError):
        return 바탕값
    return 고른것 if 고른것.성한가 else 바탕값
