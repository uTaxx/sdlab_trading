"""매매 대상 종목 트렌드 계산.

## 왜 여기까지 시험하나

이 숫자는 매일 텔레그램과 화면에 나간다. 틀려도 아무것도 안 빨개진다.
주문이 안 나가는 계산이라 실패가 조용하다.

특히 조심할 것이 둘이다. 시세가 모자란 종목을 0으로 채우면 비율이 실제보다
낮게 나온다. 그리고 평균을 쓰면 크게 오른 한 종목이 유니버스 요약을 통째로
만든다.
"""

from __future__ import annotations

from datetime import date, timedelta

import pandas as pd

from muwon.analysis.trend import (
    MIN_SYMBOLS,
    구간재기,
    트렌드글,
    트렌드재기,
)


def _시세(값들: list[float], 시작: date = date(2026, 1, 1)) -> pd.DataFrame:
    """종가만 다른 일봉. 거래일은 하루씩 늘린다."""
    날들 = [시작 + timedelta(days=ㄱ) for ㄱ in range(len(값들))]
    return pd.DataFrame(
        {
            "trade_date": 날들,
            "open": 값들,
            "high": 값들,
            "low": 값들,
            "close": 값들,
            "volume": [1000] * len(값들),
        }
    )


def _유니버스(끝값들: dict[str, float], 길이: int = 30) -> dict[str, pd.DataFrame]:
    """100에서 시작해 끝값까지 곧게 가는 종목들."""
    나온것 = {}
    for 심볼, 끝 in 끝값들.items():
        걸음 = (끝 - 100.0) / (길이 - 1)
        나온것[심볼] = _시세([100.0 + 걸음 * ㄱ for ㄱ in range(길이)])
    return 나온것


def test_등락률은_구간_첫_종가와_마지막_종가로_잰다():
    ㅎ = {"A": _시세([100.0, 110.0, 120.0])}
    ㅌ = 구간재기(ㅎ, date(2026, 1, 1), date(2026, 1, 3), "3일")
    assert ㅌ.종목수 == 1
    assert ㅌ.종목들[0].등락 == 20.0


def test_봉이_하나뿐이면_그_종목은_못잰것으로_간다():
    """0%로 채우면 '안 움직였다'로 읽힌다. 실제로는 못 잰 것이다."""
    ㅎ = {"A": _시세([100.0])}
    ㅌ = 구간재기(ㅎ, date(2026, 1, 1), date(2026, 1, 1), "하루")
    assert ㅌ.종목수 == 0
    assert ㅌ.못잰것 == ["A"]


def test_요약은_평균이_아니라_중앙값이다():
    """한 종목이 크게 오르면 평균은 그 종목 이야기가 된다."""
    ㅎ = _유니버스({"A": 101.0, "B": 102.0, "C": 103.0, "D": 104.0, "E": 300.0})
    ㅌ = 구간재기(ㅎ, date(2026, 1, 1), date(2026, 1, 30), "한달")
    assert ㅌ.종목수 == 5
    # 평균이면 40% 언저리다. 중앙값은 3%다.
    assert 2.0 < ㅌ.중앙값등락 < 4.0


def test_종목이_모자라면_요약을_안_낸다():
    """몇 종목의 이야기를 유니버스 요약이라고 부르면 안 된다."""
    ㅎ = _유니버스({"A": 110.0, "B": 120.0})
    ㅌ = 구간재기(ㅎ, date(2026, 1, 1), date(2026, 1, 30), "한달")
    assert ㅌ.종목수 < MIN_SYMBOLS
    assert ㅌ.오른비율 is None
    assert ㅌ.중앙값등락 is None
    assert not ㅌ.믿을만한가


def test_오른비율은_오른_종목수를_센_것이다():
    ㅎ = _유니버스({"A": 110.0, "B": 120.0, "C": 90.0, "D": 80.0, "E": 130.0})
    ㅌ = 구간재기(ㅎ, date(2026, 1, 1), date(2026, 1, 30), "한달")
    assert ㅌ.오른수 == 3
    assert ㅌ.오른비율 == 60.0


def test_이동평균이_안_만들어진_종목은_비율에서_뺀다():
    """0으로 채우면 상장 초기 종목이 전부 '선 아래'로 잡혀 비율이 낮아진다."""
    긴것 = _유니버스({f"L{ㄱ}": 130.0 for ㄱ in range(5)}, 길이=30)
    짧은것 = {"S": _시세([100.0, 101.0, 102.0])}
    ㅌ = 구간재기({**긴것, **짧은것}, date(2026, 1, 1), date(2026, 1, 30), "한달")
    # 오르는 다섯은 전부 선 위다. 짧은 하나는 아예 안 센다.
    assert ㅌ.이평위비율 == 100.0


def test_트렌드재기는_구간마다_따로_낸다():
    ㅎ = _유니버스({f"S{ㄱ}": 120.0 for ㄱ in range(6)}, 길이=30)
    나온것 = 트렌드재기(
        ㅎ,
        {
            "1주": (date(2026, 1, 24), date(2026, 1, 30)),
            "1개월": (date(2026, 1, 1), date(2026, 1, 30)),
        },
    )
    assert set(나온것) == {"1주", "1개월"}
    # 곧게 오르는 구간이라 한 달이 한 주보다 많이 오른다.
    assert 나온것["1개월"].중앙값등락 > 나온것["1주"].중앙값등락


def test_트렌드글은_판단하는_말을_안_쓴다():
    """오른 종목이 많다고 사기 좋은 때라고 적으면 투자 판단이 된다."""
    ㅎ = _유니버스({f"S{ㄱ}": 130.0 for ㄱ in range(8)}, 길이=30)
    글 = 트렌드글(구간재기(ㅎ, date(2026, 1, 1), date(2026, 1, 30), "1개월"))
    for 안쓸말 in ("좋은", "안전", "추천", "사기 좋", "유리", "기회"):
        assert 안쓸말 not in 글, f"{안쓸말!r}: {글}"
    assert "중앙값" in 글
    assert "—" not in 글, "사람에게 가는 문장에는 줄표를 안 씁니다"


def test_트렌드글은_표본이_모자라면_그렇게_적는다():
    ㅎ = _유니버스({"A": 110.0, "B": 120.0})
    글 = 트렌드글(구간재기(ㅎ, date(2026, 1, 1), date(2026, 1, 30), "1개월"))
    assert "요약하지 않습니다" in 글


def test_못잰_종목이_있으면_글에_적는다():
    """빼고 계산한 숫자를 전체 숫자처럼 읽으면 안 된다."""
    긴것 = _유니버스({f"L{ㄱ}": 120.0 for ㄱ in range(6)}, 길이=30)
    ㅌ = 구간재기(
        {**긴것, "S": _시세([100.0])}, date(2026, 1, 1), date(2026, 1, 30), "1개월"
    )
    assert "1종목은 제외했습니다" in 트렌드글(ㅌ)
