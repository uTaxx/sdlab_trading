      + "계산합니다.\n\n등록된 전략 전체를 계산하므로 5분에서 한 시간까지 "
      + "걸립니다. 주문은 발생하지 않습니다.\n\n시작할까요?";
    if (!window.confirm(물음)) return;

    const 단추 = $("찾기실행");
    단추.disabled = true;
    단추.textContent = "시작하는 중...";
