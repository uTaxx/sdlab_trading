"""리포트 전문을 텔레그램에 보낼 짧은 요약으로 줄인다.

## 왜 줄이나

시장·섹터 리포트 전문은 200줄이 넘는다. 그걸 매일 텔레그램으로 보내면
아무도 안 읽는다. 안 읽는 알림은 없는 것과 같고, 오히려 진짜 중요한
알림이 묻힌다.

## 2026-08-26에 또 다시 쓴 이유

8월 25일에 "한 줄도 이해할 수 없다"는 말을 듣고 모든 용어를 풀어 쓰는
쪽으로 고쳤는데, 그게 반대 방향으로 망가졌다. 받아 보는 사람이 다시
"단어도 문장도 하나도 이해가 안 된다"고 했다.

무엇이 잘못됐는지 세 가지로 정리된다.

1. 용어를 없앤 자리에 없는 말을 지어냈다. "우연폭 ±24%p"는 뜻이 정해진
   말이라 한 번 배우면 계속 쓴다. 그걸 "우연 범위 안"으로 바꾸니 이
   저장소 밖에서는 통하지 않는 말이 됐다. "평소", "차이", "이런 자리",
   "비슷했던 과거"도 전부 같은 경우다.
2. 설명서를 알림 안에 넣었다. "보는 법" 여섯 줄이 매일 왔다. 매일 오는
   알림에 사용법이 붙어 있으면 그건 알림이 아니라 설명서다.
3. CLAUDE.md에 넣은 문체 규칙("한 문장에 한 가지만", "비유 금지")을
   지키다 보니 "이런 자리는 몇 해에 한 번 볼까 말까 합니다" 같은 문장이
   나왔다. 뜻도 없고 무엇을 하라는 것도 없다. 그 규칙은 지웠다.

## 지금 이 파일이 지키는 것

- 숫자 옆에는 항상 견줄 값을 둔다. "20일 평균 6,650보다 2.4% 위".
- 표본이 몇 개인지 밝힌다. "16번 중 15번". 이게 있으면 판정을 안 믿어도
  스스로 판단할 수 있고, 없으면 판정을 그냥 믿는 수밖에 없다.
- 기각된 실험은 짧게 적는다. 안 믿기로 한 숫자가 메시지의 3분의 2를
  차지하면 경고를 아무리 위에 둬도 숫자가 이긴다.
"""

from __future__ import annotations

import math

#: 텔레그램 한 통의 안전한 길이.
MAX_LEN = 3500

_요일 = ("월", "화", "수", "목", "금", "토", "일")

#: 앞으로 며칠을 보는가. analog.HORIZON과 같아야 한다.
_지평_거래일 = 20


def _날짜글(기준일) -> str:
    try:
        return f"{기준일.month}월 {기준일.day}일({_요일[기준일.weekday()]})"
    except AttributeError:
        return str(기준일)


def state_line(state, 원시=None, 지수=None) -> str:
    """오늘 장 상태를 세 줄로.

    z점수는 화면에 안 낸다. "평소에 견줘 얼마나 벗어났나"라는 뜻이지
    퍼센트가 아닌데, `-2.8`을 그대로 찍었더니 "고점에서 2.8% 빠졌다"로
    읽혔다. 대신 원래 값과 견줄 값을 나란히 적는다. 어느 쪽도 없으면
    그 줄을 쓰지 않는다. 지어내는 것보다 비는 편이 낫다."""
    if len(state) == 0:
        return "  아직 잴 수 없습니다. 견줄 과거가 3년치는 쌓여야 합니다."

    날짜 = state.index[-1]
    원시오늘 = None
    if 원시 is not None and len(원시):
        같은날 = 원시.loc[:날짜]
        if len(같은날):
            원시오늘 = 같은날.iloc[-1]

    def _raw(이름: str):
        if 원시오늘 is None or 이름 not in 원시오늘.index:
            return None
        값 = float(원시오늘[이름])
        return None if math.isnan(값) else 값

    def _평소(이름: str):
        try:
            from muwon.market.state import 평소값
        except ImportError:  # pragma: no cover
            return None
        return 평소값(원시, 이름, 날짜)

    줄 = []
    지금값 = None
    if 지수 is not None and len(지수):
        쓸것 = 지수.loc[:날짜]
        if len(쓸것):
            지금값 = float(쓸것.iloc[-1])
            어제 = float(쓸것.iloc[-2]) if len(쓸것) >= 2 else 0.0
            어제대비 = f" (어제보다 {지금값 / 어제 - 1:+.1%})" if 어제 > 0 else ""
            줄 += [f"  {지금값:,.0f}{어제대비}", ""]

    if (추세 := _raw("kospi_추세20")) is not None:
        평균 = 지금값 / (1 + 추세) if 지금값 and 추세 != -1 else None
        기준 = f"20일 평균 {평균:,.0f}보다" if 평균 else "20일 평균보다"
        줄.append(f"  {기준} {abs(추세):.1%} {'위' if 추세 >= 0 else '아래'}입니다.")

    if (낙폭 := _raw("kospi_고점대비")) is not None:
        고점 = 지금값 / (1 + 낙폭) if 지금값 and 낙폭 != -1 else None
        기준 = f"1년 최고 {고점:,.0f}보다" if 고점 else "1년 최고보다"
        줄.append(f"  {기준} {abs(낙폭):.1%} 아래입니다.")

    if (변동 := _raw("kospi_변동성")) is not None:
        평소 = _평소("kospi_변동성")
        if 평소:
            큰가 = 변동 > 평소
            뒷말 = (
                " 크게 움직이는 장이라 손절선에 걸리기 쉽습니다."
                if 큰가 and 변동 >= 평소 * 1.5
                else ""
            )
            줄.append(
                f"  하루 등락은 평균 {변동:.1%}로, 평소 {평소:.1%}보다 "
                f"{'큽니다' if 큰가 else '작습니다'}.{뒷말}"
            )
        else:
            줄.append(f"  하루 등락은 평균 {변동:.1%}입니다.")

    return "\n".join(줄) if 줄 else "  지표를 못 읽었습니다."


def _은는(말: str) -> str:
    """받침이 있으면 '은', 없으면 '는'. "바이오은"이 나가고 있었다."""
    끝 = 말.strip()[-1] if 말.strip() else ""
    if not ("가" <= 끝 <= "힣"):
        return "는"  # 숫자·영문·기호로 끝나면 안전한 쪽으로
    return "은" if (ord(끝) - 0xAC00) % 28 else "는"


def _섹터줄(f) -> str:
    """섹터 한 줄. 몇 번 중 몇 번이었는지가 비율보다 중요하다.

    "바이오 94%"만 보면 대단해 보이지만 "16번 중 15번"을 같이 보면
    표본이 열여섯 개뿐이라는 것이 바로 보인다."""
    if f.기준선 is None or f.상승확률 is None:
        return f"  {f.대상}: {f.상승확률:.0f}%" if f.상승확률 else f"  {f.대상}"
    오른횟수 = round(f.상승확률 * f.구간수 / 100)
    return (
        f"  {f.대상}{_은는(f.대상)} {f.구간수}번 중 {오른횟수}번"
        f"({f.상승확률:.0f}%) 올랐습니다. "
        f"아무 날에나 샀다면 {f.기준선.상승확률:.0f}%입니다."
    )


def summarize(state, forecasts, 기준일, 렌즈: str = "", 지평: int = _지평_거래일,
              원시=None, 지수=None) -> str:
    """텔레그램 한 통짜리 요약."""
    낸것 = [f for f in forecasts if f.낼수있나]
    눈에띈것 = [f for f in 낸것 if f.우연을_넘었나]
    묻힌것 = [f for f in 낸것 if not f.우연을_넘었나]
    못낸것 = [f for f in forecasts if not f.낼수있나]

    줄 = [
        f"📊 {_날짜글(기준일)} 코스피 마감",
        "",
        state_line(state, 원시, 지수),
        "",
        "주문은 한 건도 내지 않았습니다.",
    ]

    if 낸것:
        줄 += [
            "",
            "─────────────",
            "아래는 실험 기록입니다. 매매에는 쓰지 않습니다.",
            "",
            f"지금과 비슷했던 과거를 찾아, 그 뒤 {지평}거래일 동안 값이 올랐던",
            "비율을 센 것입니다. 이 방식은 과거로 되돌려 검증했을 때 적중률이",
            "51.8%로, 아무 날에나 샀을 때의 56.3%보다 낮아 기각했습니다.",
            "지금은 '그때 뭐라고 했었나'를 되짚기 위해서만 남깁니다.",
            "",
        ]
        if 눈에띈것:
            줄 += [_섹터줄(f) for f in 눈에띈것]
        else:
            줄.append("  이번에는 눈에 띄게 벌어진 섹터가 없습니다.")
        if 묻힌것:
            줄 += [
                "",
                (f"  나머지 {len(묻힌것)}개 섹터는 비슷했던 과거가 적어서, 동전을 "
                 "그만큼 던져도 이 정도는 벌어집니다. 그래서 적지 않았습니다."),
            ]

    if 못낸것:
        줄 += [
            "",
            f"비슷했던 과거가 너무 적어 비율을 내지 않은 것이 {len(못낸것)}개 있습니다.",
        ]

    줄 += ["", "─────────────", "자세한 기록은 대시보드에 있습니다.",
          "https://utaxx.github.io/sdlab_trading/"]

    if 렌즈:
        줄 += ["", f"본 자료: {_렌즈설명(렌즈)}"]

    글 = "\n".join(줄)
    if len(글) > MAX_LEN:
        글 = 글[: MAX_LEN - 20] + "\n… (줄임)"
    return 글


def _렌즈설명(렌즈: str) -> str:
    """'렌즈 확장'만 적으면 무슨 말인지 알 수 없다. 무엇을 봤는지 적는다."""
    from muwon.market.series import LENSES, SERIES

    if 렌즈 not in LENSES:
        return 렌즈
    키들, 시작연도, _ = LENSES[렌즈]
    이름들 = ", ".join(SERIES[k].이름 for k in 키들 if k in SERIES)
    return f"{이름들} ({시작연도}년부터)"
