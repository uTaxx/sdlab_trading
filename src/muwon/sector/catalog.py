def sector_by_code(code: str) -> Sector:
    for s in CATALOG:
        if s.코드 == code:
            return s
    raise KeyError(f"모르는 섹터 코드: {code} (있는 것: {', '.join(s.코드 for s in CATALOG)})")


def all_members() -> list[tuple[str, SectorMember]]:
    """(섹터코드, 종목) 전부."""
    return [(s.코드, m) for s in CATALOG for m in s.종목]
