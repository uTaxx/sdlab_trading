"""텔레그램에서 온 글을 **명령으로 읽는다.** 여기서는 아무것도 실행하지 않는다.

## 왜 텔레그램에서 기준을 바꾸게 하나

기준을 고칠 일은 대개 **폰을 보고 있을 때** 생긴다. "오늘 후보가 다섯 개나
되네, 좀 줄이자" 같은 순간에 노트북을 열어야 하면 안 고치게 되고, 안 고치는
설정은 없는 것과 같다.

## 어떻게 받나. 서버 없이

봇에게 **웹훅을 걸지 않는다.** 웹훅을 받으려면 상시 도는 서버가 필요한데
이 저장소에는 그런 게 없다. 대신 워크플로가 주기적으로 `getUpdates`로
**물어보러 간다.** 늦어야 몇 분이고, 설정을 바꾸는 일에 몇 분은 늦어도 된다.

## 안전 규칙: 전부 '아무 일도 안 일어나는 쪽'으로

**① 정해 둔 사람만.** 시트/DB에 저장된 chat_id에서 온 것만 듣는다. 봇 이름을
아는 누구나 말을 걸 수 있고, 그 사람이 매매 기준을 바꾸면 안 된다.

**② 매매를 켜는 것은 여기서 못 한다.** `/끄기`는 되고 `/켜기`는 안 된다.
폰에서 손가락이 미끄러져 매매가 켜지는 일은 없어야 한다. 켜는 것은 시트나
대시보드에서, 화면을 보면서 한다.

**③ 아는 이름·아는 범위만.** 값 검증은 시트에서 읽을 때와 **같은 규칙**을
쓴다. 규칙이 두 벌이면 한쪽으로 들어온 값이 다른 쪽 기준을 어긴다.

**④ 모르는 말에는 안내만 한다.** 비슷한 명령을 추측해서 실행하지 않는다.
"아마 이 뜻이겠지"가 매매 기준을 바꾸면 안 된다.
"""

from __future__ import annotations

from dataclasses import dataclass

from muwon.settings.from_sheet import SettingsError, 값글자, 기준들, 기준표, 해석값

#: 같은 뜻의 명령을 한글·영어 둘 다 받는다. 폰에서 한글 입력이 귀찮은
#: 순간이 있고, 그때 못 쓰면 안 쓰게 된다.
별명 = {
    "/상태": "상태", "/status": "상태", "/기준": "상태", "/settings": "상태",
    "/설정": "설정", "/set": "설정",
    "/끄기": "끄기", "/stop": "끄기", "/정지": "끄기",
    "/켜기": "켜기", "/start": "켜기", "/시작": "켜기",
    "/승인": "승인", "/approve": "승인",
    "/도움": "도움", "/help": "도움", "/?": "도움",
}


@dataclass(frozen=True)
class 명령:
    종류: str            # 상태 / 설정 / 끄기 / 켜기 / 승인 / 도움 / 모름
    이름: str = ""       # 설정: 어느 기준인가
    값: object = None    # 설정: 검증까지 끝난 값
    글자: str = ""       # 설정: 사람이 적은 원래 글자
    종목들: tuple[str, ...] = ()   # 승인: 어떤 종목인가
    말: str = ""         # 못 알아들었을 때 돌려줄 말


def parse_command(글: str) -> 명령:
    """텔레그램 한 줄 → 명령. **네트워크도 상태도 없다.**

    규칙이 이 함수의 전부라, 구글이나 텔레그램에 붙지 않고 시험한다."""
    조각 = (글 or "").strip().split()
    if not 조각:
        return 명령("모름", 말="빈 글입니다. /도움 을 보내 보세요.")

    머리 = 조각[0].lower()
    종류 = 별명.get(머리)
    if 종류 is None:
        return 명령("모름", 말=f"모르는 명령입니다: {조각[0]}\n/도움 을 보내 보세요.")

    if 종류 in ("상태", "도움", "끄기", "켜기"):
        return 명령(종류)

    if 종류 == "승인":
        코드 = tuple(c for c in 조각[1:] if c.isdigit() and len(c) == 6)
        나머지 = [c for c in 조각[1:] if c not in 코드]
        if not 코드:
            return 명령("모름", 말="종목코드 여섯 자리를 같이 적어 주세요. 예: /승인 005930")
        if 나머지:
            # 절반만 알아듣고 실행하지 않는다. 무엇이 승인됐는지 헷갈린다.
            return 명령("모름", 말=f"종목코드로 안 보이는 것이 섞여 있습니다: {', '.join(나머지)}")
        return 명령("승인", 종목들=코드)

    # 설정
    if len(조각) < 3:
        return 명령("모름", 말="이름과 값을 같이 적어 주세요. 예: /설정 max_position_weight 12")
    이름, 글자 = 조각[1], 조각[2]
    b = 기준표.get(이름)
    if b is None:
        return 명령("모름", 말=f"모르는 기준입니다: {이름}\n/기준 을 보내면 목록이 나옵니다.")
    if not b.텔레그램가능:
        return 명령(
            "모름",
            말=f"{b.표시}는 텔레그램에서 못 바꿉니다. 시트나 대시보드에서 바꿔 주세요.\n"
               "끄는 것만은 /끄기 로 언제든 됩니다.",
        )
    try:
        값 = 해석값(b, 글자)
    except SettingsError as e:
        return 명령("모름", 말=f"{e}")
    return 명령("설정", 이름=이름, 값=값, 글자=글자)


def 도움말() -> str:
    return "\n".join([
        "■ 보낼 수 있는 말",
        "",
        "  /상태            지금 설정된 기준",
        "  /설정 <이름> <값>  기준 하나 바꾸기",
        "  /끄기            매매 즉시 중단 (언제든 됩니다)",
        "  /승인 005930     오늘 후보 중 이 종목을 사도 좋다",
        "                   (후보 알림에 붙은 버튼을 눌러도 같습니다)",
        "  /도움            이 글",
        "",
        "매수 후보 알림에는 ✅ 승인 버튼과 ❌ 거절 버튼이 붙어 옵니다.",
        "한 번 누르면 끝이고, 잘못 눌렀으면 반대쪽을 눌러 되돌리면 됩니다.",
        "",
        "매매를 다시 켜는 것은 여기서 안 됩니다. 시트나 대시보드에서 화면을",
        "보고 켜 주세요. 폰에서 손가락이 미끄러져 매매가 켜지면 안 되기",
        "때문입니다.",
        "",
        "바꿀 수 있는 이름:",
        *[f"  {b.이름}  ({b.표시}, 지금 기본 {b.기본})" for b in 기준들 if b.텔레그램가능],
    ])


def 바꾼말(이름: str, 옛것, 새것) -> str:
    b = 기준표[이름]
    return "\n".join([
        f"✅ **{b.표시}** {값글자(b, 옛것)} → **{값글자(b, 새것)}**",
        "",
        f"  {b.설명}",
        "",
        f"  왜 이 값이 중요한가: {b.왜}",
        "",
        "다음 실행부터 적용됩니다.",
    ])
