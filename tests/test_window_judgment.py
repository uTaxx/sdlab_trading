def test_작을수록_좋은_값은_부호를_뒤집어_둔다():
    """지침은 언제나 클수록 좋은 값을 돌려준다. 한 곳만 빠뜨리면 순위가
    조용히 뒤집힌다."""
    많이만료 = _잰것(만료=80.0)
    적게만료 = _잰것(만료=10.0)
    꺼짐 = ㅈ.찾기("expire_ratio")
    assert 꺼짐.값(적게만료) > 꺼짐.값(많이만료)

    흔들림큼 = _잰것(표준편차=9.0)
    흔들림작음 = _잰것(표준편차=1.0)
    ㅎ = ㅈ.찾기("window_std")
    assert ㅎ.값(흔들림작음) > ㅎ.값(흔들림큼)

    손절많음 = _잰것(손절=40.0)
    손절적음 = _잰것(손절=5.0)
    ㅅ = ㅈ.찾기("stop_ratio")
    assert ㅅ.값(손절적음) > ㅅ.값(손절많음)


