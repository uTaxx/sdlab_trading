    # 못 지운다. 그래서 사람에게 보이는 문장에만 쓰이는 말을 고른다.
    # 아래는 저장소 안에서만 쓰던 말이다. 코드에서는 걷어냈지만, 다시
    # 들어오는 것을 막으려고 목록은 남겨 둔다.
    안쓸말 = ["돌려 보기", "골라서 돌려", "언제 돌린", "지금 걸린 것",
             "따로 안 걺", "견주기", "견주다", "성적표", "돈이 나가는 결정",
             "제일 나빴던", "제일 아팠던", "한 주도 안 샀", "잘 벌고 있다는"]
    나온것 = [ㄱ for ㄱ in 안쓸말 if ㄱ in 코드 or ㄱ in 쪽]
    assert not 나온것, f"화면에 저장소 말이 남아 있습니다: {나온것}"


