def _지표(수익률=0.0, 낙폭=-10.0, 거래=40, 손익비=1.5, 샤프=1.0,
        승률=50.0, 노출=60.0) -> BacktestMetrics:
    return BacktestMetrics(
        total_return_pct=수익률, cagr_pct=수익률, max_drawdown_pct=낙폭,
        sharpe=샤프, sortino=샤프, profit_factor=손익비, expectancy_pct=0.5,
        win_rate_pct=승률, num_trades=거래, avg_holding_days=3.0,
        exposure_pct=노출, turnover=1.0,
    )


def _성적(구간들=None, **칸) -> 기간성적:
    return 기간성적(
        이름="3개월", 시작=date(2026, 6, 1), 끝=date(2026, 8, 31),
        metrics=_지표(**칸),
        구간들=list(구간들) if 구간들 is not None else [],
    )


