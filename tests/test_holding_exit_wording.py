"""보유 기간 만료로 팔 때의 매도 사유 문구.

## 무엇이 문제였나 (2026-09-02)

문구가 `f"보유 {상한}일 경과 청산"`이었다. 상한만 적고 실제로 며칠 들고
있었는지는 안 적었다. 둘이 같은 날은 문제가 없지만 **전략을 바꾸면 상한이
바뀐다.**

그날 아침 전략을 갭 상승 따라가기로 바꿨고 그 전략의 보유 상한은 1일이다.
5거래일 들고 있던 종목이 그 규칙에 걸려 팔렸는데 알림에는 "보유 1일 경과
청산"이라고 나갔다. 받는 사람은 하루 만에 팔렸다고 읽는다. 같은 메시지의
다른 칸에는 보유기간 5일이 찍혀 있어서 둘이 어긋났다.
"""

from __future__ import annotations

from muwon.risk.exits import 보유만료글


def test_상한과_실제가_같으면_한_번만_적는다():
    """평소가 이 경우다. 같은 숫자를 두 번 적으면 읽기만 번거롭다."""
    assert 보유만료글(5, 5) == "보유 상한 5거래일에 닿아 청산"


def test_상한보다_오래_들고_있었으면_둘_다_적는다():
    """전략을 바꿔 상한이 줄면 여기가 갈린다. 실제 보유일을 안 적으면
    하루 만에 팔린 것으로 읽힌다."""
    글 = 보유만료글(1, 5)
    assert "보유 상한 1거래일" in 글
    assert "실제 5거래일 보유" in 글


def test_실제_보유일이_문구에_그대로_들어간다():
    for 상한, 실제 in ((1, 3), (2, 7), (3, 20)):
        글 = 보유만료글(상한, 실제)
        assert f"{상한}거래일" in 글
        assert f"실제 {실제}거래일 보유" in 글


def test_사람에게_가는_글에_줄표를_안_쓴다():
    assert "—" not in 보유만료글(1, 5)
    assert "—" not in 보유만료글(5, 5)
