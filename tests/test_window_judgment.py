def _잰것(연환산=None, 플러스=None, 하위10=None, 표준편차=None,
        만료=0.0, 손절=0.0, 매매수=100, 낙폭=-10.0, 이름="t") -> ㅇ.잰것:
    ㄱ = ㅇ.구간재기([ㅇ.구간(date(2026, 1, 5), date(2026, 1, 9), 1.0, -1.0)] * 40, 20)
    ㄱ = replace(ㄱ, 연환산=연환산, 플러스비율=플러스, 하위10=하위10,
               표준편차=표준편차)
    매매 = ㅇ.매매성적(
        매매수=매매수,
        갈래비율={"손절": 손절, "익절": 0.0, "트레일링": 0.0,
                "매도신호": 100.0 - 만료 - 손절, "기간만료": 만료},
    )
    return ㅇ.잰것(
        전략=이름, 상한=20, 슬리피지=0.001, 매매대상="시험",
        시작일=date(2021, 1, 4), 끝일=date(2026, 9, 2), 잰날=date(2026, 9, 3),
        구간=ㄱ, 겹친구간=None, 매매=매매, 최대낙폭=낙폭,
    )


