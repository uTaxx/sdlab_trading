"""텔레그램으로 나가는 모든 글 맨 아래에 붙는 대시보드 링크.

알림을 폰에서 보다가 "지금 얼마야", "꺼야 하나"가 궁금해지면 결국 대시보드를
열어야 한다. 그때 주소를 찾아 헤매게 하지 않으려고 **글마다 링크를 달아 둔다.**

## 왜 한 군데서만 붙이나

내보내는 길이 셋이다 — 알림(TelegramNotifier), 버튼 달린 글(telegram_api.send),
버튼을 누른 뒤 갈아 끼우는 글(telegram_api.edit_text). 각자 붙이면 어느 하나를
빠뜨리고, 빠뜨린 줄도 모른다. 그래서 여기 한 곳에 두고 셋이 같이 쓴다.

## 하이퍼링크와 평문, 둘 다 만든다

주소를 그대로 적으면 글 끝이 긴 URL로 어수선하고 폰에서 두세 줄을 잡아먹는다.
이름에 주소를 걸면 한 줄이다. 그러려면 텔레그램의 HTML 모드를 켜야 하고,
그러면 본문에 `<`, `>`, `&`가 섞였을 때 텔레그램이 **글 전체를 거절한다.**

한 번 이렇게 만들었다가 되돌린 적이 있다(2026-08-24). 알림이 통째로 안 가는
쪽이 링크가 없는 쪽보다 훨씬 나쁘기 때문이다.

그래서 이번에는 둘 다 만든다. `하이퍼()`가 기본이고, 텔레그램이 거절하면
부르는 쪽이 `평문()`으로 한 번 더 보낸다. 실패해도 알림은 간다.

## 왜 붙이기 전에 떼나

버튼을 누르면 이미 보낸 글을 통째로 갈아 끼우는데, 그 원본에는 이미 링크가
붙어 있다. 떼지 않고 붙이면 누를 때마다 링크가 한 줄씩 쌓인다.

떼기가 받아야 할 모양이 셋이다.

1. 우리가 방금 만든 `<a href=...>` — 이스케이프도 같이 되돌린다. 안 그러면
   다시 붙일 때 `&amp;amp;`로 쌓인다.
2. 텔레그램이 돌려주는 것 — 버튼을 누르면 화면 글자만 넘어와서 주소 없이
   `📊 …` 한 줄이다.
3. 평문 — 이름 아래에 주소가 한 줄 더 있다.
"""

from __future__ import annotations

import html
import os
import re

#: 텔레그램 한 메시지 길이 제한.
텔레그램한도 = 4096

이름 = "주식매매 관리용 대시보드"
표시 = f"📊 {이름}"
#: 하이퍼링크일 때 보이는 글자. 눌러야 하는 것이라고 말해 준다.
누름표시 = f"📊 {이름} 바로가기"

#: GitHub Pages 주소(docs/대시보드_통합.md). 스트림릿에서 옮겨 왔다 —
#: 관리 지점이 다섯이라 답답하다는 말을 듣고 화면 하나로 모았다.
#: MUWON_DASHBOARD_URL 환경변수로 덮어쓸 수 있게 해 둔다. 배포 주소는
#: 우리가 정하는 값이 아니라서 코드를 고치지 않고도 갈아 끼워야 한다.
기본주소 = "https://utaxx.github.io/sdlab_trading/"

#: 우리가 만든 앵커. 되돌릴 때 이 모양을 먼저 찾는다.
_앵커 = re.compile(r'\s*<a href="[^"]*">[^<]*</a>\s*$')


def 주소() -> str:
    return (os.environ.get("MUWON_DASHBOARD_URL") or "").strip() or 기본주소


def 블록() -> str:
    """평문 꼬리. 길이 계산에도 이것을 쓴다 — 둘 중 긴 쪽이라 안전하다."""
    return f"{표시}\n{주소()}"


def 앵커() -> str:
    return f'<a href="{주소()}">{누름표시}</a>'


def 떼기(글: str) -> str:
    """이미 붙어 있는 링크를 걷어 낸다. 없으면 그대로 돌려준다."""
    글 = 글 or ""
    벗긴것 = _앵커.sub("", 글)
    if 벗긴것 != 글:
        # 우리가 만든 앵커였다. 본문 이스케이프도 같이 되돌린다.
        return html.unescape(벗긴것).rstrip()
    for 표식 in (누름표시, 표시):
        자리 = 글.rfind(표식)
        if 자리 >= 0:
            return 글[:자리].rstrip()
    return 글


def _자르기(몸통: str, 꼬리길이: int, 한도: int) -> str:
    """한도를 넘으면 **링크를 빼는 게 아니라 본문을 줄인다.**

    링크가 빠지면 "항상 달려 있다"는 약속이 조용히 깨지는데, 붙어 있다고
    믿는 쪽이 더 위험하다. 잘린 본문은 눈에 보이지만 없는 링크는 안 보인다."""
    남는자리 = 한도 - 꼬리길이
    if len(몸통) <= 남는자리:
        return 몸통
    말줄임 = "…"
    return 몸통[: max(남는자리 - len(말줄임), 0)] + 말줄임


def 평문(글: str, 한도: int = 텔레그램한도) -> str:
    """주소를 그대로 적는 꼬리. parse_mode 없이 보낼 때 쓴다."""
    꼬리 = "\n\n" + 블록()
    return _자르기(떼기(글), len(꼬리), 한도) + 꼬리


def 하이퍼(글: str, 한도: int = 텔레그램한도) -> str:
    """이름에 주소를 건 꼬리. **HTML 모드로 보내야 한다.**

    본문을 이스케이프한다. 종목명이나 오류 글에 `<`나 `&`가 섞이면
    텔레그램이 글 전체를 거절하는데, 그건 나중에야 알게 되는 실패다."""
    꼬리 = "\n\n" + 앵커()
    몸통 = html.escape(떼기(글), quote=False)
    # 이스케이프가 길이를 늘리므로 자르기는 이스케이프한 뒤에 한다.
    return _자르기(몸통, len(꼬리), 한도) + 꼬리


def 붙이기(글: str, 한도: int = 텔레그램한도) -> str:
    """예전 이름. 평문과 같다 — 부르는 쪽이 아직 남아 있어 남겨 둔다."""
    return 평문(글, 한도)
