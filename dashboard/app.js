  //: 그리면 어느 것이 지금 상태인지 알 수 없다. 순서는 기간 목록 순서다.
  function 최신만(줄들) {
    const 최신 = new Map();
    줄들.forEach((ㄱ) => {
      const 앞 = 최신.get(ㄱ.기간);
      if (!앞 || String(ㄱ.잰때) > String(앞.잰때)) 최신.set(ㄱ.기간, ㄱ);
    });
    const 차례 = 기간표.map((ㄱ) => ㄱ.이름);
    return [...최신.values()].sort(
      (ㄱ, ㄴ) => 차례.indexOf(ㄱ.기간) - 차례.indexOf(ㄴ.기간));
  }

