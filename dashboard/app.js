  /* 1순위부터, 큰 값이 위로. 동점 범위 안이면 다음 순위로 넘어간다.

     범위가 없으면 0.01%p 차이로 순위가 정해지고 2순위와 3순위가 영영 안
     쓰인다. 파이썬 window_judgment.기준.정렬키와 같은 규칙이다. */
  function 찾기줄세우기(줄들, 자리, 열쇠들) {
    const 칸만들기 = (줄) => 열쇠들.map((열쇠) => {
      const 값 = 찾기기준값(줄, 자리, 열쇠);
      if (값 === null) return [1, 0];
      const 폭 = Number((찾기지침(열쇠) || {}).비긴폭) || 0;
      return [0, -(폭 > 0 ? Math.round(값 / 폭) : 값)];
    });
    return [...줄들].sort((ㄱ, ㄴ) => {
      const 가 = 칸만들기(ㄱ);
      const 나 = 칸만들기(ㄴ);
      for (let i = 0; i < 가.length; i += 1) {
        if (가[i][0] !== 나[i][0]) return 가[i][0] - 나[i][0];
        if (가[i][1] !== 나[i][1]) return 가[i][1] - 나[i][1];
      }
      return 0;
    });
  }

