def test_어느_문장도_바꾸라고_말하지_않는다():
    """한 구간에서 제일 좋았던 것으로 옮기는 일이 곧 과최적화다.

    이 문장들은 화면과 텔레그램과 시트에 동시에 남는다. 한 군데서 새면
    나중에 어디를 고쳐야 하는지 알기 어렵다."""
    ㅅ = _순위([("지금것", 5.0, 40), ("다른것", 30.0, 40)])
    ㅎ = 후보내기(ㅅ)
    글들 = [후보글(ㅎ), 총평([ㅎ], ㅎ.등급)]
    for 글 in 글들:
        for 안쓸말 in ("바꾸세요", "바꾸는 것이 좋", "권장합니다", "추천", "갈아타"):
            assert 안쓸말 not in 글, f"{안쓸말!r}: {글}"
        assert "—" not in 글, f"줄표가 있습니다: {글}"


def test_후보글은_지금_전략의_자리도_같이_적는다():
    """후보만 적으면 지금 것이 얼마나 나쁜지 알 수 없다."""
