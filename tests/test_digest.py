def test_짧다():
    """예전 판은 60줄이었다. 매일 오는 알림이 그 길이면 안 읽는다."""
    글 = summarize(
        _상태(),
        [_전망(대상=f"섹터{ㄱ}", 상승확률=90.0, 기준선=50.0) for ㄱ in range(10)],
        date(2026, 8, 19), 렌즈="확장", 원시=_원시(), 지수=_지수(),
    )

    assert len(글) <= MAX_LEN
    assert len(글.splitlines()) <= 40, "40줄이 넘으면 폰에서 안 읽힌다"
