"""**장 마감 정산 알림이 읽히는가.**

받아 보는 사람이 이 글을 보고 물었다. *"이것만 보면 어떤 주식인지,
내용의 의미가 무엇인지 해석이 되니?"*

    066970 4주 → 12주 @ 118,241원
       슬리피지 -2.76% (판단가 121,600원)

안 된다. 무슨 주식인지(종목명이 없다), 산 건지 판 건지, 4→12가 좋은
일인지 나쁜 일인지, -2.76%가 유리한 건지 불리한 건지 — 한 줄도 알 수 없다.

그중 제일 위험한 것이 **슬리피지 부호**였다. 살 때 음수는 판단한 값보다
싸게 산 것이라 **유리한데**, 마이너스라 손해처럼 보인다. 부호를 그대로
찍지 않고 '싸게/비싸게'와 '유리/불리'로 적는다.
"""

from __future__ import annotations

from datetime import date

from muwon.execution.fill_settle import 보유고침, 주문고침
from scripts.settle_fills import _알림글


def _주문(**덮개) -> 주문고침:
    바탕 = {
        "order_id": "0000005963", "symbol": "066970", "옛수량": 4, "새수량": 12,
        "옛체결가": 118300.0, "새체결가": 118241.0, "판단가": 121600.0,
        "종목명": "엘앤에프", "방향": "BUY",
    }
    return 주문고침(**{**바탕, **덮개})


def _보유(**덮개) -> 보유고침:
    바탕 = {"symbol": "066970", "옛수량": 4, "새수량": 12,
            "옛진입가": 118300.0, "새진입가": 118241.0}
    return 보유고침(**{**바탕, **덮개})


def _글(주문들=None, 보유들=None, **kw) -> str:
    return _알림글(
        date(2026, 8, 25),
        주문들 if 주문들 is not None else [_주문()],
        보유들 if 보유들 is not None else [],
        **kw,
    )


# ── 슬리피지 부호 — 이 파일에서 제일 중요한 부분 ──────────────────────


def test_싸게_산_것은_유리라고_적는다():
    """-2.76%는 손해가 아니라 이득이다. 부호만 보면 정반대로 읽힌다."""
    글 = _글()

    assert "싸게 샀습니다 (유리)" in 글
    assert "-2.76" not in 글, "부호를 그대로 찍으면 손해로 읽힌다"


def test_비싸게_산_것은_불리라고_적는다():
    글 = _글([_주문(새체결가=125000.0)])

    assert "비싸게 샀습니다 (불리)" in 글


def test_싸게_판_것은_불리다():
    """같은 음수라도 파는 쪽에서는 뜻이 뒤집힌다."""
    주문 = _주문(방향="SELL", 새체결가=118241.0)

    assert 주문.유리한가 is False
    assert "싸게 팔았습니다 (불리)" in _글([주문])


def test_비싸게_판_것은_유리다():
    주문 = _주문(방향="SELL", 새체결가=125000.0)

    assert 주문.유리한가 is True
    assert "비싸게 팔았습니다 (유리)" in _글([주문])


def test_판단가를_모르면_잰_척하지_않는다():
    글 = _글([_주문(판단가=0.0)])

    assert "유리" not in 글 and "불리" not in 글


# ── 무슨 주식인지, 무슨 일이 있었는지 ────────────────────────────────


def test_종목코드만_찍지_않는다():
    """'066970'을 보고 엘앤에프를 떠올릴 수 있는 사람은 없다."""
    글 = _글()

    assert "엘앤에프(066970)" in 글


def test_종목명을_모르면_코드만이라도_적는다():
    글 = _글([_주문(종목명="")])

    assert "066970" in 글


def test_산_건지_판_건지_적는다():
    assert "매수" in _글()
    assert "매도" in _글([_주문(방향="SELL")])


def test_수량이_바뀐_것이_무슨_뜻인지_적는다():
    """'4주 → 12주'만 보면 더 산 것처럼 읽힌다. 실은 기록이 틀렸던 것이다."""
    글 = _글()

    assert "8주가 기록에서 빠져 있었습니다" in 글
    assert "새로 사거나 판 것은 없습니다" in 글


def test_수량이_줄면_체결이_안_된_것이라고_적는다():
    글 = _글([_주문(옛수량=12, 새수량=4)])

    assert "8주가 실제로는 체결되지 않았습니다" in 글


def test_총_얼마어치인지_적는다():
    """1주당 값만 있으면 얼마짜리 거래였는지 감이 안 온다."""
    글 = _글()

    assert "1,418,892원" in 글


# ── 그래서 무엇이 달라지나 ───────────────────────────────────────────


def test_손절선을_실제_가격으로_알려준다():
    """'진입가 118,241원'만으로는 언제 팔리는지 알 수 없다."""
    글 = _글(보유들=[_보유()], 손절비율=-0.05)

    assert "112,329원" in 글
    assert "5% 빠지면" in 글


def test_ATR_손절이면_고정_가격을_말하지_않는다():
    """켜져 있는데 고정 %로 적으면 화면이 거짓말을 한다."""
    글 = _글(보유들=[_보유()], 손절비율=-0.05, atr손절=True)

    assert "112,329원" not in 글
    assert "ATR" in 글


def test_지켜지지_않던_수량이_있었다는_것을_말한다():
    """이 도구가 있는 이유 자체다. 안 적으면 무엇이 위험했는지 안 남는다."""
    글 = _글(보유들=[_보유()])

    assert "손절이 안 걸려 있었습니다" in 글


def test_왜_이런_일이_생기는지_설명이_붙는다():
    글 = _글()

    assert "시장가 주문은 내는 순간 다 체결되지 않을 때가 있습니다" in 글


def test_텔레그램에_안_먹는_기호를_안_쓴다():
    """send_message에 parse_mode를 안 준다 — `**굵게**`가 그대로 도착한다."""
    글 = _글(보유들=[_보유()], 손절비율=-0.05)

    assert "**" not in 글


