"""측정 결과를 사람이 읽는 표로 찍는다.

## 왜 따로 두나

**결과 파일을 못 받는 자리가 있다.** 아티팩트를 내려받는 주소가 막혀
있으면 이 표가 유일하게 결과를 보는 길이다.

재는 스크립트와 쌓는 스크립트가 둘 다 이 표를 찍는다. 각자 한 벌씩
들고 있으면 한쪽만 고쳤을 때 같은 자료가 두 가지 표로 보인다. 그러면
어느 쪽이 맞는지 알 수가 없다.

## 무엇을 찍나

상한별 연환산 수익률, 상한별 기간 만료 비율, 상한별 매매 수, 슬리피지를
바꿨을 때의 변화, 그리고 판단 기준으로 세운 상한별 순위 다섯 개씩이다.
"""

from __future__ import annotations

from muwon.analysis import window_judgment as ㅍ
from muwon.analysis import window_perf as ㅇ


def _수글(값, 자리: int = 1, 폭: int = 8, 부호: bool = True) -> str:
    """못 잰 값은 줄표로. **0으로 채우지 않는다.**"""
    if 값 is None:
        return "—".rjust(폭)
    모양 = f"{{:{'+' if 부호 else ''}{폭}.{자리}f}}"
    return 모양.format(값)


def _구간값(줄: dict | None, 이름: str):
    ㄱ = (줄 or {}).get("구간") or {}
    return ㄱ.get(이름)


def _매매값(줄: dict | None, 이름: str):
    return ((줄 or {}).get("매매") or {}).get(이름)


def 요약찍기(줄들: list[dict], 상한들: list[int], 슬리피지들: list[float]) -> None:
    """로그에 표로 찍는다.

    **결과 파일을 못 받는 자리가 있다.** 아티팩트를 내려받는 주소가 막혀
    있으면 이 표가 유일하게 결과를 보는 길이다. 그래서 판단에 필요한 값만
    골라 로그에도 남긴다."""
    if not 줄들:
        return

    기준슬립 = 0.001 if 0.001 in 슬리피지들 else 슬리피지들[0]
    이름표: dict[str, str] = {}
    for ㄹ in 줄들:
        이름표.setdefault(ㄹ["전략"], ㄹ["이름"])

    찾기 = {(ㄹ["전략"], ㄹ["상한"], round(ㄹ["슬리피지"], 6)): ㄹ for ㄹ in 줄들}

    def 한줄(키: str, 뽑기) -> str:
        칸들 = [뽑기(찾기.get((키, 상한, round(기준슬립, 6)))) for 상한 in 상한들]
        return f"{이름표[키]:26}" + " ".join(칸들)

    머리 = f"{'전략':26}" + " ".join(f"{ㅅ:>7}일" for ㅅ in 상한들)

    print(f"\n\n■ 상한별 연환산 수익률 (슬리피지 {기준슬립 * 100:g}%)")
    print("  상한이 다른 전략을 같은 줄에 놓기 위한 값입니다. 짧을수록 크게 나옵니다.")
    print(머리)
    for 키 in 이름표:
        print(한줄(키, lambda ㄹ: _수글(_구간값(ㄹ, "연환산"))))

    print(f"\n■ 상한별 기간 만료 비율 (슬리피지 {기준슬립 * 100:g}%)")
    print("  높을수록 그 상한 안에 답이 안 나오는 전략입니다.")
    print(머리)
    for 키 in 이름표:
        print(한줄(키, lambda ㄹ: _수글(_매매값(ㄹ, "기간만료비율"), 0, 8, False)))

    print(f"\n■ 상한별 매매 수 (슬리피지 {기준슬립 * 100:g}%)")
    print(머리)
    for 키 in 이름표:
        print(한줄(키, lambda ㄹ: _수글(_매매값(ㄹ, "매매수"), 0, 8, False)))

    print("\n■ 슬리피지를 바꿨을 때 상한별 연환산의 가운데값")
    print("  짧은 상한일수록 매매가 잦아 슬리피지에 크게 깎입니다.")
    print(f"{'슬리피지':26}" + " ".join(f"{ㅅ:>7}일" for ㅅ in 상한들))
    for 슬립 in 슬리피지들:
        칸들 = []
        for 상한 in 상한들:
            값들 = sorted(
                ㄱ for ㄱ in
                (_구간값(찾기.get((키, 상한, round(슬립, 6))), "연환산")
                 for 키 in 이름표)
                if ㄱ is not None
            )
            칸들.append(_수글(값들[len(값들) // 2] if 값들 else None))
        print(f"{슬립 * 100:>6.2g}%{'':19}" + " ".join(칸들))

    print(f"\n■ 판단 기준으로 세운 순위 (슬리피지 {기준슬립 * 100:g}%)")
    print("  연환산 수익률 → 플러스 구간 비율 → 하위 10% 구간")
    print("  매수가 한 건도 없는 전략은 뺐습니다.")
    for 상한 in 상한들:
        후보 = [ㄹ for ㄹ in 줄들
              if ㄹ["상한"] == 상한 and abs(ㄹ["슬리피지"] - 기준슬립) < 1e-9
              and (_매매값(ㄹ, "매매수") or 0) > 0]
        if not 후보:
            print(f"\n  상한 {상한}일: 매수가 발생한 전략이 없습니다.")
            continue
        차례 = sorted(후보, key=lambda ㄹ: ㅍ.기본기준.정렬키(ㅇ.잰것으로(ㄹ)))
        print(f"\n  상한 {상한}일 (위 5개)")
        for i, ㄹ in enumerate(차례[:5], 1):
            print(
                f"   {i} {ㄹ['이름']:24}"
                f" 연환산{_수글(_구간값(ㄹ, '연환산'), 1, 8)}%"
                f" 플러스{_수글(_구간값(ㄹ, '플러스비율'), 0, 5, False)}%"
                f" 하위10{_수글(_구간값(ㄹ, '하위10'), 1, 7)}%"
                f" 매매{_수글(_매매값(ㄹ, '매매수'), 0, 6, False)}건"
                f" 만료{_수글(_매매값(ㄹ, '기간만료비율'), 0, 5, False)}%"
                f" 구간{_수글(_구간값(ㄹ, '구간수'), 0, 5, False)}"
            )
