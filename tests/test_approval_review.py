def test_한쪽이_비면_차이를_내지_않는다():
    """0으로 두면 '차이가 없다'로 읽힌다."""
    ㄱ = ㅅ.견주기(_여럿(3, 0, 5.0, 0.0), "d20")
    assert ㄱ.거절중앙값 is None
    assert ㄱ.차이 is None


