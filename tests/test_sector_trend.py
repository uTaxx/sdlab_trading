"""섹터가 최근에 어떻게 움직였나. 화면 '시장 트렌드' 탭이 읽는 숫자.

여기서 지키는 것이 넷이다.

1. 못 잰 구간을 0으로 채우지 않는다. 0%는 "안 움직였다"이고 None은
   "모른다"이다. 표에서 섞이면 구별할 방법이 없다.
2. 시장(코스피) 줄이 같이 나온다. 섹터만 보면 전부 빠진 날에 어느 섹터가
   나쁜 것처럼 읽힌다.
3. 종목이 모자라 지수를 못 만든 섹터도 줄은 남는다. 표에서 통째로 사라지면
   "그 섹터는 안 움직였나"로 읽힌다.
4. 시트 칸 순서가 창구·화면과 같다. 한 칸만 밀려도 표가 통째로 어긋나는데
   화면은 멀쩡히 그려진다.
"""

from __future__ import annotations

from datetime import date, timedelta

import numpy as np
import pandas as pd
import pytest

from muwon.analysis import sector_trend as ㅅ


def _시세(기울기: float, 씨앗: int, 날수: int = 120) -> pd.DataFrame:
    날들 = [date(2026, 4, 1) + timedelta(days=i) for i in range(날수)]
    r = np.random.default_rng(씨앗)
    값 = 100 * np.cumprod(1 + r.normal(기울기, 0.01, 날수))
    return pd.DataFrame({"trade_date": 날들, "close": 값})


class _종목:
    def __init__(self, 이름):
        self.name = 이름


def _섹터시세(섹터별: dict[str, tuple[float, int]]) -> dict:
    나온것 = {}
    for 코드, (기울기, 종목수) in 섹터별.items():
        나온것[코드] = {
            f"{코드}{i}": (_종목(f"{코드}{i}"), _시세(기울기, hash(코드) % 100 + i))
            for i in range(종목수)
        }
    return 나온것


이름표 = {"SEMI": "반도체", "BIO": "바이오", "ROBO": "로봇"}


def test_오르는_섹터와_빠지는_섹터가_갈린다():
    움 = ㅅ.재기(_섹터시세({"SEMI": (0.002, 5), "BIO": (-0.002, 5)}), 이름표)
    표 = {ㄱ.코드: ㄱ for ㄱ in 움}
    assert 표["SEMI"].값("d60") > 표["BIO"].값("d60")


def test_시장_줄이_맨_앞에_온다():
    시장 = _시세(0.0005, 7).set_index("trade_date")["close"]
    움 = ㅅ.재기(_섹터시세({"SEMI": (0.002, 5)}), 이름표, 시장)
    assert 움[0].코드 == ㅅ.시장코드
    assert 움[0].시장인가
    assert 움[0].이름 == "코스피"


def test_상대강도는_시장을_뺀_값이다():
    시장 = _시세(0.0005, 7).set_index("trade_date")["close"]
    움 = ㅅ.재기(_섹터시세({"SEMI": (0.002, 5)}), 이름표, 시장)
    섹터 = 움[1]
    시장줄 = 움[0]
    assert 섹터.상대강도 == pytest.approx(섹터.값("d60") - 시장줄.값("d60"), abs=1e-6)


def test_시장을_안_주면_상대강도가_없다():
    """0으로 채우면 시장과 같았다는 뜻이 된다. 그건 재지 않은 것과 다르다."""
    움 = ㅅ.재기(_섹터시세({"SEMI": (0.002, 5)}), 이름표)
    assert 움[0].상대강도 is None


def test_종목이_모자라면_줄은_남기고_값은_비운다():
    움 = ㅅ.재기(_섹터시세({"ROBO": (0.001, 2)}), 이름표)
    ㄱ = 움[0]
    assert ㄱ.코드 == "ROBO", "줄이 사라지면 그 섹터가 없는 것으로 읽힌다"
    assert ㄱ.종목수 == 2
    assert all(ㄱ.값(ㅋ) is None for ㅋ in ㅅ.구간표)


def test_봉이_모자란_구간은_None이다():
    """상장한 지 얼마 안 된 섹터는 60거래일을 못 잰다. 0%로 채우면
    안 움직인 것으로 읽힌다."""
    짧은것 = {"SEMI": {f"s{i}": (_종목(f"s{i}"), _시세(0.001, i, 날수=30))
                    for i in range(5)}}
    ㄱ = ㅅ.재기(짧은것, 이름표)[0]
    assert ㄱ.값("d5") is not None
    assert ㄱ.값("d60") is None


# ── 시트에 남기는 줄 ────────────────────────────────────────────


def test_시트_머리와_줄의_칸_수가_같다():
    움 = ㅅ.재기(_섹터시세({"SEMI": (0.002, 5)}), 이름표)
    for 줄 in ㅅ.줄들만들기(움, date(2026, 9, 4)):
        assert len(줄) == len(ㅅ.머리)


def test_못_잰_칸은_빈칸으로_적는다():
    움 = ㅅ.재기(_섹터시세({"ROBO": (0.001, 2)}), 이름표)
    줄 = ㅅ.줄들만들기(움, date(2026, 9, 4))[0]
    자리 = ㅅ.머리.index("60거래일%")
    assert 줄[자리] == "", "0으로 적으면 안 움직인 것과 섞인다"


def test_열쇠는_날짜와_섹터로_만든다():
    """같은 날 두 번 실행해도 줄이 두 벌 쌓이지 않는다."""
    움 = ㅅ.재기(_섹터시세({"SEMI": (0.002, 5)}), 이름표)
    줄 = ㅅ.줄들만들기(움, date(2026, 9, 4))[0]
    assert 줄[0] == "T2026-09-04|SEMI"
    assert 줄[1] == "2026-09-04"


def test_머리_순서가_창구_사본과_같다():
    """한 칸만 밀려도 표의 모든 줄이 어긋나는데 화면은 멀쩡히 그려진다."""
    import re
    from pathlib import Path

    사본 = (Path(__file__).resolve().parent.parent / "n8n"
          / "대시보드자료_섹터트렌드모양으로.js").read_text(encoding="utf-8")
    번호표 = {이름: int(번호) for 이름, 번호
            in re.findall(r"^\s+([가-힣A-Za-z0-9]+): (?:수\()?값\(ㅈ, (\d+)\)",
                          사본, re.MULTILINE)}
    쓰는이름 = {
        "잰때": "잰때", "코드": "섹터코드", "섹터": "섹터", "종목수": "종목수",
        "d5": "5거래일%", "d20": "20거래일%", "d60": "60거래일%",
        "상대강도": "상대강도%p", "못잰종목": "못잰종목",
    }
    for 창구이름, 시트이름 in 쓰는이름.items():
        assert 창구이름 in 번호표, f"창구 사본이 {창구이름}을 안 읽습니다"
        assert 번호표[창구이름] == ㅅ.머리.index(시트이름), (
            f"{창구이름}이 {번호표[창구이름]}번인데 시트에서는 "
            f"{ㅅ.머리.index(시트이름)}번입니다"
        )


