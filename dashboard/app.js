  function 자산요약글(점들) {
    const 값들 = 점들.map((ㄱ) => Number(ㄱ.평가액));
    const 처음 = 값들[0];
    const 지금 = 값들[값들.length - 1];
    const 바뀜 = 처음 > 0 ? (지금 / 처음 - 1) * 100 : null;
    let 꼭지 = 값들[0];
    let 최대낙폭 = 0;
    값들.forEach((v) => {
      if (v > 꼭지) 꼭지 = v;
      if (꼭지 > 0) 최대낙폭 = Math.min(최대낙폭, (v - 꼭지) / 꼭지 * 100);
    });
    const 지금낙폭 = 꼭지 > 0 ? (지금 - 꼭지) / 꼭지 * 100 : 0;
    return '<div class="곁말">'
      + `기록 ${점들.length}회차 · ${안전(자산날짜(점들[0].때))}부터 `
      + `${안전(자산날짜(점들[점들.length - 1].때))}까지<br>`
      + `평가금액 ${돈(처음)} → <b>${돈(지금)}</b>`
      + (바뀜 === null ? "" : ` (${퍼센트(바뀜)})`) + "<br>"
      + `기록 중 최대낙폭 <b>${퍼센트(최대낙폭)}</b> · `
      + `지금은 최고점 대비 ${퍼센트(지금낙폭)}`
      + "</div>";
  }

